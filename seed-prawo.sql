W sprawach nieuregulowanych w Kodeksie stosuje się jego przepisy ogólne odpowiednio.

Art. 249.
Do spraw wszczętych i niezakończonych przed dniem wejścia w życie Kodeksu stosuje się przepisy
dotychczasowe aż do zakończenia postępowania w danej instancji.

