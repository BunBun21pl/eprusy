DZIAŁ I
                                     PRZEPISY OGÓLNE

                           Rozdział 1. Zakres i zasady wykonywania

Art. 1.
Kodeks reguluje wykonywanie orzeczeń w postępowaniu karnym, w tym kar, środków karnych,
środków zabezpieczających i środków probacyjnych, oraz tymczasowego aresztowania.

Art. 2.
Kary i środki wykonuje się w sposób humanitarny, z poszanowaniem godności ludzkiej skazanego.
Zakazane są tortury oraz kary i traktowanie okrutne, nieludzkie lub poniżające (art. 13 Konstytucji).

Art. 3.
Skazany zachowuje prawa i wolności obywatelskie; ich ograniczenie może wynikać wyłącznie z
ustawy oraz z wydanego na jej podstawie orzeczenia.

Art. 4.
Wykonywanie kary ma na celu wzbudzanie w skazanym woli współdziałania w kształtowaniu jego
społecznie pożądanych postaw oraz ochronę społeczeństwa przed przestępczością.

Art. 5.
Wykonywanie kar i środków następuje z poszanowaniem zasady równości; niedopuszczalna jest
dyskryminacja skazanych z jakiejkolwiek przyczyny (art. 14 Konstytucji).

                       Rozdział 2. Organy postępowania wykonawczego

Art. 6.
Organami postępowania wykonawczego są: sąd, sędzia penitencjarny, dyrektor zakładu karnego i
aresztu śledczego, sądowy kurator zawodowy, Służba Więzienna oraz inne organy wskazane w
ustawie.

Art. 7.
Nadzór nad wykonywaniem kary pozbawienia wolności oraz środków związanych z pozbawieniem
wolności sprawuje sędzia penitencjarny.

Art. 8.
Sędzia penitencjarny w ramach nadzoru wizytuje zakłady karne i areszty śledcze, bada legalność i
prawidłowość wykonywania kary, może uchylać sprzeczne z prawem decyzje organów
wykonawczych oraz zarządzać zwolnienie osoby pozbawionej wolności bez podstawy prawnej.

Art. 9.
Sądem penitencjarnym jest sąd okręgowy.

Art. 10.

Prokurator czuwa nad praworządnością wykonywania kar i środków.

                                     Rozdział 3. Skazany

Art. 11.
Skazany ma prawo do informacji o swoich prawach i obowiązkach, do ochrony zdrowia oraz do
składania wniosków, skarg i próśb.

Art. 12.
Skazany ma obowiązek przestrzegania prawa, regulaminu oraz poleceń organów wykonawczych, a
także poszanowania praw innych osób.

Art. 13.
Skargi i prośby skazany może kierować do dyrektora zakładu oraz do sędziego penitencjarnego;
organy rozpatrują je bez zbędnej zwłoki.

Art. 14.
Na decyzję organu wykonawczego naruszającą jego prawa skazany może złożyć skargę do sądu
penitencjarnego; sąd może zaskarżoną decyzję uchylić albo zmienić.

                           Rozdział 4. Postępowanie wykonawcze

Art. 15.
Orzeczenie wykonuje się niezwłocznie po jego uprawomocnieniu, chyba że ustawa stanowi inaczej.

Art. 16.
Sąd może odroczyć albo przerwać wykonanie kary pozbawienia wolności w przypadkach
określonych w ustawie, w szczególności z powodu ciężkiej choroby albo ważnych względów
rodzinnych lub osobistych.

Art. 17.
1. Odroczenia oraz przerwy w wykonaniu kary udziela się na czas oznaczony; łączny czas przerw
nie może przekraczać okresu określonego w ustawie.
2. Jeżeli przerwa w wykonaniu kary trwała co najmniej rok, a skazany odbył wymaganą część kary,
sąd może warunkowo zwolnić go z odbycia reszty kary.

Art. 18.
Na postanowienia wydane w postępowaniu wykonawczym przysługuje zażalenie na zasadach
określonych w ustawie.

                                         DZIAŁ II
                          WYKONYWANIE KARY GRZYWNY

Art. 19.
Skazany uiszcza grzywnę w terminie 30 dni od dnia wezwania.

Art. 20.
Sąd może rozłożyć grzywnę na raty, jeżeli natychmiastowe jej uiszczenie byłoby dla skazanego
zbyt uciążliwe.

Art. 21.
Grzywny nieuiszczonej dobrowolnie dochodzi się w drodze egzekucji.

Art. 22.
W razie bezskuteczności egzekucji sąd zamienia grzywnę na pracę społecznie użyteczną.

Art. 23.
Jeżeli zamiana na pracę jest niemożliwa lub skazany uchyla się od jej wykonania, sąd zarządza
wykonanie zastępczej kary pozbawienia wolności.

                                         DZIAŁ III
               WYKONYWANIE KARY OGRANICZENIA WOLNOŚCI

Art. 24.
Karę ograniczenia wolności wykonuje się w miejscu zamieszkania lub zatrudnienia skazanego, pod
dozorem.

Art. 25.
Skazany wykonuje nieodpłatną, kontrolowaną pracę na cele społeczne w wymiarze określonym w
orzeczeniu.

Art. 26.
Wobec skazanego zatrudnionego można wykonywać orzeczone potrącenie części wynagrodzenia za
pracę na wskazany cel społeczny.

Art. 27.
Uchylanie się od odbywania kary ograniczenia wolności skutkuje zamianą jej na zastępczą karę
pozbawienia wolności.

                                         DZIAŁ IV
                WYKONYWANIE KARY POZBAWIENIA WOLNOŚCI

                             Rozdział 1. Cele i indywidualizacja

Art. 28.
Karę pozbawienia wolności wykonuje się w sposób sprzyjający readaptacji społecznej skazanego
oraz zapobieganiu powrotowi do przestępstwa.

Art. 29.

Wykonywanie kary indywidualizuje się, uwzględniając osobowość, wiek, płeć, stan zdrowia oraz
potrzeby skazanego.

                    Rozdział 2. Zakłady karne i systemy wykonywania

Art. 30.
Karę pozbawienia wolności wykonuje się w zakładach karnych typu zamkniętego, półotwartego
oraz otwartego.

Art. 31.
Karę wykonuje się w systemie programowanego oddziaływania, w systemie terapeutycznym albo w
systemie zwykłym.

Art. 32.
Kobiety odbywają karę oddzielnie od mężczyzn, a młodocianych oddziela się od dorosłych.

Art. 33.
Skazanego osadza się w zakładzie właściwym ze względu na typ zakładu oraz jego indywidualne
potrzeby i wymogi bezpieczeństwa.

                   Rozdział 3. Prawa skazanego pozbawionego wolności

Art. 34.
Skazany ma prawo do godnych warunków bytowych, odpowiedniego wyżywienia, odzieży oraz
warunków higienicznych.

Art. 35.
Powierzchnia celi mieszkalnej przypadająca na skazanego nie może być mniejsza niż 3 m².
Odstępstwo dopuszczalne jest wyłącznie przejściowo, w przypadkach i na zasadach określonych w
ustawie.

Art. 36.
Skazany ma prawo do ochrony zdrowia i świadczeń zdrowotnych.

Art. 37.
1. Skazany ma prawo do korespondencji, widzeń z osobami najbliższymi oraz do kontaktu
telefonicznego, na zasadach określonych w regulaminie.
2. Korespondencja skazanego z obrońcą oraz z organami ochrony praw nie podlega cenzurze ani
zatrzymaniu.

Art. 38.
Skazany ma prawo do wykonywania praktyk religijnych oraz korzystania z posług religijnych (art.
26 Konstytucji).

Art. 39.

Skazany ma prawo do nauki, informacji, dostępu do prasy i literatury oraz do udziału w zajęciach
kulturalno-oświatowych i sportowych.

Art. 40.
Kobiecie ciężarnej oraz matce małego dziecka zapewnia się szczególną opiekę; przy zakładach
mogą działać domy dla matki i dziecka.

Art. 41.
Skazanemu z niepełnosprawnością zapewnia się warunki uwzględniające jego stan.

Art. 42.
Ograniczenia praw skazanego stosuje się wyłącznie w zakresie niezbędnym dla zapewnienia
bezpieczeństwa i porządku.

                 Rozdział 4. Obowiązki, porządek i osadzeni niebezpieczni

Art. 43.
Skazany obowiązany jest przestrzegać regulaminu, dbać o porządek i czystość oraz poddawać się
niezbędnym czynnościom kontrolnym.

Art. 44.
Kontrolę osobistą oraz kontrolę pomieszczeń przeprowadza się w zakresie niezbędnym dla
bezpieczeństwa, z poszanowaniem godności skazanego.

Art. 45.
1. Osadzonego, który stwarza poważne zagrożenie dla bezpieczeństwa zakładu karnego albo dla
życia lub zdrowia innych osób, można zakwalifikować jako osadzonego niebezpiecznego.
2. Podstawą kwalifikacji może być w szczególności skazanie za zbrodnię określoną w Kodeksie
karnym ciężkim, kierowanie zorganizowaną grupą albo związkiem przestępczym, usiłowanie
ucieczki albo czynna napaść na funkcjonariusza lub inną osobę.

Art. 46.
O zakwalifikowaniu osadzonego jako niebezpiecznego oraz o cofnięciu tej kwalifikacji orzeka
komisja penitencjarna; decyzję doręcza się osadzonemu wraz z uzasadnieniem.

Art. 47.
1. Kwalifikację osadzonego jako niebezpiecznego weryfikuje się nie rzadziej niż co 3 miesiące.
2. Na decyzję komisji penitencjarnej osadzonemu przysługuje skarga do sądu penitencjarnego.

Art. 48.
1. Osadzonego niebezpiecznego osadza się w wyodrębnionym oddziale lub celi o pełnym
zabezpieczeniu, stosując wzmożone środki ochrony i kontroli.
2. Środki te stosuje się wyłącznie w zakresie niezbędnym dla bezpieczeństwa, z poszanowaniem
godności osadzonego (art. 13 Konstytucji).

Art. 49.

Kwalifikację osadzonego jako niebezpiecznego uchyla się niezwłocznie po ustaniu przyczyn, dla
których ją orzeczono.

                  Rozdział 5. Zatrudnienie skazanych i koszty utrzymania

Art. 50.
Skazanego zatrudnia się w miarę możliwości; praca skazanego sprzyja jego readaptacji i może być
wykonywana także na rzecz przedsiębiorstw państwowych oraz innych podmiotów.

Art. 51.
Za pracę skazanemu przysługuje wynagrodzenie proporcjonalne do wymiaru i rodzaju
wykonywanej pracy; wynagrodzenie za pełny wymiar pracy nie może być niższe od wynagrodzenia
minimalnego.

Art. 52.
1. Skazany, w miarę swoich możliwości, ponosi część kosztów swojego utrzymania w zakładzie
karnym.
2. W tym celu z wynagrodzenia za pracę skazanego dokonuje się potrąceń na pokrycie kosztów
utrzymania, na naprawienie szkody wyrządzonej przestępstwem oraz na Fundusz Pomocy
Postpenitencjarnej, na zasadach i w granicach określonych w ustawie.
3. Część wynagrodzenia pozostawia się do dyspozycji skazanego oraz gromadzi na okres po
zwolnieniu.

Art. 53.
Skazany jest obowiązany do nieodpłatnego wykonywania prac porządkowych na rzecz zakładu
karnego w niezbędnym wymiarze, określonym w regulaminie.

                          Rozdział 6. Nagrody i kary dyscyplinarne

Art. 54.
Za dobre zachowanie oraz postępy w readaptacji skazany może otrzymywać nagrody i ulgi, w tym
widzenia dodatkowe i przepustki.

Art. 55.
1. Za zawinione naruszenie porządku wobec skazanego wymierza się kary dyscyplinarne, z
poszanowaniem jego godności.
2. Katalog nagród oraz kar dyscyplinarnych określa ustawa i regulamin.

                    Rozdział 7. Nauczanie i przygotowanie do zwolnienia

Art. 56.
W zakładach karnych organizuje się nauczanie, szkolenie zawodowe oraz oddziaływania
sprzyjające readaptacji.

Art. 57.

Skazanego przygotowuje się do zwolnienia, w szczególności w okresie bezpośrednio je
poprzedzającym.

Art. 58.
1. Osobie zwalnianej udziela się pomocy postpenitencjarnej, w tym pomocy w znalezieniu
zatrudnienia i zakwaterowania.
2. Tworzy się Fundusz Pomocy Postpenitencjarnej.

             Rozdział 8. Odbywanie kary w systemie dozoru elektronicznego

Art. 59.
1. Skazany na karę pozbawienia wolności nieprzekraczającą wymiaru określonego w ustawie może,
za zezwoleniem sądu penitencjarnego, odbywać ją poza zakładem karnym w systemie dozoru
elektronicznego.
2. Skazany przebywa wówczas we wskazanym miejscu w wyznaczonych godzinach, a
wykonywanie kary kontroluje się za pomocą środków technicznych, w tym urządzeń
monitorujących.

Art. 60.
System dozoru elektronicznego prowadzi się we współpracy z ministrem właściwym do spraw
cyfryzacji, z zapewnieniem bezpieczeństwa systemu oraz ochrony danych osobowych.

Art. 61.
W razie naruszenia przez skazanego warunków odbywania kary w systemie dozoru elektronicznego
sąd penitencjarny uchyla zezwolenie i zarządza wykonanie kary w zakładzie karnym.

                   Rozdział 9. Kara dożywotniego pozbawienia wolności

Art. 62.
