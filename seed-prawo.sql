KSIĘGA PIERWSZA
                                          CZĘŚĆ OGÓLNA

                                       Tytuł I. Przepisy wstępne

Art. 1.
Kodeks reguluje stosunki cywilnoprawne między osobami fizycznymi i osobami prawnymi, oparte na
zasadzie równorzędności stron.

Art. 2.
Podstawą stosunków cywilnoprawnych jest autonomia woli; strony układają je swobodnie, o ile ich treść lub
cel nie sprzeciwiają się ustawie, zasadom współżycia społecznego ani naturze stosunku (swoboda umów).

Art. 3.
Własność prywatna podlega szczególnej ochronie prawnej; ograniczenia własności są dopuszczalne tylko na
podstawie ustawy i w niezbędnym zakresie.

Art. 4.
Uczestnicy obrotu obowiązani są działać w dobrej wierze; domniemywa się istnienie dobrej wiary.

Art. 5.
Nie można czynić ze swego prawa użytku, który byłby sprzeczny z jego społeczno-gospodarczym
przeznaczeniem lub z zasadami współżycia społecznego (zakaz nadużycia prawa).

Art. 6.
Ciężar udowodnienia faktu spoczywa na osobie, która z faktu tego wywodzi skutki prawne.

                                       Tytuł II. Osoby fizyczne

Art. 7.
Zdolność prawną, to jest zdolność do bycia podmiotem praw i obowiązków, ma każdy człowiek od chwili
urodzenia.

Art. 8.
Dziecko poczęte może nabywać prawa i przyjmować przysporzenia pod warunkiem, że urodzi się żywe.

Art. 9.
Pełną zdolność do czynności prawnych nabywa się z chwilą ukończenia 18 lat.

Art. 10.
1. Małoletni, który nie ukończył 14 lat, nie ma zdolności do czynności prawnych; może jednak zawierać
umowy powszechnie zawierane w drobnych bieżących sprawach życia codziennego.
2. Małoletni, który ukończył 14 lat, ma ograniczoną zdolność do czynności prawnych.

Art. 11.
Ograniczoną zdolność do czynności prawnych ma także osoba częściowo ubezwłasnowolniona; czynności
takiej osoby wymagają zgody jej przedstawiciela ustawowego, z wyjątkami określonymi w ustawie.

Art. 12.

Osoba niemająca zdolności do czynności prawnych albo o ograniczonej zdolności działa przez
przedstawiciela ustawowego albo za jego zgodą, na zasadach określonych w Kodeksie.

Art. 13.
Ze względu na wiek Kodeks wyróżnia: małoletniego poniżej 14 lat, małoletniego poniżej 17 lat, młodego
dorosłego poniżej 21 lat oraz osobę, która ukończyła 21 lat.

Art. 14.
Małoletni, który nie ukończył 14 lat:
   1) nie ponosi odpowiedzialności karnej;
   2) może zostać przesłuchany w charakterze świadka wyłącznie w odosobnionym pomieszczeniu, z
   udziałem biegłego psychologa, na zasadach określonych w Kodeksie postępowania karnego.

Art. 15.
Małoletni, który ukończył 14 lat, a nie ukończył 17 lat:
   1) może zostać przesłuchany w charakterze świadka na zasadach ogólnych;
   2) może odpowiadać przed sądem karnym wyłącznie za zgodą sądu rodzinnego.

Art. 16.
Młody dorosły, który ukończył 17 lat, a nie ukończył 21 lat:
   1) nie podlega sądowi rodzinnemu w sprawach karnych i wychowawczych;
   2) nie może być skazany na karę dożywotniego pozbawienia wolności ani na karę śmierci;
   3) jako oskarżony korzysta z obowiązkowego wsparcia pełnomocnika.

Art. 17.
Osoba, która ukończyła 21 lat, korzysta z pełni praw; może być skazana na karę dożywotniego pozbawienia
wolności oraz karę śmierci, a jako oskarżony może bronić się samodzielnie.

Art. 18.
1. Osoba, która wskutek choroby psychicznej lub niedorozwoju umysłowego nie jest w stanie kierować
swoim postępowaniem, może zostać całkowicie ubezwłasnowolniona.
2. Osoba, której stan wymaga pomocy w prowadzeniu jej spraw, lecz nie uzasadnia ubezwłasnowolnienia
całkowitego, może zostać częściowo ubezwłasnowolniona.
3. Ubezwłasnowolnienie orzeka sąd.

Art. 19.
Każdy może udzielić pełnomocnictwa opiekuńczego na wypadek przyszłej niezdolności do prowadzenia
swoich spraw, wskazując osobę uprawnioną do działania w jego imieniu.

Art. 20.
Miejscem zamieszkania osoby fizycznej jest miejscowość, w której osoba ta przebywa z zamiarem stałego
pobytu.

Art. 21.
1. Osobę, która zaginęła, można uznać za zmarłą, jeżeli upłynął okres określony w ustawie.
2. Domniemywa się, że zaginiony zmarł w chwili oznaczonej w orzeczeniu o uznaniu za zmarłego.

Art. 22.
Stan cywilny osoby oraz zdarzenia mające wpływ na jej stan rejestruje się w aktach stanu cywilnego.

Art. 23.

Każda osoba fizyczna ma imię i nazwisko; zasady ich nabycia oraz zmiany określa ustawa.

                                       Tytuł III. Dobra osobiste

Art. 24.
Dobra osobiste człowieka, w szczególności życie, zdrowie, wolność, cześć, godność, wizerunek, prywatność,
tajemnica korespondencji oraz ochrona danych osobowych, pozostają pod ochroną prawa cywilnego (art. 39
Konstytucji).

Art. 25.
Ten, czyje dobro osobiste zostaje zagrożone lub naruszone cudzym działaniem, może żądać zaniechania tego
działania oraz usunięcia jego skutków.

Art. 26.
W razie naruszenia dobra osobistego sąd może przyznać poszkodowanemu zadośćuczynienie pieniężne albo
zasądzić odpowiednią sumę na wskazany cel społeczny.

Art. 27.
Dobra osobiste osób prawnych podlegają ochronie odpowiednio do ich natury.

                                       Tytuł IV. Osoby prawne

Art. 28.
Osobą prawną jest jednostka organizacyjna, której ustawa przyznaje osobowość prawną.

Art. 29.
Osobami prawnymi są w szczególności: Skarb Państwa, jednostki samorządu terytorialnego,
przedsiębiorstwa państwowe, spółki mające osobowość prawną, spółdzielnie, fundacje oraz stowarzyszenia
rejestrowe.

Art. 30.
Skarb Państwa jest w stosunkach cywilnoprawnych podmiotem praw i obowiązków dotyczących mienia
państwowego, które podlega szczególnej ochronie (art. 136 Konstytucji).

Art. 31.
Osoba prawna powstaje z chwilą wpisu do właściwego rejestru, chyba że przepis szczególny stanowi
inaczej.

Art. 32.
Osoba prawna działa przez swoje organy w sposób przewidziany w ustawie i w opartym na niej statucie.

Art. 33.
Siedzibą osoby prawnej jest miejscowość, w której siedzibę ma jej organ zarządzający, chyba że statut
stanowi inaczej.

Art. 34.
Osoba prawna odpowiada za swoje zobowiązania całym swoim majątkiem; członkowie i wspólnicy
odpowiadają na zasadach określonych w ustawie właściwej dla danego rodzaju osoby prawnej.

Art. 35.
Osoba prawna odpowiada za szkodę wyrządzoną z winy jej organu.

Art. 36.
Ustanie osoby prawnej następuje w drodze likwidacji, na zasadach określonych w ustawie; szczegółową
organizację, ustrój oraz zasady odpowiedzialności poszczególnych rodzajów osób prawnych regulują ustawy
odrębne.

Art. 37.
Fundację ustanawia się dla realizacji celu społecznie lub gospodarczo użytecznego, z majątku
przeznaczonego na ten cel; stowarzyszenie jest dobrowolnym zrzeszeniem osób realizujących wspólny cel.

Art. 38.
Do jednostek organizacyjnych niebędących osobami prawnymi, którym ustawa przyznaje zdolność prawną,
stosuje się odpowiednio przepisy o osobach prawnych.

Art. 39.
W stosunkach cywilnoprawnych Skarb Państwa reprezentują organy państwowe oraz państwowe jednostki
organizacyjne w zakresie powierzonego im mienia.

Art. 40.
Przedsiębiorstwo jest zorganizowanym zespołem składników materialnych i niematerialnych przeznaczonym
do prowadzenia działalności gospodarczej.

Art. 41.
Przedsiębiorca działa pod firmą, którą ujawnia się we właściwym rejestrze; firma nie może wprowadzać w
błąd.

Art. 42.
Czynność prawna wywołuje nie tylko skutki w niej wyrażone, lecz również te, które wynikają z ustawy, z
zasad współżycia społecznego oraz z ustalonych zwyczajów.

                                            Tytuł V. Mienie

Art. 43.
Mieniem jest własność i inne prawa majątkowe.

Art. 44.
Rzeczami są przedmioty materialne; rzeczy dzielą się na nieruchomości oraz rzeczy ruchome.

Art. 45.
Nieruchomościami są części powierzchni ziemskiej stanowiące odrębny przedmiot własności (grunty), jak
również budynki trwale z gruntem związane lub ich części, jeżeli stanowią odrębny przedmiot własności.

Art. 46.
Częścią składową rzeczy jest wszystko, co nie może być od niej odłączone bez uszkodzenia lub istotnej
zmiany całości; część składowa nie może być odrębnym przedmiotem własności.

Art. 47.
Pożytkami rzeczy są jej płody oraz dochody, które rzecz przynosi na podstawie stosunku prawnego.

                                     Tytuł VI. Czynności prawne

Art. 48.

Czynność prawna dochodzi do skutku przez oświadczenie woli; oświadczenie woli należy tłumaczyć
zgodnie z zamiarem stron oraz celem czynności.

Art. 49.
Wola osoby dokonującej czynności prawnej może być wyrażona przez każde zachowanie ujawniające ją w
sposób dostateczny, w tym w postaci elektronicznej.

Art. 50.
Czynność prawna sprzeczna z ustawą albo mająca na celu obejście ustawy jest nieważna; nieważna jest także
czynność sprzeczna z zasadami współżycia społecznego.

Art. 51.
Jeżeli ustawa wymaga dla czynności prawnej formy szczególnej, czynność dokonana bez jej zachowania jest
nieważna tylko wtedy, gdy ustawa tak stanowi.

Art. 52.
Przeniesienie własności nieruchomości oraz inne czynności wskazane w ustawie wymagają formy aktu
notarialnego.

Art. 53.
Oświadczenie woli złożone drugiej stronie pod wpływem błędu co do treści czynności prawnej może być
uchylone, jeżeli błąd był istotny.

Art. 54.
Kto złożył oświadczenie woli pod wpływem bezprawnej groźby albo podstępu, może uchylić się od jego
skutków.

Art. 55.
Nieważne jest oświadczenie woli złożone przez osobę, która z jakichkolwiek powodów znajdowała się w
stanie wyłączającym świadome albo swobodne powzięcie decyzji.

Art. 56.
Czynność prawna może być uzależniona od zdarzenia przyszłego i niepewnego (warunek) albo od nadejścia
oznaczonego terminu.

Art. 57.
1. Czynności prawnej można dokonać przez przedstawiciela; skutki czynności dokonanej przez
przedstawiciela w granicach umocowania powstają bezpośrednio dla reprezentowanego.
2. Umocowanie do działania w cudzym imieniu opiera się na ustawie (przedstawicielstwo ustawowe) albo na
oświadczeniu reprezentowanego (pełnomocnictwo).

Art. 58.
Pełnomocnictwo ogólne obejmuje czynności zwykłego zarządu; do czynności przekraczających zwykły
zarząd potrzebne jest pełnomocnictwo określające ich rodzaj.

Art. 59.
Mocodawca może odwołać pełnomocnictwo w każdym czasie; zrzeczenie się odwołania jest dopuszczalne
tylko z przyczyn uzasadnionych treścią stosunku prawnego będącego podstawą pełnomocnictwa.

Art. 60.
Pełnomocnik może w każdym czasie wypowiedzieć pełnomocnictwo; jeżeli wypowiada je bez ważnego
powodu, odpowiada za szkodę wynikłą z wypowiedzenia.

Art. 61.
Prokura jest pełnomocnictwem udzielonym przez przedsiębiorcę, obejmującym umocowanie do czynności
związanych z prowadzeniem przedsiębiorstwa.

Art. 62.
Jeżeli jedna ze stron, wyzyskując przymusowe położenie, niedołęstwo lub niedoświadczenie drugiej,
zastrzega dla siebie świadczenie rażąco niewspółmierne, druga strona może żądać zmniejszenia swojego
świadczenia, zwiększenia należnego jej świadczenia, a w razie potrzeby — unieważnienia umowy (wyzysk).

Art. 63.
Czynność prawna dokonana przez osobę o ograniczonej zdolności do czynności prawnych bez wymaganej
zgody przedstawiciela ustawowego jest bezskuteczna do czasu jej potwierdzenia (bezskuteczność
zawieszona).

Art. 64.
Jeżeli nieważna czynność prawna odpowiada wymaganiom innej czynności prawnej, czynność ta jest ważna,
gdy z okoliczności wynika, że strony chciałyby tak postąpić, wiedząc o nieważności (konwersja).

Art. 65.
Kto jako pełnomocnik zawarł umowę bez umocowania lub z przekroczeniem jego zakresu, obowiązany jest
do naprawienia szkody, którą druga strona poniosła, chyba że umowę potwierdzi osoba, w której imieniu
została zawarta.

Art. 66.
Oświadczenie woli, które ma być złożone innej osobie, jest złożone z chwilą, gdy doszło do niej w taki
sposób, że mogła zapoznać się z jego treścią.

Art. 67.
Oświadczenie woli można odwołać, jeżeli odwołanie doszło do adresata jednocześnie z tym oświadczeniem
lub wcześniej.

Art. 68.
Do zachowania dokumentowej formy czynności prawnej wystarcza złożenie oświadczenia woli w postaci
dokumentu, w sposób umożliwiający ustalenie osoby składającej oświadczenie.

Art. 69.
Czynność prawna mająca datę pewną jest skuteczna względem osób trzecich od chwili, w której jej data stała
się urzędowo stwierdzona.

Art. 70.
Nieważne jest oświadczenie woli złożone drugiej stronie za jej zgodą dla pozoru; jeżeli pozorna czynność
ukrywa inną czynność, jej ważność ocenia się według właściwości czynności ukrytej.

Art. 71.
Pełnomocnictwo wygasa wskutek jego odwołania, śmierci mocodawcy lub pełnomocnika albo z upływem
czasu, na jaki zostało udzielone, chyba że zastrzeżono inaczej z przyczyn uzasadnionych treścią stosunku.

Art. 72.
Po wygaśnięciu umocowania pełnomocnik obowiązany jest zwrócić mocodawcy dokument pełnomocnictwa.

                                       Tytuł VII. Przedawnienie

Art. 73.
Roszczenia majątkowe ulegają przedawnieniu, z wyjątkami przewidzianymi w ustawie.

Art. 74.
1. Termin przedawnienia wynosi 6 lat, a dla roszczeń związanych z prowadzeniem działalności gospodarczej
oraz roszczeń o świadczenia okresowe — 3 lata.
2. Koniec terminu przedawnienia przypada na ostatni dzień roku kalendarzowego, chyba że termin jest
krótszy niż 2 lata.

Art. 75.
Bieg przedawnienia rozpoczyna się od dnia, w którym roszczenie stało się wymagalne.

Art. 76.
Bieg przedawnienia przerywa się przez każdą czynność przed sądem przedsięwziętą w celu dochodzenia
roszczenia oraz przez uznanie roszczenia; po przerwaniu biegnie ono na nowo.

Art. 77.
Po upływie terminu przedawnienia ten, przeciwko komu przysługuje roszczenie, może uchylić się od jego
zaspokojenia, chyba że zrzeka się korzystania z zarzutu przedawnienia.

Art. 78.
Bieg przedawnienia nie rozpoczyna się, a rozpoczęty ulega zawieszeniu, co do roszczeń między osobami
najbliższymi oraz przez czas trwania przeszkody uniemożliwiającej uprawnionemu dochodzenie roszczenia.

Art. 79.
Roszczenie właściciela o wydanie nieruchomości nie ulega przedawnieniu.

Art. 80.
Do terminów zawitych, z których upływem prawo wygasa, nie stosuje się przepisów o przedawnieniu.

                                        KSIĘGA DRUGA
                           WŁASNOŚĆ I INNE PRAWA RZECZOWE

                                           Tytuł I. Własność

Art. 81.
Własność jest prawem do korzystania z rzeczy i rozporządzania nią z wyłączeniem innych osób, w granicach
określonych przez ustawę i zasady współżycia społecznego.

Art. 82.
Właściciel może w szczególności pobierać pożytki i inne dochody z rzeczy oraz rozporządzać rzeczą.

Art. 83.
Własność prywatna jest podstawową i chronioną formą własności; jej pozbawienie (wywłaszczenie) jest
dopuszczalne wyłącznie na cele publiczne, na podstawie ustawy i za słusznym odszkodowaniem.

Art. 84.

Mienie państwowe stanowi własność Skarbu Państwa albo innych państwowych osób prawnych i podlega
szczególnej ochronie (art. 136 Konstytucji).

Art. 85.
W granicach określonych przez ustawę własność gruntu rozciąga się na przestrzeń nad i pod jego
powierzchnią, w zakresie odpowiadającym społeczno-gospodarczemu przeznaczeniu gruntu.

Art. 86.
Przeniesienie własności następuje przez umowę; umowa zobowiązująca do przeniesienia własności rzeczy
oznaczonej co do tożsamości przenosi własność, chyba że strony postanowiły inaczej lub ustawa stanowi
inaczej.

Art. 87.
Do przeniesienia własności rzeczy ruchomej oznaczonej co do gatunku potrzebne jest, obok umowy,
wydanie rzeczy.

Art. 88.
Nabywca w dobrej wierze może nabyć własność rzeczy ruchomej od osoby nieuprawnionej z chwilą jej
wydania, chyba że rzecz utracono wskutek przestępstwa.

Art. 89.
Kto znajduje rzecz zgubioną, obowiązany jest zawiadomić właściciela albo właściwy organ; znalazcy
przysługuje znaleźne.

Art. 90.
1. Współwłasność ma miejsce, gdy własność tej samej rzeczy przysługuje niepodzielnie kilku osobom.
2. Każdy ze współwłaścicieli może żądać zniesienia współwłasności.

Art. 91.
Właściciel może żądać od osoby, która włada jego rzeczą, jej wydania (roszczenie windykacyjne) oraz
przywrócenia stanu zgodnego z prawem i zaniechania naruszeń (roszczenie negatoryjne).

Art. 92.
Właściciel nieruchomości powinien przy wykonywaniu swego prawa powstrzymywać się od działań, które
zakłócałyby korzystanie z nieruchomości sąsiednich ponad przeciętną miarę wynikającą z miejscowych
stosunków (immisje).

Art. 93.
Jeżeli granice gruntów stały się sporne, dokonuje się rozgraniczenia na podstawie stanu prawnego, a gdy nie
można go stwierdzić — według ostatniego spokojnego stanu posiadania.

Art. 94.
1. Samoistny posiadacz w dobrej wierze nabywa własność pożytków odłączonych od rzeczy w czasie jego
posiadania.
2. Posiadacz w złej wierze obowiązany jest do wynagrodzenia za korzystanie z rzeczy oraz do zwrotu
pożytków.

Art. 95.
Kto wytworzył nową rzecz ruchomą z cudzych materiałów, staje się jej właścicielem, jeżeli wartość nakładu
pracy przewyższa wartość materiałów; w przeciwnym razie własność przypada właścicielowi materiałów.

Art. 96.

W razie połączenia lub pomieszania rzeczy ruchomych należących do różnych osób w sposób nierozłączny
powstaje współwłasność w częściach odpowiadających wartości rzeczy w chwili połączenia.

Art. 97.
Kto znalazł rzecz stanowiącą zabytek lub przedmiot o wartości naukowej albo artystyczną (skarb),
obowiązany jest wydać ją właściwemu organowi; przedmiot taki staje się własnością Skarbu Państwa, a
znalazcy przysługuje nagroda.

Art. 98.
Do rozporządzania rzeczą wspólną oraz do czynności przekraczających zakres zwykłego zarządu potrzebna
jest zgoda wszystkich współwłaścicieli.

Art. 99.
Zniesienie współwłasności może nastąpić przez podział rzeczy wspólnej, przez przyznanie rzeczy jednemu
ze współwłaścicieli z obowiązkiem spłaty pozostałych albo przez sprzedaż rzeczy i podział uzyskanej sumy.

Art. 100.
Samoistny posiadacz może żądać zwrotu nakładów koniecznych poczynionych na rzecz w zakresie, w jakim
nie znajdują pokrycia w korzyściach, które uzyskał z rzeczy.

Art. 101.
Własność rzeczy ruchomej niczyjej nabywa się przez jej objęcie w posiadanie samoistne (zawłaszczenie).

Art. 102.
Właściciel może wyzbyć się własności rzeczy ruchomej przez jej porzucenie z zamiarem wyzbycia się
własności.

Art. 103.
Przynależnościami są rzeczy ruchome potrzebne do korzystania z rzeczy głównej zgodnie z jej
przeznaczeniem; czynność prawna dotycząca rzeczy głównej odnosi skutek także względem przynależności.

Art. 104.
Jeżeli nieruchomość nie ma odpowiedniego dostępu do drogi publicznej, właściciel może żądać
ustanowienia za wynagrodzeniem służebności drogi koniecznej.

Art. 105.
Owoce spadłe z drzewa lub krzewu na grunt sąsiedni stanowią pożytki tego gruntu.

Art. 106.
Właściciel może żądać od samoistnego posiadacza w złej wierze, obok wydania rzeczy, wynagrodzenia za
korzystanie z niej oraz naprawienia szkody z powodu jej pogorszenia lub utraty (roszczenia uzupełniające).

Art. 107.
Nabywca nieruchomości nabywa wraz z nią prawa związane z jej własnością oraz obowiązany jest znosić
obciążenia ujawnione w księdze wieczystej.

Art. 108.
Domniemywa się, że udziały współwłaścicieli są równe; każdy współwłaściciel może rozporządzać swoim
udziałem bez zgody pozostałych.

Art. 109.

Jeżeli współwłaściciele nie mogą dokonać zniesienia współwłasności w drodze umowy, o sposobie
zniesienia rozstrzyga sąd.

Art. 110.
Zaspokojenie zastawnika z rzeczy obciążonej następuje w drodze sądowego postępowania egzekucyjnego,
chyba że ustawa przewiduje inny sposób.

Art. 111.
Hipoteka przymusowa może powstać na podstawie tytułu wykonawczego stwierdzającego wierzytelność.

                                         Tytuł II. Zasiedzenie

Art. 112.
1. Posiadacz nieruchomości niebędący jej właścicielem nabywa własność, jeżeli posiada nieruchomość
nieprzerwanie jako posiadacz samoistny przez 20 lat.
2. Jeżeli posiadacz uzyskał posiadanie w dobrej wierze, termin ten wynosi 10 lat.

Art. 113.
Posiadacz rzeczy ruchomej niebędący jej właścicielem nabywa własność, jeżeli posiada rzecz nieprzerwanie
jako posiadacz samoistny w dobrej wierze przez 3 lata.

              Tytuł III. Użytkowanie, służebności i inne prawa rzeczowe ograniczone

Art. 114.
Ograniczonymi prawami rzeczowymi są: użytkowanie, służebności, zastaw oraz hipoteka.

Art. 115.
Nie ustanawia się prawa użytkowania wieczystego.

Art. 116.
Użytkowanie polega na obciążeniu rzeczy prawem do jej używania i pobierania jej pożytków.

Art. 117.
1. Służebność gruntowa obciąża nieruchomość na rzecz każdoczesnego właściciela innej nieruchomości
(nieruchomości władnącej).
2. Służebność osobista przysługuje oznaczonej osobie fizycznej.

Art. 118.
Służebność przesyłu obciąża nieruchomość na rzecz przedsiębiorcy, który zamierza wybudować lub którego
własność stanowią urządzenia służące do przesyłania mediów.

Art. 119.
Zastaw obciąża rzecz ruchomą lub prawo w celu zabezpieczenia wierzytelności; zastawnik może zaspokoić
się z rzeczy obciążonej z pierwszeństwem przed innymi wierzycielami.

Art. 120.
Hipoteka obciąża nieruchomość w celu zabezpieczenia wierzytelności; wierzyciel hipoteczny może
dochodzić zaspokojenia z nieruchomości bez względu na to, czyją stała się własnością.

Art. 121.

Zastaw można ustanowić także w postaci zastawu rejestrowego, wpisanego do rejestru zastawów; ustrój
zastawu rejestrowego określa ustawa odrębna.

Art. 122.
Do przeniesienia ograniczonego prawa rzeczowego potrzebna jest umowa między uprawnionym a nabywcą
oraz, gdy prawo jest ujawnione w księdze wieczystej, wpis do tej księgi.

Art. 123.
Jeżeli kilka ograniczonych praw rzeczowych obciąża tę samą rzecz, prawo powstałe wcześniej ma
pierwszeństwo przed prawem powstałym później, chyba że ustawa stanowi inaczej.

Art. 124.
Ograniczone prawo rzeczowe wygasa, jeżeli przejdzie na właściciela rzeczy obciążonej albo jeżeli
uprawniony zrzeknie się prawa.

                                          Tytuł IV. Posiadanie

Art. 125.
Posiadaczem rzeczy jest zarówno ten, kto nią faktycznie włada jak właściciel (posiadacz samoistny), jak i
ten, kto włada nią jak użytkownik lub najemca (posiadacz zależny).

Art. 126.
Posiadanie jest chronione; posiadacz, którego posiadanie naruszono, może żądać przywrócenia stanu
poprzedniego i zaniechania naruszeń.

Art. 127.
Domniemywa się, że ten, kto rzeczą faktycznie włada, jest posiadaczem samoistnym oraz że posiadanie jest
zgodne ze stanem prawnym.

Art. 128.
Kto rzeczą faktycznie włada za kogo innego, jest dzierżycielem, a nie posiadaczem.

Art. 129.
Roszczenie o przywrócenie naruszonego posiadania wygasa, jeżeli nie było dochodzone w ciągu roku od
naruszenia.

Art. 130.
Służebność gruntowa może zostać nabyta przez zasiedzenie, jeżeli polega na korzystaniu z trwałego i
widocznego urządzenia.

Art. 131.
Służebność wygasa wskutek jej niewykonywania przez 10 lat.

                                        Tytuł V. Księgi wieczyste

Art. 132.
Dla nieruchomości prowadzi się księgi wieczyste w celu ustalenia stanu prawnego nieruchomości; ustrój i
prowadzenie ksiąg wieczystych określa ustawa odrębna.

Art. 133.

Domniemywa się, że prawo jawne z księgi wieczystej jest wpisane zgodnie z rzeczywistym stanem
prawnym; rękojmia wiary publicznej ksiąg wieczystych chroni nabywcę działającego w zaufaniu do ich
treści.

                                       KSIĘGA TRZECIA
                                         ZOBOWIĄZANIA

                                       Tytuł I. Przepisy ogólne

Art. 134.
Zobowiązanie polega na tym, że wierzyciel może żądać od dłużnika świadczenia, a dłużnik powinien
świadczenie spełnić.

Art. 135.
Świadczenie może polegać na działaniu albo na zaniechaniu.

Art. 136.
1. Zobowiązania pieniężne wyraża się i spełnia w walucie Republiki Pruskiej — marce pruskiej (art. 138–
139 Konstytucji).
2. Strony mogą zastrzec spełnienie świadczenia w walucie obcej, jeżeli ustawa nie stanowi inaczej.

Art. 137.
1. Jeżeli wysokość odsetek nie jest oznaczona, należą się odsetki ustawowe.
2. Maksymalna wysokość odsetek wynikających z czynności prawnej nie może przekraczać odsetek
maksymalnych określonych w ustawie; postanowienie przewyższające tę granicę jest w części nadwyżki
bezskuteczne (ochrona przed lichwą).

Art. 138.
Dłużnik powinien wykonać zobowiązanie zgodnie z jego treścią, w sposób odpowiadający jego celowi
społeczno-gospodarczemu oraz zasadom współżycia społecznego.

Art. 139.
Dłużnik obowiązany jest do staranności ogólnie wymaganej w stosunkach danego rodzaju (należyta
staranność).

Art. 140.
Miejscem spełnienia świadczenia jest miejsce oznaczone w umowie, a w jego braku — miejsce wynikające z
właściwości zobowiązania lub z ustawy.

Art. 141.
Jeżeli dłużnik nie spełnia świadczenia w terminie, popada w zwłokę; wierzyciel może żądać wykonania oraz
naprawienia szkody wynikłej ze zwłoki.

Art. 142.
1. Dłużnik obowiązany jest do naprawienia szkody wynikłej z niewykonania lub nienależytego wykonania
zobowiązania, chyba że jest ono następstwem okoliczności, za które nie ponosi odpowiedzialności.
2. Naprawienie szkody obejmuje poniesioną stratę oraz utracone korzyści.

Art. 143.

Strony mogą zastrzec, że naprawienie szkody wynikłej z niewykonania zobowiązania niepieniężnego nastąpi
przez zapłatę oznaczonej sumy (kara umowna).

Art. 144.
Wierzyciel może przenieść wierzytelność na osobę trzecią (przelew) bez zgody dłużnika, chyba że
sprzeciwiałoby się to ustawie, umowie lub właściwości zobowiązania.

Art. 145.
Za zgodą wierzyciela osoba trzecia może wstąpić w miejsce dłużnika, który zostaje z długu zwolniony
(przejęcie długu).

Art. 146.
Gdy dwie osoby są jednocześnie względem siebie dłużnikami i wierzycielami, każda z nich może potrącić
swoją wierzytelność z wierzytelności drugiej strony.

Art. 147.
Zobowiązanie wygasa przez spełnienie świadczenia, potrącenie, odnowienie, zwolnienie z długu oraz w
innych przypadkach określonych w ustawie.

Art. 148.
Jeżeli świadczenie stało się niemożliwe wskutek okoliczności, za które dłużnik nie odpowiada, zobowiązanie
wygasa; jeżeli dłużnik za nie odpowiada, wierzyciel może żądać naprawienia szkody.

Art. 149.
W razie zwłoki dłużnika w wykonaniu zobowiązania czynienia wierzyciel może, zachowując roszczenie o
naprawienie szkody, wykonać czynność na koszt dłużnika (wykonanie zastępcze).

Art. 150.
Zobowiązany do wydania cudzej rzeczy może ją zatrzymać do czasu zaspokojenia lub zabezpieczenia
przysługujących mu roszczeń o zwrot nakładów na rzecz (prawo zatrzymania).

Art. 151.
W razie istotnej zmiany siły nabywczej pieniądza po powstaniu zobowiązania sąd może, po rozważeniu
interesów stron i zasad współżycia społecznego, zmienić wysokość lub sposób spełnienia świadczenia
pieniężnego (waloryzacja sądowa).

Art. 152.
Jeżeli wierzyciel odmawia przyjęcia świadczenia albo jest nieobecny, dłużnik może zwolnić się z
zobowiązania przez złożenie przedmiotu świadczenia do depozytu sądowego.

Art. 153.
Spełnienie świadczenia pieniężnego następuje przez zapłatę sumy nominalnej, chyba że przepisy szczególne
albo umowa stanowią inaczej (zasada nominalizmu).

Art. 154.
Jeżeli dłużnik opóźnia się ze spełnieniem świadczenia pieniężnego, wierzyciel może żądać odsetek za
opóźnienie, choćby nie poniósł żadnej szkody.

Art. 155.
Jeżeli dłużnik jest zobowiązany w ten sposób, że wykonanie zobowiązania może nastąpić przez spełnienie
jednego z kilku świadczeń (zobowiązanie przemienne), wyboru świadczenia dokonuje dłużnik, chyba że
zastrzeżono inaczej.

Art. 156.
Wierzyciel dopuszcza się zwłoki, gdy bez uzasadnionej przyczyny odmawia przyjęcia zaofiarowanego
świadczenia; dłużnik może wówczas żądać naprawienia wynikłej stąd szkody.

Art. 157.
Zobowiązania niezupełnego nie można dochodzić przed sądem, jednak spełnione świadczenie nie podlega
zwrotowi (zobowiązanie naturalne).

Art. 158.
Dłużnik odpowiada jak za własne działanie za działania i zaniechania osób, którymi posługuje się przy
wykonaniu zobowiązania.

Art. 159.
W umowie wzajemnej świadczenia obu stron powinny być spełnione jednocześnie, chyba że z umowy,
ustawy albo orzeczenia wynika, że jedna ze stron obowiązana jest do wcześniejszego świadczenia.

Art. 160.
Jeżeli jedna ze stron umowy wzajemnej dopuszcza się zwłoki, druga strona może wyznaczyć jej odpowiedni
dodatkowy termin, a po jego bezskutecznym upływie — odstąpić od umowy.

Art. 161.
Roszczenie stwierdzone prawomocnym orzeczeniem sądu przedawnia się z upływem 6 lat, choćby termin
przedawnienia roszczeń tego rodzaju był krótszy.

Art. 162.
Jeżeli kara umowna jest rażąco wygórowana albo zobowiązanie zostało w znacznej części wykonane,
dłużnik może żądać jej zmniejszenia (miarkowanie kary umownej).

Art. 163.
Przelew wierzytelności staje się skuteczny wobec dłużnika z chwilą powzięcia przez niego wiadomości o
przelewie; do tego czasu spełnienie świadczenia do rąk zbywcy zwalnia dłużnika.

                            Tytuł II. Wielość dłużników albo wierzycieli

Art. 164.
1. Kilku dłużników może być zobowiązanych w ten sposób, że wierzyciel może żądać całości świadczenia
od wszystkich łącznie lub od każdego z osobna (solidarność dłużników).
2. Zaspokojenie wierzyciela przez któregokolwiek z dłużników zwalnia pozostałych.

Art. 165.
Dłużnik solidarny, który spełnił świadczenie, może żądać zwrotu od współdłużników w częściach na nich
przypadających (roszczenie regresowe).

Art. 166.
Kilku wierzycieli może być uprawnionych w ten sposób, że dłużnik może spełnić całe świadczenie do rąk
jednego z nich (solidarność wierzycieli).

                                Tytuł III. Umowy — przepisy ogólne

Art. 167.

Strony zawierające umowę mogą ułożyć stosunek prawny według swego uznania, byleby jego treść lub cel
nie sprzeciwiały się ustawie, zasadom współżycia społecznego ani naturze stosunku (zasada swobody
umów).

Art. 168.
Umowa zostaje zawarta przez zgodne oświadczenia woli stron; oświadczenie skierowane do drugiej strony
zawierające istotne postanowienia umowy stanowi ofertę.

Art. 169.
Oferta wiąże oferenta; przyjęcie oferty z zastrzeżeniem zmian uważa się za nową ofertę.

Art. 170.
Strony obowiązane są prowadzić negocjacje w dobrej wierze; kto rozpoczyna lub prowadzi negocjacje z
naruszeniem dobrej wiary, obowiązany jest naprawić szkodę.

Art. 171.
Ustalony przez jedną ze stron wzorzec umowy wiąże drugą stronę, jeżeli został jej doręczony przed
zawarciem umowy; postanowienia niejednoznaczne tłumaczy się na korzyść strony, która wzorca nie
ustalała.

Art. 172.
Postanowienia umowy zawieranej z konsumentem, nieuzgodnione indywidualnie, nie wiążą go, jeżeli
kształtują jego prawa i obowiązki w sposób sprzeczny z dobrymi obyczajami, rażąco naruszając jego
interesy (niedozwolone postanowienia umowne).

Art. 173.
Umowa przedwstępna, przez którą strona zobowiązuje się do zawarcia oznaczonej umowy, powinna określać
istotne postanowienia umowy przyrzeczonej.

Art. 174.
Można zastrzec w umowie, że dłużnik spełni świadczenie na rzecz osoby trzeciej; osoba trzecia może
wówczas żądać spełnienia świadczenia bezpośrednio.

Art. 175.
1. W braku odmiennego zastrzeżenia zadatek dany przy zawarciu umowy ma to znaczenie, że w razie
niewykonania umowy przez jedną ze stron druga strona może zachować zadatek albo żądać jego podwójnej
wysokości.
2. Strony mogą zastrzec prawo odstąpienia od umowy za zapłatą oznaczonej sumy (odstępne).

Art. 176.
1. Jeżeli z powodu nadzwyczajnej zmiany stosunków spełnienie świadczenia byłoby połączone z
nadmiernymi trudnościami albo groziłoby jednej ze stron rażącą stratą, czego strony nie przewidywały przy
zawarciu umowy, sąd może oznaczyć sposób wykonania zobowiązania, wysokość świadczenia lub orzec o
rozwiązaniu umowy (klauzula nadzwyczajnej zmiany stosunków).
2. Przepis stosuje się w szczególności do skutków wojny, kryzysu gospodarczego oraz gwałtownej zmiany
wartości pieniądza.

                                 Tytuł IV. Bezpodstawne wzbogacenie

Art. 177.

Kto bez podstawy prawnej uzyskał korzyść majątkową kosztem innej osoby, obowiązany jest do jej zwrotu
albo do zwrotu jej wartości.

Art. 178.
Kto spełnił świadczenie nienależne, może żądać jego zwrotu; świadczenie jest nienależne, jeżeli podstawa
świadczenia odpadła albo nie istniała.

Art. 179.
Kto bez zlecenia prowadzi cudzą sprawę, powinien działać zgodnie z prawdopodobną wolą osoby, której
sprawę prowadzi, oraz z należytą starannością (prowadzenie cudzych spraw bez zlecenia).

Art. 180.
Kto przez ogłoszenie publiczne przyrzekł nagrodę za wykonanie oznaczonej czynności, obowiązany jest
przyrzeczenia dotrzymać.

Art. 181.
Kto przekazuje drugiemu świadczenie osoby trzeciej, upoważnia tym samym odbiorcę do przyjęcia, a
przekazanego do spełnienia świadczenia na rachunek przekazującego (przekaz).

Art. 182.
Papiery wartościowe stwierdzają przysługujące uprawnionemu prawa majątkowe; do przeniesienia praw z
papieru wartościowego na okaziciela potrzebne jest jego wydanie.

                                     Tytuł V. Czyny niedozwolone

Art. 183.
Kto z winy swojej wyrządził drugiemu szkodę, obowiązany jest do jej naprawienia.

Art. 184.
Kto wyrządził szkodę czynem niedozwolonym, odpowiada niezależnie od istnienia między stronami
stosunku zobowiązaniowego.

Art. 185.
Naprawienie szkody obejmuje poniesioną stratę oraz utracone korzyści; następuje przez przywrócenie stanu
poprzedniego albo przez zapłatę odpowiedniej sumy pieniężnej.

Art. 186.
Osoba, która nie ukończyła 14 lat, nie ponosi odpowiedzialności za wyrządzoną szkodę; odpowiedzialność
ponosi osoba obowiązana do nadzoru nad nią, chyba że nadzorowi uczyniła zadość.

Art. 187.
Kto powierza wykonanie czynności drugiemu, odpowiada za szkodę wyrządzoną przez podwładnego
działającego na jego rachunek.

Art. 188.
1. Prowadzący na własny rachunek przedsiębiorstwo wprawiane w ruch za pomocą sił przyrody odpowiada
za szkodę wyrządzoną komukolwiek przez ruch przedsiębiorstwa, chyba że szkoda nastąpiła wskutek siły
wyższej albo wyłącznie z winy poszkodowanego (odpowiedzialność na zasadzie ryzyka).
2. Na tej samej zasadzie odpowiada posiadacz mechanicznego środka komunikacji za szkodę wyrządzoną
jego ruchem.

Art. 189.

Kto wytwarza produkt niebezpieczny, odpowiada za szkodę wyrządzoną przez ten produkt na zasadzie
ryzyka.

Art. 190.
Kto chowa zwierzę lub się nim posługuje, obowiązany jest do naprawienia wyrządzonej przez nie szkody.

Art. 191.
Za szkodę wyrządzoną wyrzuceniem, wylaniem lub spadnięciem przedmiotu z pomieszczenia odpowiada
ten, kto pomieszczenie zajmuje.

Art. 192.
Kilka osób, które wspólnie wyrządziły szkodę, odpowiada za nią solidarnie.

Art. 193.
1. W razie uszkodzenia ciała lub wywołania rozstroju zdrowia sąd może przyznać poszkodowanemu
odpowiednią sumę tytułem zadośćuczynienia za doznaną krzywdę.
2. Jeżeli poszkodowany utracił zdolność do pracy albo zwiększyły się jego potrzeby, może żądać renty.

Art. 194.
W razie śmierci poszkodowanego najbliżsi członkowie jego rodziny mogą żądać stosownego odszkodowania
oraz zadośćuczynienia za doznaną krzywdę.

Art. 195.
Roszczenie o naprawienie szkody wyrządzonej czynem niedozwolonym przedawnia się z upływem 3 lat od
dnia, w którym poszkodowany dowiedział się o szkodzie i o osobie obowiązanej do jej naprawienia, nie
później jednak niż z upływem 10 lat od zdarzenia.

Art. 196.
Skarb Państwa oraz jednostki samorządu terytorialnego odpowiadają za szkodę wyrządzoną przez niezgodne
z prawem działanie lub zaniechanie przy wykonywaniu władzy publicznej.

Art. 197.
Nie ponosi odpowiedzialności za szkodę ten, kto wyrządził ją działając w obronie koniecznej albo w stanie
wyższej konieczności.

Art. 198.
Kto namówił lub pomógł do wyrządzenia szkody, jak również ten, kto świadomie skorzystał z wyrządzonej
drugiemu szkody, odpowiada solidarnie ze sprawcą.

Art. 199.
Naprawienia szkody można dochodzić także wtedy, gdy nie można ustalić, który z kilku uczestników
zdarzenia szkodę wyrządził; uczestnicy odpowiadają wówczas solidarnie.

                                    Tytuł VI. Ochrona konsumenta

Art. 200.
Konsumentem jest osoba fizyczna dokonująca czynności prawnej niezwiązanej bezpośrednio z jej
działalnością gospodarczą lub zawodową.

Art. 201.
Konsument, który zawarł umowę na odległość lub poza lokalem przedsiębiorstwa, może od niej odstąpić bez
podania przyczyny w terminie określonym w ustawie.

Art. 202.
Przedsiębiorca obowiązany jest udzielić konsumentowi jasnej i rzetelnej informacji o towarze lub usłudze
oraz o warunkach umowy; szczegółową ochronę konsumenta określają ustawy odrębne.

                                     Tytuł VII. Umowy nazwane

Art. 203.
1. Przez umowę sprzedaży sprzedawca zobowiązuje się przenieść na kupującego własność rzeczy i wydać
mu rzecz, a kupujący zobowiązuje się rzecz odebrać i zapłacić cenę.
2. Sprzedawca jest odpowiedzialny względem kupującego, jeżeli rzecz sprzedana ma wadę (rękojmia).

Art. 204.
W razie stwierdzenia wady kupujący może żądać usunięcia wady lub wymiany rzeczy, obniżenia ceny albo
odstąpić od umowy, chyba że wada jest nieistotna.

Art. 205.
Sprzedawca lub inny podmiot może udzielić kupującemu gwarancji jakości rzeczy sprzedanej; obowiązki
gwaranta określa oświadczenie gwarancyjne.

Art. 206.
W sprzedaży konsumenckiej odpowiedzialność sprzedawcy wobec konsumenta z tytułu wad nie może być
wyłączona ani ograniczona.

Art. 207.
Przez umowę zamiany każda ze stron zobowiązuje się przenieść na drugą własność rzeczy w zamian za
zobowiązanie się do przeniesienia własności innej rzeczy.

Art. 208.
Przez umowę dostawy dostawca zobowiązuje się do wytworzenia i dostarczania rzeczy oznaczonych co do
gatunku oraz do ich dostarczania częściami albo periodycznie, a odbiorca — do ich odbierania i zapłaty
ceny.

Art. 209.
1. Przez umowę darowizny darczyńca zobowiązuje się do bezpłatnego świadczenia na rzecz obdarowanego
kosztem swego majątku.
2. Darczyńca może odwołać darowiznę, jeżeli obdarowany dopuścił się względem niego rażącej
niewdzięczności.

Art. 210.
Oświadczenie darczyńcy powinno być złożone w formie aktu notarialnego; darowizna wykonana staje się
jednak ważna mimo niezachowania tej formy.

Art. 211.
1. Przez umowę najmu wynajmujący zobowiązuje się oddać najemcy rzecz do używania przez czas
oznaczony lub nieoznaczony, a najemca zobowiązuje się płacić czynsz.
2. Najemca powinien używać rzeczy zgodnie z jej przeznaczeniem i umową.

Art. 212.
Bez zgody wynajmującego najemca nie może oddać rzeczy najętej osobie trzeciej do używania, chyba że
umowa stanowi inaczej.

Art. 213.
Wynajmujący może wypowiedzieć najem, jeżeli najemca dopuszcza się zwłoki z zapłatą czynszu albo używa
rzeczy w sposób sprzeczny z umową.

Art. 214.
Przez umowę dzierżawy wydzierżawiający zobowiązuje się oddać dzierżawcy rzecz do używania i
pobierania pożytków, a dzierżawca zobowiązuje się płacić czynsz.

Art. 215.
Przez umowę leasingu finansujący zobowiązuje się nabyć rzecz i oddać ją korzystającemu do używania albo
używania i pobierania pożytków przez czas oznaczony, a korzystający zobowiązuje się zapłacić
wynagrodzenie w ratach.

Art. 216.
Przez umowę użyczenia użyczający zezwala biorącemu na bezpłatne używanie rzeczy przez czas oznaczony
lub nieoznaczony.

Art. 217.
1. Przez umowę pożyczki dający pożyczkę zobowiązuje się przenieść na własność biorącego określoną ilość
pieniędzy albo rzeczy oznaczonych co do gatunku, a biorący zobowiązuje się zwrócić tę samą ilość.
2. Wysokość odsetek od pożyczki podlega ograniczeniu przez odsetki maksymalne.

Art. 218.
Przez umowę kredytu bank zobowiązuje się oddać do dyspozycji kredytobiorcy określoną kwotę środków
pieniężnych, a kredytobiorca zobowiązuje się do jej zwrotu wraz z odsetkami i prowizją.

Art. 219.
Przez umowę rachunku bankowego bank zobowiązuje się przechowywać środki pieniężne posiadacza
rachunku oraz przeprowadzać na jego zlecenie rozliczenia pieniężne.

Art. 220.
1. Przez umowę zlecenia przyjmujący zlecenie zobowiązuje się do dokonania określonej czynności prawnej
dla dającego zlecenie.
2. Przyjmujący zlecenie może bez uprzedniej zgody odstąpić od wskazanego sposobu wykonania, jeżeli
wymaga tego interes dającego zlecenie.

Art. 221.
Za wykonanie zlecenia należy się wynagrodzenie, chyba że z umowy lub okoliczności wynika, że
przyjmujący zobowiązał się wykonać je bez wynagrodzenia.

Art. 222.
1. Przez umowę o dzieło przyjmujący zamówienie zobowiązuje się do wykonania oznaczonego dzieła, a
zamawiający — do zapłaty wynagrodzenia.
2. Przyjmujący zamówienie odpowiada za wady dzieła.

Art. 223.
Przez umowę o roboty budowlane wykonawca zobowiązuje się do oddania przewidzianego w umowie
obiektu, wykonanego zgodnie z projektem i zasadami wiedzy technicznej, a inwestor — do zapłaty
wynagrodzenia.

Art. 224.

Przez umowę przechowania przechowawca zobowiązuje się zachować w stanie niepogorszonym rzecz
ruchomą oddaną mu na przechowanie.

Art. 225.
Przez umowę składu przedsiębiorca składowy zobowiązuje się do przechowania oznaczonych w umowie
rzeczy ruchomych za wynagrodzeniem.

Art. 226.
Przez umowę komisu przyjmujący zlecenie zobowiązuje się za wynagrodzeniem do kupna lub sprzedaży
rzeczy ruchomych na rachunek dającego zlecenie, lecz we własnym imieniu.

Art. 227.
Przez umowę agencyjną przyjmujący zlecenie zobowiązuje się do stałego pośredniczenia przy zawieraniu
umów na rzecz dającego zlecenie albo do zawierania ich w jego imieniu.

Art. 228.
1. Przez umowę przewozu przewoźnik zobowiązuje się do przewiezienia osób lub rzeczy za
wynagrodzeniem.
2. Do przewozów wykonywanych przez państwowe przedsiębiorstwa transportowe stosuje się przepisy
odrębne.

Art. 229.
Przez umowę spedycji spedytor zobowiązuje się za wynagrodzeniem do wysłania lub odbioru przesyłki albo
do organizacji jej przewozu.

Art. 230.
1. Przez umowę ubezpieczenia ubezpieczyciel zobowiązuje się spełnić określone świadczenie w razie zajścia
przewidzianego w umowie wypadku, a ubezpieczający zobowiązuje się zapłacić składkę.
2. Ubezpieczenie może być osobowe albo majątkowe.

Art. 231.
Ubezpieczyciel wolny jest od odpowiedzialności, jeżeli ubezpieczający wyrządził szkodę umyślnie.

Art. 232.
1. Przez umowę poręczenia poręczyciel zobowiązuje się względem wierzyciela wykonać zobowiązanie na
wypadek, gdyby dłużnik go nie wykonał.
2. Poręczyciel, który spłacił dług, wstępuje w prawa zaspokojonego wierzyciela.

Art. 233.
1. Przez umowę spółki cywilnej wspólnicy zobowiązują się dążyć do osiągnięcia wspólnego celu
gospodarczego przez działanie w sposób oznaczony.
2. Za zobowiązania spółki wspólnicy odpowiadają solidarnie.

Art. 234.
Przez umowę renty jedna ze stron zobowiązuje się względem drugiej do określonych świadczeń okresowych
w pieniądzu lub w rzeczach oznaczonych co do gatunku.

Art. 235.
1. Przez umowę dożywocia nabywca nieruchomości zobowiązuje się zapewnić zbywcy dożywotnie
utrzymanie w zamian za przeniesienie własności nieruchomości.
2. Umowa dożywocia wymaga formy aktu notarialnego.

Art. 236.
Przez ugodę strony czynią sobie wzajemne ustępstwa w zakresie istniejącego stosunku prawnego w celu
uchylenia niepewności lub sporu.

Art. 237.
Sprzedaż na raty to sprzedaż rzeczy ruchomej osobie fizycznej za cenę płatną w ratach, jeżeli rzecz zostaje
wydana kupującemu przed całkowitym zapłaceniem ceny.

Art. 238.
Sprzedawca może zastrzec własność rzeczy sprzedanej aż do uiszczenia całej ceny (zastrzeżenie prawa
własności).

Art. 239.
Strony mogą zastrzec prawo odkupu, na mocy którego sprzedawca może w oznaczonym terminie odkupić
rzecz sprzedaną.

Art. 240.
Prawo pierwokupu polega na tym, że oznaczonej osobie przysługuje pierwszeństwo kupna rzeczy na
wypadek, gdyby jej właściciel rzecz sprzedawał.

Art. 241.
Przez umowę kontraktacji producent rolny zobowiązuje się wytworzyć i dostarczyć oznaczoną ilość
produktów rolnych, a nabywca — do ich odbioru i zapłaty.

Art. 242.
Przez gwarancję bankową bank zobowiązuje się zapłacić beneficjentowi oznaczoną sumę po spełnieniu
przez niego warunków określonych w gwarancji.

Art. 243.
Przez akredytywę bank, działając na zlecenie klienta, zobowiązuje się zapłacić beneficjentowi po
przedstawieniu dokumentów zgodnych z warunkami akredytywy.

Art. 244.
Przez umowę faktoringu faktor nabywa wierzytelności przysługujące przedsiębiorcy wobec jego dłużników i
świadczy na jego rzecz usługi z tym związane.

Art. 245.
Przez umowę o pośrednictwo pośrednik zobowiązuje się do stworzenia sposobności do zawarcia umowy
albo do pośredniczenia przy jej zawarciu, a dający zlecenie — do zapłaty wynagrodzenia.

Art. 246.
Przez umowę licencyjną uprawniony z prawa własności intelektualnej zezwala na korzystanie z tego prawa
w oznaczonym zakresie, a licencjobiorca zobowiązuje się do zapłaty wynagrodzenia, chyba że licencja jest
nieodpłatna.

Art. 247.
Do umów o świadczenie usług, które nie są uregulowane innymi przepisami, stosuje się odpowiednio
przepisy o zleceniu.

Art. 248.
Do najmu lokalu mieszkalnego stosuje się przepisy o najmie ze zmianami wynikającymi z ochrony praw
lokatora, określonymi w ustawie odrębnej.

Art. 249.
Do dzierżawy gruntu rolnego stosuje się przepisy o dzierżawie z uwzględnieniem szczególnego charakteru
gospodarowania rolnego.

Art. 250.
Przez umowę o korzystanie z budynku lub pomieszczenia mieszkalnego w oznaczonym czasie w każdym
roku przedsiębiorca zobowiązuje się ustanowić na rzecz konsumenta takie prawo za wynagrodzeniem.

Art. 251.
Utrzymujący zarobkowo hotel lub podobny zakład odpowiada za utratę lub uszkodzenie rzeczy wniesionych
przez gościa, chyba że szkoda wynikła z właściwości rzeczy albo z siły wyższej.

Art. 252.
Darowizna na wypadek śmierci jest skuteczna, jeżeli obdarowany przeżył darczyńcę, a umowa została
zawarta w formie przewidzianej dla darowizny.

Art. 253.
Przez umowę renty ustanowionej odpłatnie uprawniony do renty przenosi na zobowiązanego prawo
majątkowe w zamian za zobowiązanie do świadczeń okresowych.

                                       KSIĘGA CZWARTA
                                                SPADKI

                                        Tytuł I. Przepisy ogólne

Art. 254.
Prawa i obowiązki majątkowe zmarłego przechodzą z chwilą jego śmierci na spadkobierców (spadek).

Art. 255.
Nie należą do spadku prawa i obowiązki ściśle związane z osobą zmarłego oraz prawa, które z chwilą
śmierci przechodzą na oznaczone osoby niezależnie od tego, czy są spadkobiercami.

Art. 256.
Spadkobierca nabywa spadek z chwilą otwarcia spadku, którą jest chwila śmierci spadkodawcy.

Art. 257.
Nabycie własności i praw majątkowych w drodze dziedziczenia oraz zapisu nie podlega opodatkowaniu.

Art. 258.
Nie może być spadkobiercą osoba, która nie żyje w chwili otwarcia spadku; niegodny dziedziczenia jest ten,
kto dopuścił się umyślnie ciężkiego przestępstwa przeciwko spadkodawcy.

Art. 259.
Spadkobierca ustawowy może przez umowę z przyszłym spadkodawcą, zawartą w formie aktu notarialnego,
zrzec się dziedziczenia po nim.

Art. 260.
Spadkobierca, który spadek przyjął, może zbyć spadek albo udział w spadku; umowa zbycia spadku wymaga
formy aktu notarialnego.

                                   Tytuł II. Dziedziczenie ustawowe

Art. 261.
Dziedziczenie ustawowe następuje, gdy spadkodawca nie powołał spadkobiercy albo gdy żadna z osób
powołanych nie chce lub nie może dziedziczyć.

Art. 262.
W pierwszej kolejności powołane są z ustawy do spadku dzieci spadkodawcy oraz jego małżonek;
dziedziczą oni w częściach równych, jednak część przypadająca małżonkowi nie może być mniejsza niż
jedna czwarta całości spadku.

Art. 263.
Jeżeli dziecko spadkodawcy nie dożyło otwarcia spadku, jego udział przypada jego zstępnym w częściach
równych.

Art. 264.
W braku zstępnych powołani są do spadku małżonek oraz rodzice spadkodawcy; w braku rodziców —
rodzeństwo spadkodawcy i jego zstępni.

Art. 265.
W braku małżonka i krewnych powołanych do dziedziczenia ustawowego spadek przypada gminie
ostatniego miejsca zamieszkania spadkodawcy, a gdy nie da się jej ustalić — Skarbowi Państwa.

                                          Tytuł III. Testament

Art. 266.
1. Spadkodawca może rozrządzić majątkiem na wypadek śmierci w testamencie.
2. Testament może zawierać rozrządzenie tylko jednego spadkodawcy i może być w każdej chwili odwołany.

Art. 267.
Sporządzić i odwołać testament może tylko osoba mająca pełną zdolność do czynności prawnych.

Art. 268.
Testament własnoręczny sporządza się w ten sposób, że spadkodawca napisze go w całości pismem ręcznym,
podpisze i opatrzy datą.

Art. 269.
Testament notarialny sporządza się w formie aktu notarialnego.

Art. 270.
1. Testament ustny można sporządzić, jeżeli istnieje obawa rychłej śmierci spadkodawcy albo jeżeli wskutek
szczególnych okoliczności zachowanie zwykłej formy testamentu jest niemożliwe lub utrudnione.
2. Spadkodawca oświadcza wówczas ostatnią wolę ustnie w obecności co najmniej trzech świadków.

Art. 271.
1. Testament wojskowy może sporządzić żołnierz oraz osoba towarzysząca Siłom Zbrojnym w czasie wojny,
mobilizacji lub działań zbrojnych, w uproszczonej formie określonej w ustawie.
2. Testament wojskowy traci moc po upływie oznaczonego czasu od ustania okoliczności, które uzasadniały
jego sporządzenie.

Art. 272.

Spadkodawca może w testamencie powołać spadkobiercę do całości lub części spadku oraz ustanowić kilku
spadkobierców.

Art. 273.
Spadkodawca może przez zapis zobowiązać spadkobiercę do spełnienia określonego świadczenia
majątkowego na rzecz oznaczonej osoby (zapisobiercy).

Art. 274.
Spadkodawca może w testamencie włożyć na spadkobiercę lub zapisobiercę obowiązek oznaczonego
działania lub zaniechania (polecenie).

Art. 275.
Spadkodawca może w testamencie pozbawić zstępnych, małżonka oraz rodziców zachowku
(wydziedziczenie), jeżeli uprawniony rażąco narusza obowiązki rodzinne albo dopuścił się względem
spadkodawcy ciężkiego przewinienia.

Art. 276.
Spadkodawca może w testamencie sporządzonym w formie aktu notarialnego postanowić, że oznaczona
osoba nabywa przedmiot zapisu z chwilą otwarcia spadku (zapis windykacyjny).

Art. 277.
Spadkodawca może powołać wykonawcę testamentu, który zarządza majątkiem spadkowym oraz wykonuje
zapisy i polecenia.

Art. 278.
Testament może być odwołany w całości lub w części przez sporządzenie nowego testamentu albo przez
jego zniszczenie z zamiarem odwołania.

                                         Tytuł IV. Zachowek

Art. 279.
1. Zstępnym, małżonkowi oraz rodzicom spadkodawcy, którzy byliby powołani do spadku z ustawy, należy
się zachowek.
2. Zachowek wynosi połowę wartości udziału spadkowego, który przypadłby uprawnionemu przy
dziedziczeniu ustawowym, a dla małoletniego lub trwale niezdolnego do pracy — dwie trzecie tej wartości.

Art. 280.
Uprawniony, którego nie powołano do spadku w wystarczającej części, może żądać od spadkobiercy zapłaty
sumy potrzebnej do pokrycia zachowku.

Art. 281.
Sąd może pozbawić uprawnionego prawa do zachowku, jeżeli uprawniony rażąco zaniedbywał swoje
obowiązki rodzinne wobec spadkodawcy.

                      Tytuł V. Przyjęcie i odrzucenie spadku oraz dział spadku

Art. 282.
1. Spadkobierca może przyjąć spadek bez ograniczenia odpowiedzialności za długi (przyjęcie proste),
przyjąć spadek z ograniczeniem tej odpowiedzialności do wartości spadku (przyjęcie z dobrodziejstwem
inwentarza) albo spadek odrzucić.

2. Oświadczenie składa się w terminie określonym w ustawie; brak oświadczenia oznacza przyjęcie z
dobrodziejstwem inwentarza.

Art. 283.
Spadkobierca, który przyjął spadek z dobrodziejstwem inwentarza, odpowiada za długi spadkowe tylko do
wartości ustalonego stanu czynnego spadku.

Art. 284.
Do chwili działu spadku spadkobiercy ponoszą solidarną odpowiedzialność za długi spadkowe.

Art. 285.
Dział spadku może nastąpić na podstawie umowy między spadkobiercami albo na mocy orzeczenia sądu.

Art. 286.
Sąd na wniosek osoby mającej w tym interes stwierdza nabycie spadku przez spadkobierców; stwierdzenie
nabycia spadku może nastąpić także w formie aktu poświadczenia dziedziczenia sporządzonego przez
notariusza.

Art. 287.
Jeżeli spadkobierca zmarł przed przyjęciem spadku, prawo do przyjęcia lub odrzucenia spadku przechodzi
na jego spadkobierców (transmisja).

Art. 288.
Spadkodawca może powołać spadkobiercę na wypadek, gdyby inna osoba powołana w pierwszej kolejności
nie chciała lub nie mogła dziedziczyć (podstawienie).

Art. 289.
Jeżeli jeden ze spadkobierców testamentowych nie chce lub nie może dziedziczyć, jego udział przypada
pozostałym spadkobiercom w stosunku do ich udziałów (przyrost), chyba że spadkodawca postanowił
inaczej.

Art. 290.
Od chwili otwarcia spadku do jego działu spadek stanowi wspólność majątku spadkowego, do której stosuje
się odpowiednio przepisy o współwłasności.

Art. 291.
Zapisobierca może żądać od obciążonego zapisem wykonania zapisu z chwilą, w której zapis stał się
wymagalny.

Art. 292.
Przy obliczaniu zachowku dolicza się do spadku darowizny uczynione przez spadkodawcę, na zasadach
określonych w ustawie.

Art. 293.
Roszczenie o zachowek przedawnia się z upływem 5 lat od ogłoszenia testamentu albo od otwarcia spadku.

Art. 294.
Uznania spadkobiercy za niegodnego dziedziczenia może żądać każdy, kto ma w tym interes; orzeka o tym
sąd.

Art. 295.

Na żądanie osoby mającej interes prawny sąd zarządza sporządzenie spisu inwentarza oraz zabezpieczenie
spadku.

Art. 296.
W braku rodzeństwa spadkodawcy i ich zstępnych powołani są do spadku dziadkowie spadkodawcy.

Art. 297.
Oświadczenie o przyjęciu lub odrzuceniu spadku składa się przed sądem albo notariuszem w terminie 6
miesięcy od dnia, w którym spadkobierca dowiedział się o tytule swego powołania.

Art. 298.
Spadkobierca, który spadek odrzucił, zostaje wyłączony od dziedziczenia, tak jakby nie dożył otwarcia
spadku.

Art. 299.
Jeżeli przy dziale spadku przedmioty spadkowe przyznano jednemu ze spadkobierców, sąd orzeka o
obowiązku dopłaty na rzecz pozostałych spadkobierców.

Art. 300.
Po dokonaniu działu spadku spadkobiercy ponoszą odpowiedzialność za długi spadkowe w stosunku do
wielkości udziałów.

