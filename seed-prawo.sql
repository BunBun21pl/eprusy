                                               CZĘŚĆ OGÓLNA

                                   Rozdział I. Zasady odpowiedzialności karnej

Art. 1.
Odpowiedzialności karnej podlega ten tylko, kto popełnia czyn zabroniony pod groźbą kary przez ustawę obowiązującą
w czasie jego popełnienia.

Art. 2.
Nie stanowi przestępstwa czyn zabroniony, którego społeczna szkodliwość jest znikoma.

Art. 3.
§1. Przestępstwa dzielą się na zbrodnie i występki.
§2. Zbrodnią jest czyn zabroniony zagrożony karą pozbawienia wolności na czas nie krótszy niż 3 lata; występkiem —
czyn zagrożony karą łagodniejszą.

Art. 4.
§1. Zbrodnię można popełnić tylko umyślnie.
§2. Występek można popełnić także nieumyślnie, jeżeli ustawa tak stanowi.

Art. 5.
§1. Czyn zabroniony popełniony jest umyślnie, gdy sprawca ma zamiar jego popełnienia, to jest chce go popełnić albo
przewidując możliwość jego popełnienia, na to się godzi.
§2. Czyn zabroniony popełniony jest nieumyślnie, gdy sprawca, nie mając zamiaru, popełnia go wskutek
niezachowania ostrożności wymaganej w danych okolicznościach, mimo że możliwość jego popełnienia przewidywał
albo mógł przewidzieć.

Art. 6.
Odpowiada za przestępstwo skutkowe popełnione przez zaniechanie ten tylko, na kim ciążył prawny, szczególny
obowiązek zapobiegnięcia skutkowi.

Art. 7.
§1. Czas popełnienia czynu określa czas działania lub zaniechania sprawcy.
§2. Miejscem popełnienia jest miejsce, w którym sprawca działał lub zaniechał działania, albo gdzie skutek nastąpił lub
miał nastąpić.

Art. 8.
Jeżeli w czasie orzekania obowiązuje ustawa inna niż w czasie popełnienia czynu, stosuje się ustawę nową; stosuje się
jednak ustawę poprzednio obowiązującą, jeżeli jest względniejsza dla sprawcy.

Art. 9.
§1. Kodeks stosuje się do sprawcy, który popełnił czyn na terytorium Republiki Pruskiej lub na pruskim statku wodnym
albo powietrznym.
§2. Kodeks stosuje się do obywatela pruskiego, który popełnił czyn za granicą, na zasadach określonych w ustawie.

                                   Rozdział II. Formy popełnienia przestępstwa

Art. 10.
Odpowiada za sprawstwo nie tylko ten, kto wykonuje czyn zabroniony sam albo wspólnie i w porozumieniu z inną
osobą, ale także ten, kto kieruje wykonaniem czynu przez inną osobę lub poleca jej wykonanie.

Art. 11.
Odpowiada za podżeganie, kto chcąc, aby inna osoba dokonała czynu zabronionego, nakłania ją do tego.

Art. 12.
Odpowiada za pomocnictwo, kto w zamiarze, aby inna osoba dokonała czynu zabronionego, ułatwia jego popełnienie.

Art. 13.
Każdy ze współdziałających odpowiada w granicach swojego zamiaru, niezależnie od odpowiedzialności pozostałych.

Art. 14.
§1. Odpowiada za usiłowanie, kto w zamiarze popełnienia czynu zabronionego swoim zachowaniem bezpośrednio
zmierza do jego dokonania, które jednak nie następuje.
§2. Sąd wymierza karę za usiłowanie w granicach zagrożenia przewidzianego dla danego przestępstwa.

Art. 15.
Nie podlega karze za usiłowanie, kto dobrowolnie odstąpił od dokonania albo zapobiegł skutkowi stanowiącemu
znamię czynu zabronionego (czynny żal).

Art. 16.
W przypadku usiłowania nieudolnego sąd może zastosować nadzwyczajne złagodzenie kary, a nawet odstąpić od jej
wymierzenia.

Art. 17.
Przygotowanie do przestępstwa jest karalne tylko wtedy, gdy ustawa tak stanowi.

                           Rozdział III. Okoliczności wyłączające odpowiedzialność

Art. 18.
Nie popełnia przestępstwa, kto w obronie koniecznej odpiera bezpośredni, bezprawny zamach na jakiekolwiek dobro
chronione prawem.

Art. 19.
W razie przekroczenia granic obrony koniecznej sąd może zastosować nadzwyczajne złagodzenie kary, a nawet
odstąpić od jej wymierzenia.

Art. 20.
Nie popełnia przestępstwa, kto działa w celu uchylenia bezpośredniego niebezpieczeństwa grożącego dobru
chronionemu prawem, jeżeli niebezpieczeństwa nie można inaczej uniknąć, a dobro poświęcone nie przedstawia
wartości oczywiście wyższej (stan wyższej konieczności).

Art. 21.
Nie popełnia przestępstwa umyślnego, kto pozostaje w usprawiedliwionym błędzie co do okoliczności stanowiącej
znamię czynu zabronionego.

Art. 22.
Nie popełnia przestępstwa, kto dopuszcza się czynu w usprawiedliwionej nieświadomości jego bezprawności.

Art. 23.
Nie popełnia przestępstwa, kto z powodu choroby psychicznej lub innego zakłócenia czynności psychicznych nie mógł
w czasie czynu rozpoznać jego znaczenia lub pokierować swoim postępowaniem (niepoczytalność).

Art. 24.

Jeżeli zdolność rozpoznania znaczenia czynu lub pokierowania postępowaniem była w znacznym stopniu ograniczona,
sąd może zastosować nadzwyczajne złagodzenie kary.

Art. 25.
Przepisów o niepoczytalności nie stosuje się, gdy sprawca wprawił się w stan odurzenia powodujący wyłączenie lub
ograniczenie poczytalności, które przewidywał albo mógł przewidzieć.

Art. 26.
Nie popełnia przestępstwa żołnierz lub funkcjonariusz, który wykonuje rozkaz, chyba że wykonując rozkaz umyślnie
popełnia czyn zabroniony, wiedząc, że rozkaz do tego zmierza.

                                Rozdział IV. Wiek i odpowiedzialność nieletnich

Art. 27.
Na zasadach określonych w Kodeksie odpowiada ten, kto popełnia czyn zabroniony po ukończeniu 17 lat.

Art. 28.
W szczególnie uzasadnionych przypadkach, za zgodą sądu rodzinnego, na zasadach określonych w Kodeksie może
odpowiadać również osoba, która nie ukończyła 17 lat, jeżeli przemawiają za tym okoliczności sprawy, stopień jej
rozwoju oraz właściwości i warunki osobiste.

Art. 29.
Wobec sprawcy, który w czasie czynu nie ukończył 18 lat, sąd kieruje się przede wszystkim tym, aby sprawcę
wychować; może zastosować nadzwyczajne złagodzenie kary.

Art. 30.
Wobec sprawcy młodocianego sąd wymierza karę, kierując się przede wszystkim jego wychowaniem, i może
zastosować nadzwyczajne złagodzenie kary, jeżeli przemawiają za tym jego właściwości i warunki osobiste.

                                                Rozdział V. Kary

Art. 31.
Karami są: grzywna, ograniczenie wolności, pozbawienie wolności oraz dożywotnie pozbawienie wolności.

Art. 32.
Karę oraz środek karny stosuje się z poszanowaniem godności człowieka. Niedopuszczalne są kary i środki okrutne,
nieludzkie lub poniżające.

Art. 33.
Niniejszy Kodeks nie przewiduje kary śmierci. Karę śmierci przewiduje wyłącznie Kodeks kary śmierci, na zasadach
określonych w art. 16 i art. 114 Konstytucji.

Art. 34.
§1. Grzywnę wymierza się w stawkach dziennych, określając liczbę stawek oraz wysokość jednej stawki.
§2. Ustalając wysokość stawki, sąd bierze pod uwagę dochody sprawcy, jego warunki osobiste, rodzinne i majątkowe.

Art. 35.
§1. Kara ograniczenia wolności polega na wykonywaniu nieodpłatnej, kontrolowanej pracy na cele społeczne albo na
potrąceniu części wynagrodzenia za pracę.
§2. W czasie odbywania kary sprawca nie może zmieniać miejsca stałego pobytu bez zgody sądu.

§3. Kara ograniczenia wolności może również polegać w przypadku przestępstw przeciwko zwierzętom na zakazie
posiadania zwierzęcia na czas nie krótszy niż rok.

Art. 36.
1. Kara pozbawienia wolności znajdująca się w kodeksie karnym trwa najkrócej miesiąc, najdłużej 30 lat; wymierza się
ją w miesiącach i latach.
2. Karę dożywotniego pozbawienia wolności orzeka się za przestępstwa, wobec których Kodeks tak stanowi.

Art. 37.
Jeżeli ustawa przewiduje możliwość wyboru rodzaju kary, sąd orzeka karę pozbawienia wolności tylko wtedy, gdy inna
kara lub środek karny nie może spełnić celów kary.

                                            Rozdział VI. Środki karne

Art. 38.
Środkami karnymi są w szczególności:
    1) pozbawienie praw publicznych;
    2) zakaz zajmowania określonego stanowiska, wykonywania zawodu lub prowadzenia działalności;
    3) zakaz prowadzenia pojazdów;
    4) zakaz przebywania w określonych miejscach, kontaktowania się lub zbliżania do określonych osób oraz nakaz
    opuszczenia lokalu zajmowanego wspólnie z pokrzywdzonym;
    5) przepadek przedmiotów i korzyści pochodzących z przestępstwa;
    6) obowiązek naprawienia szkody, nawiązka oraz świadczenie pieniężne;
    7) podanie wyroku do publicznej wiadomości.

Art. 39.
Sąd orzeka przepadek korzyści majątkowej osiągniętej z popełnienia przestępstwa albo jej równowartości.

Art. 40.
W razie skazania za przestępstwo, z którego sprawca osiągnął korzyść majątkową znacznej wartości, uważa się, że
mienie, które sprawca objął we władanie w okresie objętym postępowaniem, pochodzi z przestępstwa, chyba że
sprawca lub inna zainteresowana osoba wykaże inaczej (przepadek rozszerzony).

                                           Rozdział VII. Wymiar kary

Art. 41.
Sąd wymierza karę według swojego uznania, w granicach przewidzianych przez ustawę, bacząc, by jej dolegliwość nie
przekraczała stopnia winy, uwzględniając stopień społecznej szkodliwości czynu oraz cele zapobiegawcze i
wychowawcze.

Art. 42.
Sąd uwzględnia w szczególności motywację i sposób zachowania się sprawcy, rodzaj naruszonych obowiązków, rodzaj
i stopień naruszenia dóbr, właściwości i warunki osobiste sprawcy oraz jego zachowanie po popełnieniu przestępstwa.

Art. 43.
Jeżeli sprawca skazany za przestępstwo umyślne na karę pozbawienia wolności popełnia w ciągu 5 lat po odbyciu co
najmniej 6 miesięcy tej kary podobne przestępstwo umyślne, sąd może wymierzyć karę do górnej granicy zagrożenia
zwiększonej o połowę (recydywa).

Art. 44.

Wobec sprawcy, który był już uprzednio skazany w warunkach recydywy i ponownie popełnia przestępstwo umyślne,
sąd wymierza karę pozbawienia wolności powyżej dolnej granicy ustawowego zagrożenia, a może ją wymierzyć do
górnej granicy zwiększonej o połowę (recydywa wielokrotna).

Art. 45.
Jeżeli sprawca popełnia w krótkich odstępach czasu, w podobny sposób, dwa lub więcej przestępstw, zanim zapadł
pierwszy wyrok co do któregokolwiek z nich, sąd orzeka jedną karę na podstawie przepisu, którego znamiona każde z
nich wyczerpuje (ciąg przestępstw).

Art. 46.
Nadzwyczajne złagodzenie kary polega na wymierzeniu kary poniżej dolnej granicy ustawowego zagrożenia albo kary
łagodniejszego rodzaju, na zasadach określonych w Kodeksie.

Art. 47.
W przypadkach wskazanych w Kodeksie sąd może odstąpić od wymierzenia kary, orzekając środek karny.

                         Rozdział VIII. Środki związane z poddaniem sprawcy próbie

Art. 48.
Sąd może warunkowo umorzyć postępowanie karne, jeżeli wina i społeczna szkodliwość czynu nie są znaczne, a
okoliczności jego popełnienia nie budzą wątpliwości.

Art. 49.
1. Sąd może warunkowo zawiesić wykonanie orzeczonej kary pozbawienia wolności nieprzekraczającej 2 lat, na okres
próby nieprzekraczającej lat 5.
2. Zawieszając wykonanie kary, sąd może nałożyć na sprawcę obowiązki próby.

Art. 50.
Skazanego na karę pozbawienia wolności sąd może warunkowo zwolnić z odbycia reszty kary po odbyciu co najmniej
połowy kary, jeżeli jego postawa uzasadnia przekonanie, że będzie przestrzegał porządku prawnego.

                                  Rozdział IX. Zbieg przestępstw i kara łączna

Art. 51.
Jeżeli czyn wyczerpuje znamiona określone w dwóch albo więcej przepisach ustawy, sąd skazuje za jedno przestępstwo
na podstawie wszystkich zbiegających się przepisów.

Art. 52.
1. Jeżeli sprawca popełnił dwa lub więcej przestępstw, sąd wymierza kary jednostkowe, a następnie karę łączną.
2. Karę łączną wymierza się w granicach od najwyższej z kar jednostkowych do ich sumy, nie przekraczając granic
danego rodzaju kary.

Art. 53.
Dwa lub więcej zachowań podjętych w krótkich odstępach czasu, w wykonaniu z góry powziętego zamiaru, uważa się
za jeden czyn zabroniony (czyn ciągły).

                                       Rozdział X. Środki zabezpieczające

Art. 54.
Wobec sprawcy, który dopuścił się czynu w stanie niepoczytalności, sąd może orzec pobyt w zakładzie
psychiatrycznym, jeżeli istnieje wysokie prawdopodobieństwo, że popełni ponownie czyn o znacznej szkodliwości.

Art. 55.
Sąd może orzec wobec sprawcy terapię lub terapię uzależnień, jeżeli jest to niezbędne dla zapobieżenia ponownemu
popełnieniu przestępstwa.

Art. 56.
Środki zabezpieczające orzeka się tylko wtedy, gdy jest to konieczne, i tylko na czas niezbędny; podlegają one
okresowej kontroli sądu.

                                             Rozdział XI. Przedawnienie

Art. 57.
Karalność przestępstwa ustaje, jeżeli od czasu jego popełnienia upłynął okres określony w ustawie, zależny od wagi
przestępstwa i wysokości zagrożenia karą.

Art. 58.
Karalność przestępstwa ustaje, gdy od czasu jego popełnienia upłynęło:
    1) 30 lat — gdy czyn stanowi zbrodnię zagrożoną karą dożywotniego pozbawienia wolności;
    2) 20 lat — gdy czyn stanowi inną zbrodnię;
    3) 15 lat — gdy czyn stanowi występek zagrożony karą pozbawienia wolności przekraczającą 5 lat;
    4) 10 lat — gdy czyn stanowi występek zagrożony karą pozbawienia wolności przekraczającą 3 lata;
    5) 5 lat — w pozostałych przypadkach.

Art. 59.
Nie ulega przedawnieniu karalność zbrodni określonych w Kodeksie karnym ciężkim, w szczególności zbrodni wojny
napastniczej, ludobójstwa oraz zbrodni przeciwko ludzkości.

Art. 60.
Przedawnienie wykonania kary następuje po upływie okresu określonego w ustawie, liczonego od uprawomocnienia się
wyroku.

                                          Rozdział XII. Zatarcie skazania

Art. 61.
1. Skazanie ulega zatarciu z mocy prawa po upływie okresu określonego w ustawie.
2. Z chwilą zatarcia skazanie uważa się za niebyłe, a wpis o skazaniu usuwa się z rejestru.

                                 Rozdział XIII. Objaśnienie wyrażeń ustawowych

Art. 62.
W rozumieniu Kodeksu:
    1) czynem zabronionym jest zachowanie o znamionach określonych w ustawie karnej;
    2) funkcjonariuszem publicznym jest osoba pełniąca funkcje w organach władzy publicznej oraz inne osoby
    wskazane w ustawie;
    3) mieniem znacznej wartości jest mienie o wartości przekraczającej próg określony w ustawie;
    4) groźbą bezprawną jest groźba popełnienia przestępstwa lub spowodowania postępowania karnego albo
    rozgłoszenia wiadomości uwłaczającej czci;
    5) dokumentem jest każdy przedmiot lub zapis stanowiący dowód prawa, stosunku prawnego lub okoliczności
    mającej znaczenie prawne;
    6) korzyścią majątkową jest korzyść dla siebie lub dla kogo innego;
    7) młodocianym jest sprawca, który w czasie czynu nie ukończył 21 lat.

                            Rozdział XIV. Stosunek do Kodeksu karnego ciężkiego

Art. 63.
1. Zbrodnie określone w Kodeksie karnym ciężkim podlegają przepisom tego kodeksu.
2. W zakresie nieuregulowanym w Kodeksie karnym ciężkim stosuje się przepisy części ogólnej niniejszego Kodeksu.

Art. 64.
Przestępstwo ściga się z urzędu, chyba że ustawa przewiduje ściganie na wniosek pokrzywdzonego albo z oskarżenia
prywatnego.

                                         CZĘŚĆ SZCZEGÓLNA

                             Rozdział XV. Przestępstwa przeciwko życiu i zdrowiu

Art. 65. [Zabójstwo]
§1. Kto zabija człowieka, jeżeli czyn nie stanowi zbrodni określonej w Kodeksie karnym ciężkim, podlega karze
pozbawienia wolności na czas nie krótszy niż 12 lat bądź karze dożywotniego pozbawienia wolności.
§2. Kto zabija człowieka ze szczególnym okrucieństwem, jeżeli czyn nie stanowi zbrodni określonej w Kodeksie
karnym ciężkim, podlega karze pozbawienia wolności na czas nie krótszy niż 25 lat bądź karze dożywotniego
pozbawienia wolności

Art. 66. [Zabójstwo pod wpływem wzburzenia]
Kto zabija człowieka pod wpływem silnego wzburzenia usprawiedliwionego okolicznościami, podlega karze
pozbawienia wolności od roku do lat 10.

Art. 67. [Zabójstwo na żądanie]
Kto zabija człowieka na jego żądanie i pod wpływem współczucia dla niego, podlega karze pozbawienia wolności od 3
miesięcy do lat 5.

Art. 68. [Nieumyślne spowodowanie zabójstwa]
Kto nieumyślnie powoduje śmierć człowieka, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 69. [Doprowadzenie człowieka do targnięcia na życie]
Kto namową lub przez udzielenie pomocy doprowadza człowieka do targnięcia się na własne życie, podlega karze
pozbawienia wolności od 3 miesięcy do lat 5.

Art. 70. [Spowodowanie uszczerbku na zdrowiu]
§1. Kto powoduje ciężki uszczerbek na zdrowiu w postaci pozbawienia człowieka wzroku, słuchu, mowy, zdolności
płodzenia albo innego ciężkiego kalectwa lub choroby zagrażającej życiu, podlega karze pozbawienia wolności od lat 3
do lat 15.
§2. Kto powoduje średni uszczerbek na zdrowiu w postaci naruszenia czynności narządu ciała lub rozstrój zdrowia
trwający dłużej niż 7 dni, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.
§3. Kto powoduje lekki uszczerbek na zdrowiu w postaci naruszenia czynności narządu lub rozstrój trwający nie dłużej
niż 7 dni, podlega karze grzywny, ograniczenia wolności bądź pozbawienia wolności do lat 2.

Art. 71. [Naruszenie czynności narządu ciała]
Kto powoduje naruszenie czynności narządu ciała lub rozstrój zdrowia inny niż ciężki, podlega grzywnie, karze
ograniczenia wolności albo pozbawienia wolności do lat 5.

Art. 72. [Bójka]

Kto bierze udział w bójce lub pobiciu, w którym naraża się człowieka na bezpośrednie niebezpieczeństwo utraty życia
albo ciężkiego uszczerbku na zdrowiu, podlega karze pozbawienia wolności do lat 3.

Art. 73. [Narażanie na bezpośrednie niebezpieczeństwo]
Kto naraża człowieka na bezpośrednie niebezpieczeństwo utraty życia albo ciężkiego uszczerbku na zdrowiu, podlega
karze pozbawienia wolności do lat 3.

Art. 74. [Nie udzielenie pomocy]
Kto człowiekowi znajdującemu się w położeniu grożącym bezpośrednim niebezpieczeństwem utraty życia nie udziela
pomocy, mogąc jej udzielić bez narażenia siebie lub innych, podlega karze pozbawienia wolności do lat 3.

Art. 75. [Nieumyślne spowodowanie uszczerbku na zdrowiu]
Kto nieumyślnie powoduje ciężki uszczerbek na zdrowiu, podlega karze pozbawienia wolności do lat 3.

Art. 76. [Zabójstwo w wyniku bójki]
Jeżeli następstwem bójki lub pobicia jest śmierć człowieka, sprawca podlega karze pozbawienia wolności na czas nie
krótszy niż 5 lat bądź karze dożywotniego pozbawienia wolności.

Art. 77. [Dzieciobójstwo]
Matka, która zabija dziecko w okresie porodu pod wpływem jego przebiegu, podlega karze pozbawienia wolności od 3
miesięcy do lat 5.

Art. 78. [Narażanie człowieka na zarażenie chorobą]
Kto, wiedząc, że jest dotknięty chorobą zakaźną, ciężką chorobą weneryczną lub inną chorobą ciężką, naraża
bezpośrednio inną osobę na zarażenie, podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności do
lat 3.

                   Rozdział XVI. Przestępstwa przeciwko bezpieczeństwu powszechnemu

Art. 79. [Sprowadzenie zdarzenia zagrażające życiu lub zdrowiu w dużym stopniu]
Kto sprowadza zdarzenie zagrażające życiu lub zdrowiu wielu osób albo mieniu w wielkich rozmiarach, mające postać
pożaru, zawalenia budowli, wybuchu albo gwałtownego wyzwolenia energii, podlega karze pozbawienia wolności od
roku do lat 10.

Art. 80. [Sprowadzenie zdarzenia zagrażające życiu lub zdrowiu]
Kto sprowadza bezpośrednie niebezpieczeństwo zdarzenia, o którym mowa w artykule poprzedzającym, podlega karze
pozbawienia wolności od 6 miesięcy do lat 8.

Art. 81. [Nieumyślne sprowadzenie zdarzenia zagrażającego życiu lub zdrowiu]
Kto nieumyślnie sprowadza zdarzenie zagrażające życiu lub zdrowiu wielu osób albo mieniu w wielkich rozmiarach,
podlega karze pozbawienia wolności do lat 3.

Art. 82. [Bezprawne posiadanie lub handel bronią]
§1. Kto bez wymaganego zezwolenia posiada broń palną albo amunicję, podlega karze pozbawienia wolności od 6
miesięcy do lat 5.
§2. Kto bez wymaganego zezwolenia handluje lub wytwarza broń palną lub amunicję, podlega karze pozbawienia
wolności od 2 do 10 lat.

                   Rozdział XVII. Przestępstwa przeciwko bezpieczeństwu w komunikacji

Art. 83. [Wypadek ze skutkiem zranienia innej osoby]
Kto, naruszając zasady bezpieczeństwa w ruchu, powoduje wypadek, w którym inna osoba odnosi uszczerbek na
zdrowiu, podlega karze pozbawienia wolności do lat 3.

Art. 84. [Prowadzenie pojazdu pod wpływem]
Kto prowadzi pojazd mechaniczny w stanie nietrzeźwości lub pod wpływem środka odurzającego, podlega grzywnie,
karze ograniczenia wolności albo pozbawienia wolności do lat 2 oraz zakazowi prowadzenia pojazdów.

Art. 85. [Wypadek ze skutkiem śmiertelnym bądź ciężkim uszczerbkiem na zdrowiu]
§1. Jeżeli następstwem wypadku w komunikacji jest śmierć innej osoby, sprawca podlega karze pozbawienia wolności
od 2 do 30 lat.
§2. Jeżeli następstwem wypadku w komunikacji jest ciężki uszczerbek na jej zdrowiu, sprawca podlega karze
pozbawienia wolności od 6 miesięcy do lat 8.

Art. 86. [Ucieczka z miejsca zdarzenia wypadku]
Kto, będąc uczestnikiem wypadku, zbiega z miejsca zdarzenia, podlega karze surowszej na zasadach określonych w
ustawie.

Art. 87. [Prowadzenie pojazdu bez uprawnień]
Kto prowadzi pojazd mechaniczny, nie mając do tego uprawnień albo wbrew orzeczonemu zakazowi prowadzenia
pojazdów, podlega karze ograniczenia wolności albo pozbawienia wolności do lat 5.

                               Rozdział XVIII. Przestępstwa przeciwko wolności

Art. 88. [Pozbawienie wolności]
Kto pozbawia człowieka wolności, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 89. [Groźba]
Kto grozi innej osobie popełnieniem przestępstwa na jej szkodę, jeżeli groźba wzbudza uzasadnioną obawę spełnienia,
podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności do lat 2.

Art. 90. [Szantaż]
Kto przemocą lub groźbą bezprawną zmusza inną osobę do określonego działania, zaniechania lub znoszenia, podlega
karze pozbawienia wolności do lat 3.

Art. 91. [Stalking]
Kto przez uporczywe nękanie innej osoby wzbudza u niej uzasadnione poczucie zagrożenia lub istotnie narusza jej
prywatność, podlega karze pozbawienia wolności od roku do lat 10.

Art. 92. [Obcowanie z inną osobą przemocą lub groźbą]
Kto obcuje płciowo z inną osobą przemocą, groźbą bezprawną lub podstępem, jeżeli czyn nie stanowi zbrodni
określonej w Kodeksie karnym ciężkim, podlega karze pozbawienia wolności od lat 2 do 12.

Art. 93. [Handel ludźmi]
Kto uprawia handel ludźmi, podlega karze pozbawienia wolności na czas nie krótszy niż 3 lata.

Art. 94. [Utrwalanie wizerunku osoby nagiej bez jej zgody]
Kto utrwala wizerunek nagiej osoby lub osoby w trakcie czynności seksualnej bez jej zgody albo taki wizerunek
rozpowszechnia, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 95. [Zakłócenie miru domowego]
Kto wdziera się do cudzego domu, mieszkania, lokalu lub ogrodzonego terenu albo wbrew żądaniu osoby uprawnionej
miejsca takiego nie opuszcza, podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności do roku.

Art. 96.
Ściganie przestępstw groźby karalnej oraz uporczywego nękania następuje na wniosek pokrzywdzonego.

                      Rozdział XIX. Przestępstwa przeciwko wolności sumienia i wyznania

Art. 97. [Przeszkadzanie w wykonywaniu aktu religijnego]
Kto złośliwie przeszkadza publicznemu wykonywaniu aktu religijnego uznanego wyznania albo pogrzebowi, podlega
grzywnie, karze ograniczenia wolności albo pozbawienia wolności do lat 2.

Art. 98. [Znieważenie przedmiotu czci religijnej]
Kto publicznie znieważa przedmiot czci religijnej lub miejsce przeznaczone do publicznego wykonywania obrzędów
religijnych albo obraża uczucia religijne innych osób, podlega grzywnie, karze ograniczenia wolności albo pozbawienia
wolności do lat 2 (art. 25 Konstytucji).

                       Rozdział XX. Przestępstwa przeciwko czci i nietykalności cielesnej

Art. 99. [Pomówienie]
Kto pomawia inną osobę o postępowanie lub właściwości, które mogą poniżyć ją w opinii publicznej lub narazić na
utratę zaufania, podlega grzywnie albo karze ograniczenia wolności.

Art. 100. [Znieważenie]
Kto znieważa inną osobę w jej obecności albo publicznie, podlega grzywnie albo karze ograniczenia wolności.

Art. 101. [Naruszenie nietykalności cielesnej]
Kto narusza nietykalność cielesną innej osoby, podlega grzywnie, karze ograniczenia wolności albo pozbawienia
wolności do roku.

Art. 102.
Ściganie przestępstw określonych w niniejszym rozdziale odbywa się z oskarżenia prywatnego.

                            Rozdział XXI. Przestępstwa przeciwko rodzinie i opiece

Art. 103. [Znęcanie się psychicznie lub fizycznie nad osobą najbliższą]
Kto znęca się fizycznie lub psychicznie nad osobą najbliższą lub pozostającą w stosunku zależności, jeżeli czyn nie
stanowi zbrodni określonej w Kodeksie karnym ciężkim, podlega karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 104. [Uporczywe uchylanie się od obowiązku alimentacyjnego]
Kto uporczywie uchyla się od wykonania obowiązku alimentacyjnego, narażając osobę uprawnioną na niemożność
zaspokojenia podstawowych potrzeb życiowych, podlega grzywnie, karze ograniczenia wolności albo pozbawienia
wolności do lat 2.

Art. 105. [Porzucenie małoletniego poniżej lat 15 bądź osoby nieporadnej]
Kto porzuca małoletniego poniżej lat 15 albo osobę nieporadną ze względu na jej stan, podlega karze pozbawienia
wolności od 3 miesięcy do lat 5.

Art. 106. [Rozpicie małoletniego]
Kto rozpija małoletniego, dostarczając mu napoju alkoholowego lub ułatwiając jego spożycie, podlega grzywnie, karze
ograniczenia wolności albo pozbawienia wolności do lat 2.

Art. 107. [Bigamia]
Kto zawiera małżeństwo, pozostając w związku małżeńskim (bigamia), podlega grzywnie albo karze ograniczenia
wolności.

Art. 108. [Uprowadzenie]
§1. Kto wbrew woli uprowadza lub zatrzymuje inną osobę, podlega karze pozbawienia wolności od 2 do 10 lat.

§2. Kto wbrew woli osoby powołanej do opieki uprowadza lub zatrzymuje małoletniego poniżej lat 15 albo osobę
nieporadną, podlega karze pozbawienia wolności od 2 do 15 lat.

                                Rozdział XXII. Przestępstwa przeciwko mieniu

Art. 109. [Zabranie i przywłaszczenie rzeczy ruchomej]
Kto zabiera w celu przywłaszczenia cudzą rzecz ruchomą, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 110. [Kradzież z włamaniem]
Kto kradnie z włamaniem, podlega karze pozbawienia wolności od roku do lat 10.

Art. 111. [Rozbój]
Kto kradnie, używając przemocy wobec osoby lub grożąc jej natychmiastowym użyciem przemocy (rozbój), podlega
karze pozbawienia wolności od lat 2 do 12.

Art. 112. [Przywłaszczenie]
Kto przywłaszcza sobie cudzą rzecz ruchomą lub prawo majątkowe, podlega grzywnie, karze ograniczenia wolności
albo pozbawienia wolności do lat 3.

Art. 113. [Oszustwo]
Kto w celu osiągnięcia korzyści majątkowej doprowadza inną osobę do niekorzystnego rozporządzenia mieniem za
pomocą wprowadzenia w błąd (oszustwo), podlega karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 114. [Paserstwo]
Kto nabywa lub pomaga w zbyciu rzeczy uzyskanej za pomocą czynu zabronionego (paserstwo), podlega karze
pozbawienia wolności od 3 miesięcy do lat 5.

Art. 115. [Niszczycielstwo]
Kto cudzą rzecz niszczy, uszkadza lub czyni niezdatną do użytku, podlega grzywnie, karze ograniczenia wolności albo
pozbawienia wolności do lat 3.

Art. 116. [Kradzież pojazdu na krótki okres]
Kto zabiera w celu krótkotrwałego użycia cudzy pojazd mechaniczny, podlega karze pozbawienia wolności od 3
miesięcy do lat 5.

Art. 117. [Kradzież rozbójnicza]
Kto, w celu utrzymania się w posiadaniu zabranej rzeczy, bezpośrednio po dokonaniu kradzieży używa przemocy
wobec osoby lub grozi jej natychmiastowym jej użyciem (kradzież rozbójnicza), podlega karze pozbawienia wolności
od roku do lat 10.

Art. 118. [Wymuszenie rozbójnicze]
Kto przemocą lub groźbą zamachu na życie lub zdrowie doprowadza inną osobę do rozporządzenia mieniem
(wymuszenie rozbójnicze), podlega karze pozbawienia wolności od roku do lat 10.

Art. 119. [Oszustwo odszkodowania lub ubezpieczenia]
Kto w celu osiągnięcia korzyści majątkowej doprowadza do wypłaty odszkodowania z tytułu umowy ubezpieczenia,
powodując zdarzenie będące podstawą wypłaty, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 120. [Kradzież energii lub karty uprawniającej do podjęcia pieniędzy]
Kto kradnie energię lub kartę uprawniającą do podjęcia pieniędzy, podlega karze pozbawienia wolności od 3 miesięcy
do lat 5.

Art. 121. [Kradzież poniżej 800 marek pruskich]

Jeżeli wartość mienia będącego przedmiotem czynu nie przekracza progu 800 marek pruskich, czyn stanowi
wykroczenie.

Art. 122. [Kradzież, oszustwo lub zniszczenie mienia znacznej wartości]
Kto dopuszcza się kradzieży, przywłaszczenia, oszustwa albo zniszczenia mienia w stosunku do mienia znacznej
wartości, podlega karze pozbawienia wolności od roku do lat 10.

Art. 123. [Kradzież na osobie najbliższej]
Jeżeli kradzież, przywłaszczenie albo oszustwo popełniono na szkodę osoby najbliższej, ściganie następuje na wniosek
pokrzywdzonego.

                      Rozdział XXIII. Przestępstwa przeciwko obrotowi gospodarczemu

Art. 124. [Wyrządzenie znacznej szkody majątkowej]
Kto, nadużywając udzielonych uprawnień lub nie dopełniając obowiązku, wyrządza znaczną szkodę majątkową w
obrocie gospodarczym, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 125. [Pranie pieniędzy]
Kto podejmuje czynności mające na celu ukrycie przestępnego pochodzenia środków majątkowych (pranie pieniędzy),
podlega karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 126. [Łapownictwo]
Kto w związku z pełnieniem funkcji kierowniczej w jednostce gospodarczej przyjmuje korzyść majątkową w zamian za
zachowanie mogące wyrządzić jej szkodę, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 127. [Oszustwo kredytowe]
Kto w celu uzyskania kredytu, pożyczki lub dotacji przedkłada podrobiony, przerobiony lub nierzetelny dokument albo
nierzetelne pisemne oświadczenie, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 128. [Oszustwo na wierzycielu]
Kto, będąc dłużnikiem, udaremnia lub uszczupla zaspokojenie wierzyciela przez usuwanie, ukrywanie lub pozorne
zbywanie składników swojego majątku, podlega karze pozbawienia wolności do lat 3.

                    Rozdział XXIV. Przestępstwa przeciwko wiarygodności dokumentów

Art. 129. [Podrobienie dokumentu]
Kto podrabia lub przerabia dokument w celu użycia go za autentyczny albo takiego dokumentu jako autentycznego
używa, podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności od 3 miesięcy do lat 5.

Art. 130. [Poświadczenie nieprawdy przy wystawianiu dokumentu]
Kto, będąc uprawnionym do wystawienia dokumentu, poświadcza w nim nieprawdę co do okoliczności mającej
znaczenie prawne, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 131. [Niszczenie dokumentów]
Kto niszczy, ukrywa lub usuwa dokument, którym nie ma prawa wyłącznie rozporządzać, podlega grzywnie, karze
ograniczenia wolności albo pozbawienia wolności do lat 2.

                      Rozdział XXV. Przestępstwa przeciwko porządkowi publicznemu

Art. 132. [Udział w bezprawnym zbiegowisku]
Kto bierze czynny udział w zbiegowisku, wiedząc, że jego uczestnicy dopuszczają się gwałtownego zamachu na osobę
lub mienie, podlega karze pozbawienia wolności do lat 3.

Art. 133. [Nawoływanie do popełnienia przestępstwa
Kto publicznie nawołuje do popełnienia przestępstwa, podlega karze ograniczenia wolności albo pozbawienia wolności
do lat 6.

Art. 134. [Udział w zorganizowanej grupie przestępczej]
Kto bierze udział w zorganizowanej grupie albo związku mającym na celu popełnianie przestępstw, podlega karze
pozbawienia wolności od 3 miesięcy do lat 5.

Art. 135. [Znieważenie symboli państwowych]
Kto publicznie znieważa flagę, herb lub hymn państwowy Republiki Pruskiej, podlega grzywnie, karze ograniczenia
wolności albo pozbawienia wolności do roku.

Art. 136. [Fałszywy alarm]
Kto wywołuje fałszywy alarm lub fałszywe ostrzeżenie o zagrożeniu, w szczególności w ramach Elektronicznego
Systemu Ostrzegania, podlega karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 137. [Nawoływanie do nienawiści]
Kto publicznie nawołuje do nienawiści na tle różnic narodowościowych, etnicznych, rasowych lub wyznaniowych,
podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności do lat 5.

Art. 138. [Propagowanie ustrojów totalitarnych]
Kto publicznie propaguje totalitarny ustrój państwa, podlega grzywnie, karze ograniczenia wolności albo pozbawienia
wolności do lat 2.

                    Rozdział XXVI. Przestępstwa przeciwko wymiarowi sprawiedliwości

Art. 139. [Składanie fałszywych zeznań]
Kto, składając zeznanie mające służyć za dowód w postępowaniu, zeznaje nieprawdę lub zataja prawdę, podlega karze
pozbawienia wolności od 6 miesięcy do lat 8.

Art. 140. [Fałszywe oskarżenie]
Kto przed organem powołanym do ścigania fałszywie oskarża inną osobę o popełnienie czynu zabronionego, podlega
grzywnie, karze ograniczenia wolności albo pozbawienia wolności do lat 2.

Art. 141. [Poplecznictwo]
Kto utrudnia lub udaremnia postępowanie karne, pomagając sprawcy przestępstwa uniknąć odpowiedzialności
(poplecznictwo), podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 142. [Wywieranie wpływu na świadka]
Kto przemocą lub groźbą bezprawną wywiera wpływ na świadka, biegłego lub tłumacza albo w związku z
postępowaniem używa wobec nich przemocy, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 143. [Ucieczka od pozbawienia wolności]
Kto uwalnia się sam, będąc pozbawionym wolności na podstawie orzeczenia sądu, podlega grzywnie, karze
ograniczenia wolności albo pozbawienia wolności do lat 2.

Art. 144. [Znieważenie sądu i organów orzekających]
Kto znieważa sąd lub inny organ orzekający w związku z wykonywaniem czynności, podlega grzywnie, karze
ograniczenia wolności albo pozbawienia wolności do lat 2.

               Rozdział XXVII. Przestępstwa przeciwko działalności instytucji państwowych

Art. 145. [Naruszenie nietykalności funkcjonariusza publicznego na służbie]

Kto narusza nietykalność cielesną funkcjonariusza publicznego podczas lub w związku z pełnieniem obowiązków
służbowych, podlega grzywnie, karze ograniczenia wolności albo pozbawienia wolności do lat 3.

Art. 146. [Groźby wobec funkcjonariusza publicznego]
Kto stosuje przemoc lub groźbę bezprawną w celu zmuszenia funkcjonariusza publicznego do przedsięwzięcia lub
zaniechania czynności służbowej, podlega karze pozbawienia wolności od 3 miesięcy do lat 5.

Art. 147. [Znieważenie funkcjonariusza publicznego]
Kto znieważa funkcjonariusza publicznego podczas i w związku z pełnieniem obowiązków służbowych, podlega
grzywnie, karze ograniczenia wolności albo pozbawienia wolności do dwóch lat.

Art. 148. [Sprzedajność]
Kto, pełniąc funkcję publiczną, przyjmuje korzyść majątkową lub osobistą albo jej obietnicę (sprzedajność), podlega
karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 149. [Przekupstwo]
Kto udziela lub obiecuje udzielić korzyści majątkowej lub osobistej osobie pełniącej funkcję publiczną (przekupstwo),
podlega karze pozbawienia wolności od 6 miesięcy do lat 8.

Art. 150. [Przekroczenie uprawnień lub niedopełnienie obowiązku]
Kto, przekraczając uprawnienia lub nie dopełniając obowiązków, działa na szkodę interesu publicznego lub
prywatnego, podlega karze pozbawienia wolności do lat 3.

Art. 151. [Płatna protekcja]
