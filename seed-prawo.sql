   3) stopień wojskowy — przez rozstrzelanie.

Art. 10.
Stopień wojskowy stosuje się wyłącznie wobec osób pełniących funkcje polityczne oraz żołnierzy.

Art. 11.
Stopień kary śmierci orzeka sędzia egzekutor, na podstawie rodzaju i wagi czynów popełnionych
przez skazanego.

                                        ROZDZIAŁ II
                         NIENARUSZALNOŚĆ KARY ŚMIERCI

Art. 12.
Kara śmierci przewidziana w Kodeksie nie może zostać zniesiona, zawieszona ani ograniczona
inaczej niż w drodze zmiany Konstytucji, w granicach dopuszczonych jej art. 175.

Art. 13.
Sąd nie może odmówić orzeczenia albo wykonania kary śmierci ani jej uchylić, powołując się na
godność człowieka, na podmiotowość prawną człowieka, na prawa człowieka lub na inne zasady
ogólne, wbrew wyraźnej dopuszczalności kary śmierci wynikającej z art. 15 i art. 16 Konstytucji.

Art. 14.
W postępowaniu przed sądem drugiej oraz trzeciej instancji nie można uchylić ani zmienić
orzeczenia o karze śmierci z powołaniem się na okoliczność, że skazany jest człowiekiem w
rozumieniu prawa, ani na inną podstawę o charakterze wyłącznie aksjologicznym lub
światopoglądowym.

Art. 15.
Orzeczenie o karze śmierci może zostać uchylone lub zmienione wyłącznie z przyczyn określonych
w Kodeksie oraz w Kodeksie postępowania karnego, w szczególności w razie ujawnienia dowodów
niewinności skazanego albo istotnego naruszenia przepisów postępowania mającego wpływ na treść
wyroku.

Art. 16.
Umowa międzynarodowa, orzeczenie sądu lub organu międzynarodowego oraz zalecenie
organizacji międzynarodowej nie mogą znieść, zawiesić ani ograniczyć kary śmierci; w razie
sprzeczności pierwszeństwo ma Konstytucja Republiki Pruskiej (art. 5 Konstytucji).

Art. 17.
Nie zawiera się umów międzynarodowych zobowiązujących do zniesienia albo ograniczenia kary
śmierci; postanowienie takiej umowy w tym zakresie nie wywołuje skutków prawnych w Republice
Pruskiej.

Art. 18.

Sędzia, który wbrew Kodeksowi odmawia orzeczenia lub wykonania kary śmierci z przyczyn, o
których mowa w niniejszym rozdziale, podlega wyłączeniu od orzekania w sprawie oraz
odpowiedzialności dyscyplinarnej.

                                       ROZDZIAŁ III
                         SĘDZIA EGZEKUTOR I IZBA ŚMIERCI

Art. 19.
Sędzią egzekutorem jest sędzia, który uzyskał licencję sędziego egzekutora.

Art. 20.
Licencję sędziego egzekutora uzyskuje sędzia, który zdał egzamin na sędziego egzekutora oraz
pomyślnie przeszedł test psychologiczny.

Art. 21.
Pytania egzaminacyjne na sędziego egzekutora określa, w drodze rozporządzenia, Minister
Sprawiedliwości; odpowiedzi udziela się w formie „tak" albo „nie", chyba że pytanie wskazuje
inaczej.

Art. 22.
W sprawach, w których oskarżonemu zarzuca się co najmniej jedną zbrodnię określoną w Kodeksie
karnym ciężkim, obradom sądu przewodniczy sędzia egzekutor.

Art. 23.
1. Tworzy się izbę śmierci Sądu Najwyższego, w skład której mogą wchodzić wyłącznie sędziowie
egzekutorzy.
2. Tryb pracy izby śmierci odpowiada trybowi pracy izby karnej Sądu Najwyższego.

Art. 24.
Sędzia egzekutor przewodniczący składowi podejmuje decyzję o orzeczeniu kary śmierci po
naradzie z pozostałymi sędziami składu.

                                       ROZDZIAŁ IV
                              POSTĘPOWANIE I INSTANCJE

Art. 25.
Postępowanie w sprawach zagrożonych karą śmierci odbywa się w trzech instancjach.

Art. 26.
W pierwszej instancji orzeka skład pięciu sędziów, któremu przewodniczy sędzia egzekutor.

Art. 27.
W drugiej instancji orzeka skład siedmiu sędziów, w którym co najmniej trzej są sędziami
egzekutorami; obradom przewodniczy sędzia egzekutor.

Art. 28.
W trzeciej instancji sprawę rozpoznaje izba śmierci Sądu Najwyższego.

Art. 29.
Obrona jest obligatoryjna we wszystkich instancjach; skazany musi mieć obrońcę.

Art. 30.
Skazanemu na karę śmierci przysługuje prawo do wniesienia apelacji, którą sąd ma obowiązek
rozpoznać.

Art. 31.
Sąd, prokuratura oraz obrona prowadzą prace nad całością postępowania drugiej instancji w
terminie 90 dni; sąd drugiej instancji wydaje wyrok najpóźniej 90. dnia, chyba że obrona i
prokuratura wspólnie zgłoszą brak dalszych wniosków dowodowych.

Art. 32.
Jeżeli sąd utrzymuje w mocy wyrok orzekający karę śmierci, skazanemu przysługuje prawo do
ponownej apelacji.

Art. 33.
Całość postępowania nie może trwać dłużej niż 120 dni; wyrok zapada najpóźniej 120. dnia, chyba
że prokuratura i obrona wspólnie zgłoszą gotowość do wydania wyroku wcześniej.

Art. 34.
Wyrok skazujący na karę śmierci nie uprawomocnia się w pierwszej instancji; podlega on z urzędu
rozpoznaniu przez sąd drugiej instancji, choćby apelacji nie wniesiono.

Art. 35.
1. Apelację w sprawie zagrożonej karą śmierci rozpoznaje skład siedmiu sędziów, o którym mowa
w niniejszym rozdziale; w sprawach tych nie orzeka sąd apelacyjny właściwy w sprawach
zwykłych.
2. Jeżeli ani skazany, ani jego obrońca nie wniosą apelacji, sąd drugiej instancji rozpoznaje sprawę
z urzędu, badając wyrok w całości; brak apelacji nie zwalnia sądu z tego obowiązku.

Art. 36.
Utrzymany w mocy wyrok orzekający karę śmierci podlega — na skutek ponownej apelacji albo z
urzędu — rozpoznaniu przez izbę śmierci Sądu Najwyższego jako sąd trzeciej instancji, która pełni
zarazem funkcję sądu kasacyjnego.

Art. 37.
Wyrok orzekający karę śmierci uprawomocnia się dopiero po rozpoznaniu sprawy przez izbę
śmierci Sądu Najwyższego.

Art. 38.

1. Po uprawomocnieniu się wyroku postępowanie wznawia się na rzecz skazanego, jeżeli ujawnią
się nowe fakty lub dowody wskazujące na jego niewinność albo na istotne naruszenie prawa mające
wpływ na treść wyroku.
2. Wniosek o wznowienie rozpoznaje izba śmierci Sądu Najwyższego w innym składzie.
3. Złożenie wniosku o wznowienie oraz jego rozpoznawanie wstrzymuje wykonanie kary śmierci.

Art. 39.
Środki zaskarżenia oraz wznowienie postępowania nie mogą prowadzić do uchylenia kary śmierci z
przyczyn, o których mowa w rozdziale II; służą wyłącznie zbadaniu winy skazanego oraz zgodności
postępowania z prawem.

Art. 40.
W zakresie nieuregulowanym w Kodeksie stosuje się przepisy Kodeksu postępowania karnego, o
ile nie są sprzeczne z niniejszym Kodeksem.

                                       ROZDZIAŁ V
                              ORZEKANIE STOPNIA KARY

Art. 41.
Po podjęciu decyzji o skazaniu na karę śmierci sędzia egzekutor orzeka jej stopień, na podstawie
rodzaju i wagi czynów popełnionych przez skazanego.

Art. 42.
Stopień wojskowy orzeka się wyłącznie wobec osób pełniących funkcje polityczne oraz żołnierzy.

Art. 43.
W razie skazania za dwie lub więcej zbrodni sędzia egzekutor orzeka stopień właściwy dla zbrodni
najcięższej.

                                      ROZDZIAŁ VI
                 UŁASKAWIENIE I WSTRZYMANIE WYKONANIA

Art. 44.
Skazanemu na karę śmierci przysługuje prawo wniesienia prośby o ułaskawienie.

Art. 45.
Prawo łaski wykonuje Prezydent Republiki.

Art. 46.
Wykonanie kary śmierci wstrzymuje się do czasu prawomocnego zakończenia postępowania oraz
rozpatrzenia prośby o ułaskawienie.

Art. 47.

Ułaskawienie może polegać na darowaniu kary śmierci albo na zamianie jej na karę dożywotniego
pozbawienia wolności.

Art. 48.
Nie wykonuje się kary śmierci na kobiecie ciężarnej; wykonanie wstrzymuje się do czasu urodzenia
dziecka, a sąd może zamienić karę śmierci na karę dożywotniego pozbawienia wolności.

Art. 49.
Jeżeli po wydaniu prawomocnego wyroku skazany zapadł na chorobę psychiczną uniemożliwiającą
mu rozpoznanie znaczenia kary, wykonanie kary wstrzymuje się do czasu ustania tego stanu.

                                      ROZDZIAŁ VII
           PRAWA SKAZANEGO OCZEKUJĄCEGO NA WYKONANIE KARY

Art. 50.
Skazany oczekujący na wykonanie kary śmierci przebywa w wyodrębnionym oddziale i jest
traktowany humanitarnie, z poszanowaniem jego godności (art. 13 Konstytucji).

Art. 51.
O dniu i godzinie wykonania kary zawiadamia się skazanego oraz jego rodzinę z odpowiednim
wyprzedzeniem, nie później niż na 7 dni przed wykonaniem.

Art. 52.
Skazanemu zapewnia się widzenia z osobami najbliższymi, a w dniu poprzedzającym wykonanie
kary — widzenie pożegnalne.

Art. 53.
Skazany ma prawo do korespondencji oraz do nieograniczonego kontaktu z obrońcą.

Art. 54.
Skazanemu zapewnia się opiekę lekarską i psychologiczną oraz, na jego życzenie, posługę religijną
(art. 26 Konstytucji).

Art. 55.
Skazanemu zapewnia się możliwość sporządzenia testamentu oraz uregulowania spraw osobistych i
majątkowych.

Art. 56.
W dniu wykonania kary skazany ma prawo do ostatniego posiłku według swojego życzenia, w
granicach określonych w regulaminie.

Art. 57.
Bezpośrednio przed wykonaniem kary skazanemu przysługuje prawo do wypowiedzenia ostatniego
słowa.

                                      ROZDZIAŁ VIII
                              WYKONANIE KARY ŚMIERCI

Art. 58.
Karę śmierci wykonuje się 240. dnia od dnia wydania pierwszego wyroku skazującego na karę
śmierci, o godzinie 12:00.

Art. 59.
Karę śmierci wykonuje strażnik więzienny posiadający uprawnienia kata.

Art. 60.
Karę wykonuje się w sposób odpowiadający orzeczonemu stopniowi, w wyznaczonym miejscu, z
poszanowaniem powagi wykonania.

Art. 61.
Przy wykonaniu kary śmierci obecni są: sędzia egzekutor albo wyznaczony sędzia, prokurator,
lekarz oraz kat.

Art. 62.
Lekarz stwierdza zgon skazanego; z wykonania kary sporządza się protokół.

Art. 63.
1. Obowiązek stawiennictwa jako świadkowie mają członkowie rodziny skazanego.
2. Nieobowiązkowo obecni mogą być rodzina ofiary, ofiara oraz osoby zaproszone przez rodzinę
ofiary albo skazanego.

Art. 64.
Skazanemu przed wykonaniem kary zapewnia się, na jego życzenie, posługę religijną (art. 26
Konstytucji).

Art. 65.
Ciało skazanego wydaje się rodzinie, a w razie jej braku chowa na koszt państwa.

Art. 66.
O wykonaniu kary śmierci niezwłocznie zawiadamia się rodzinę skazanego; pochówek odbywa się
z poszanowaniem wyznania skazanego.

Art. 67.
Rzeczy osobiste skazanego oraz jego ostatnią wolę wydaje się osobom przez niego wskazanym.

                                       ROZDZIAŁ IX
                                              KAT

Art. 68.

Katem może być wyłącznie osoba wykonująca zawód strażnika więziennego, która uzyskała
uprawnienia kata.

Art. 69.
Uprawnienia kata uzyskuje się przez zdany egzamin na kata oraz pomyślne przejście testu
psychologicznego.

Art. 70.
Pytania egzaminacyjne na kata określa, w drodze rozporządzenia, Minister Spraw Wewnętrznych;
odpowiedzi udziela się w formie „tak" albo „nie", chyba że pytanie wskazuje inaczej.

                                     ROZDZIAŁ X
                                PRZEPISY KOŃCOWE

Art. 71.
Traci moc dotychczasowy Kodeks kary śmierci.

Art. 72.
Kodeks ma charakter ustawy konstytucyjnej (art. 114 Konstytucji); jego zmiana wymaga trybu
określonego w art. 176 Konstytucji.

Art. 73.
Kodeks wchodzi w życie po upływie 30 dni od dnia ogłoszenia w Dzienniku Ustaw Republiki
Pruskiej.$prawo$);
