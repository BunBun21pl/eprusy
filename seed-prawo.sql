Najwyższego określone w Kodeksie kary śmierci, a obradami kieruje sędzia egzekutor.

Art. 118.
W sprawach tych obrona jest obligatoryjna, a postępowanie prowadzi się z zapewnieniem najwyższych
gwarancji procesowych (art. 16 Konstytucji).

Art. 119.
Skazanemu na karę śmierci przysługują środki zaskarżenia oraz prawo do ubiegania się o ułaskawienie;
wykonanie kary następuje na zasadach i w terminach określonych w Kodeksie kary śmierci.

