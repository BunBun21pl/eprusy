Art. 3.
Postępowanie cywilne oparte jest na zasadzie kontradyktoryjności; strony obowiązane są przedstawiać
dowody i twierdzenia, a bieg postępowania napędzają swoimi czynnościami.

Art. 4.
Sąd powinien dążyć do szybkiego i sprawnego rozpoznania sprawy, przeciwdziałając przewlekaniu
postępowania oraz nadużywaniu praw procesowych.

Art. 5.
Na każdym etapie postępowania sąd dąży do ugodowego załatwienia sprawy, w szczególności przez
nakłanianie stron do mediacji lub ugody.

Art. 6.
Rozpoznanie sprawy odbywa się jawnie, chyba że przepis szczególny stanowi inaczej; wyrok ogłasza się
publicznie (art. 113 Konstytucji).

Art. 7.
Sąd rozstrzyga sprawę na podstawie stanu rzeczy istniejącego w chwili zamknięcia rozprawy, oceniając
wiarygodność i moc dowodów według własnego przekonania.

Art. 8.
Strony mają równe prawa w postępowaniu; sąd zapewnia każdej z nich możność obrony jej praw oraz
przedstawienia twierdzeń i dowodów.

Art. 9.
Postępowanie zmierza do wyjaśnienia okoliczności sprawy zgodnie z prawdą; strony obowiązane są
dokonywać czynności procesowych zgodnie z dobrymi obyczajami i dawać wyjaśnienia zgodnie z prawdą.

Art. 10.
Postępowanie prowadzi się w języku polskim; osobie niewładającej tym językiem zapewnia się udział
tłumacza.

Art. 11.

Z uprawnienia procesowego nie można czynić użytku sprzecznego z celem, dla którego je ustanowiono; sąd
przeciwdziała nadużyciu praw procesowych i może obciążyć nadużywającego kosztami.

Art. 12.
Każdy ma prawo do rozpoznania jego sprawy bez nieuzasadnionej zwłoki; stronie, której prawo to
naruszono, przysługuje skarga na przewlekłość postępowania oraz odpowiednia suma pieniężna.

                                       Tytuł II. Sąd i właściwość

Art. 13.
W sprawach cywilnych orzekają sądy rejonowe, okręgowe i apelacyjne oraz Sąd Najwyższy.

Art. 14.
1. Sąd rejonowy działa w każdym powiecie; sąd okręgowy — w siedzibie każdej rejencji.
2. Postępowanie odbywa się w trzech instancjach.

Art. 15.
W pierwszej instancji orzeka sąd rejonowy, z wyjątkiem spraw zastrzeżonych dla sądu okręgowego.

Art. 16.
W pierwszej instancji sąd okręgowy rozpoznaje sprawy o prawa majątkowe, w których wartość przedmiotu
sporu przewyższa próg określony w ustawie, oraz sprawy o prawa niemajątkowe i inne wskazane w ustawie
ze względu na ich wagę.

Art. 17.
W drugiej instancji sąd apelacyjny rozpoznaje apelacje od wyroków sądów rejonowych i okręgowych.

Art. 18.
Sąd Najwyższy rozpoznaje skargi kasacyjne oraz inne środki i sprawy zastrzeżone dla niego w ustawie.

Art. 19.
Powództwo wytacza się przed sąd, w którego okręgu pozwany ma miejsce zamieszkania (właściwość
ogólna); w przypadkach określonych w ustawie właściwy jest także sąd miejsca wykonania umowy,
położenia nieruchomości albo zdarzenia wyrządzającego szkodę (właściwość przemienna).

Art. 20.
Strony mogą umówić się na piśmie o poddanie sporu sądowi pierwszej instancji, który według ustawy nie
jest miejscowo właściwy (właściwość umowna), z wyjątkiem właściwości wyłącznej.

Art. 21.
Sąd bada właściwość z urzędu w każdym stanie sprawy; sprawę wniesioną do sądu niewłaściwego
przekazuje sądowi właściwemu.

Art. 22.
1. Na rozprawie sąd orzeka w składzie jednego sędziego.
2. W drugiej instancji oraz w Sądzie Najwyższym sąd orzeka w składzie trzech sędziów, chyba że ustawa
stanowi inaczej.

Art. 23.
Sędzia podlega wyłączeniu na zasadach określonych dla postępowania karnego, stosowanych odpowiednio.

Art. 24.

Wartość przedmiotu sporu oznacza się sumą pieniężną dochodzoną w pozwie; w sprawach o świadczenia
powtarzające się przyjmuje się wartość świadczeń za oznaczony okres.

Art. 25.
W sprawach o własność, posiadanie oraz inne prawa do nieruchomości właściwy wyłącznie jest sąd miejsca
jej położenia (właściwość wyłączna).

Art. 26.
Sąd niewłaściwy przekazuje sprawę sądowi właściwemu postanowieniem; sąd, któremu sprawę przekazano,
jest nią związany.

Art. 27.
Sąd właściwy w chwili wniesienia pozwu pozostaje właściwy aż do ukończenia postępowania, choćby
podstawy właściwości zmieniły się w toku sprawy.

Art. 28.
Wyłączenie sędziego następuje z mocy ustawy albo na wniosek strony; do czasu rozstrzygnięcia wniosku
sędzia może dokonywać jedynie czynności niecierpiących zwłoki.

                                     Tytuł III. Strony i uczestnicy

Art. 29.
Zdolność sądową, to jest zdolność występowania w procesie jako strona, ma każda osoba fizyczna i prawna
oraz jednostka organizacyjna, której ustawa przyznaje zdolność prawną.

Art. 30.
Zdolność do czynności procesowych mają osoby fizyczne posiadające pełną zdolność do czynności
prawnych; osoby o ograniczonej zdolności działają przez przedstawiciela ustawowego.

Art. 31.
Stronami są powód i pozwany; kilka osób może występować w roli powoda lub pozwanego, jeżeli ich prawa
lub obowiązki są wspólne albo oparte na tej samej podstawie (współuczestnictwo).

Art. 32.
Osoba mająca interes prawny w rozstrzygnięciu na korzyść jednej ze stron może przystąpić do niej w
charakterze interwenienta ubocznego.

Art. 33.
W miejsce dotychczasowej strony może, za zgodą stron, wstąpić nabywca rzeczy lub prawa objętego
sporem.

Art. 34.
Współuczestnictwo jest materialne, gdy prawa lub obowiązki stron są wspólne albo oparte na tej samej
podstawie, oraz formalne, gdy roszczenia są jednorodzajowe i oparte na takiej samej podstawie faktycznej i
prawnej.

Art. 35.
Na wniosek strony lub za jej zgodą sąd może wezwać do udziału w sprawie osobę, która powinna
występować po stronie powodowej lub pozwanej (dopozwanie).

Art. 36.

Powód może aż do zamknięcia rozprawy zmienić żądanie lub wystąpić z nowym obok pierwotnego, jeżeli
nie wpływa to na właściwość sądu w sposób niedopuszczalny.

Art. 37.
W razie śmierci strony sąd zawiesza postępowanie; podejmuje się je z udziałem następców prawnych
zmarłego.

Art. 38.
Pozwany może wytoczyć przeciwko powodowi powództwo wzajemne, jeżeli pozostaje ono w związku z
roszczeniem powoda lub nadaje się do potrącenia.

Art. 39.
Kto występuje z roszczeniem o rzecz lub prawo, o które sprawa toczy się między innymi osobami, może
wytoczyć powództwo przeciwko obu stronom przed sąd, w którym toczy się sprawa (interwencja główna).

Art. 40.
Strona, której w razie niekorzystnego rozstrzygnięcia przysługiwałoby roszczenie względem osoby trzeciej
albo przeciwko której osoba trzecia mogłaby wystąpić z roszczeniem, może zawiadomić tę osobę o
toczącym się procesie i wezwać ją do udziału (przypozwanie).

Art. 41.
Powództwo może wytoczyć oraz odpowiadać na nie tylko osoba, której przysługuje dochodzone prawo lub
przeciwko której ono przysługuje (legitymacja procesowa).

Art. 42.
Za Skarb Państwa czynności procesowe podejmuje organ państwowej jednostki organizacyjnej, z której
działalnością wiąże się dochodzone roszczenie.

Art. 43.
Jednostka organizacyjna niebędąca osobą prawną, mająca zdolność sądową, dokonuje czynności
procesowych przez swój organ albo przez osoby uprawnione do działania w jej imieniu.

                                  Tytuł IV. Pełnomocnicy procesowi

Art. 44.
Strona może działać przed sądem osobiście albo przez pełnomocnika procesowego.

Art. 45.
Pełnomocnikiem procesowym może być adwokat lub radca prawny, a ponadto małżonek, rodzeństwo,
zstępny lub wstępny strony oraz osoba pozostająca ze stroną w stosunku przysposobienia, a także
współuczestnik sporu.

Art. 46.
Osoba prawna oraz przedsiębiorca mogą być reprezentowani również przez pracownika.

Art. 47.
1. Pełnomocnictwo procesowe obejmuje z mocy prawa umocowanie do wszystkich czynności procesowych
w sprawie, w tym do wniesienia środków zaskarżenia, zawarcia ugody, zrzeczenia się roszczenia oraz
uznania powództwa.
2. Zakres pełnomocnictwa może zostać ograniczony przez mocodawcę.

Art. 48.

Pełnomocnik obowiązany jest przy pierwszej czynności procesowej dołączyć do akt dokument
pełnomocnictwa.

Art. 49.
1. Mocodawca może wypowiedzieć pełnomocnictwo procesowe w każdym czasie.
2. Wypowiedzenie pełnomocnictwa przez mocodawcę odnosi skutek prawny wobec sądu od chwili
zawiadomienia go o tym, a wobec strony przeciwnej — od chwili doręczenia jej tego zawiadomienia.

Art. 50.
1. Pełnomocnik może wypowiedzieć pełnomocnictwo.
2. Adwokat lub radca prawny, który wypowiedział pełnomocnictwo, obowiązany jest działać za stronę
jeszcze przez dwa tygodnie, chyba że mocodawca zwolni go z tego obowiązku.

Art. 51.
W razie śmierci strony pełnomocnictwo procesowe nie wygasa; pełnomocnik działa aż do zawieszenia
postępowania.

Art. 52.
Sąd może ustanowić dla strony pełnomocnika z urzędu, jeżeli strona jest zwolniona od kosztów sądowych i
wykaże, że nie jest w stanie ponieść kosztów pomocy prawnej bez uszczerbku dla utrzymania.

Art. 53.
Adwokat i radca prawny mogą udzielić dalszego pełnomocnictwa (substytucji) innemu adwokatowi lub
radcy prawnemu.

Art. 54.
Sąd może dopuścić tymczasowo do czynności osobę niemogącą przedstawić pełnomocnictwa, wyznaczając
termin do jego złożenia; po bezskutecznym upływie terminu znosi skutki dokonanych czynności.

Art. 55.
Czynności procesowe podjęte przez osobę działającą bez należytego umocowania mogą zostać potwierdzone
przez stronę.

                            Tytuł V. Prokurator i organizacje społeczne

Art. 56.
Prokurator może wytoczyć powództwo w każdej sprawie oraz wziąć udział w toczącym się postępowaniu,
jeżeli wymaga tego ochrona praworządności, praw obywateli lub interesu publicznego.

Art. 57.
Organizacja społeczna może, w zakresie swoich zadań statutowych i za zgodą osoby zainteresowanej,
wytoczyć powództwo na jej rzecz albo przystąpić do sprawy w toku.

                                   Tytuł VI. Koszty postępowania

Art. 58.
Koszty postępowania obejmują opłaty sądowe oraz wydatki, a także koszty zastępstwa przez adwokata lub
radcę prawnego.

Art. 59.

Strona wnosząca pismo podlegające opłacie obowiązana jest uiścić opłatę sądową; pismo nieopłacone nie
wywołuje skutków, dopóki opłata nie zostanie uiszczona w wyznaczonym terminie.

Art. 60.
Strona przegrywająca sprawę obowiązana jest zwrócić przeciwnikowi na jego żądanie koszty niezbędne do
celowego dochodzenia praw lub obrony.

Art. 61.
1. Sąd może zwolnić stronę od kosztów sądowych w całości lub w części, jeżeli wykaże, że nie jest w stanie
ich ponieść bez uszczerbku dla koniecznego utrzymania.
2. Wraz ze zwolnieniem od kosztów strona może żądać ustanowienia pełnomocnika z urzędu.

Art. 62.
W razie ugody sądowej albo cofnięcia pozwu sąd może orzec o wzajemnym zniesieniu kosztów oraz o
zwrocie części opłaty.

Art. 63.
W razie częściowego uwzględnienia żądań koszty rozdziela się stosunkowo albo wzajemnie znosi.

Art. 64.
Do niezbędnych kosztów procesu strony reprezentowanej przez adwokata lub radcę prawnego zalicza się
wynagrodzenie, jednak nie wyższe niż stawki określone w rozporządzeniu.

Art. 65.
Współuczestnicy sporu zwracają koszty procesu w częściach równych, chyba że sąd orzeknie inaczej.

Art. 66.
Na żądanie pozwanego powód niemający miejsca zamieszkania lub siedziby w Republice Pruskiej
obowiązany jest złożyć kaucję na zabezpieczenie kosztów procesu, chyba że umowa międzynarodowa
stanowi inaczej.

Art. 67.
Ustanowienie adwokata lub radcy prawnego z urzędu jest równoznaczne z udzieleniem pełnomocnictwa
procesowego; obejmuje ono także postępowanie egzekucyjne.

Art. 68.
Opłata sądowa jest stała, stosunkowa albo podstawowa; opłatę stosunkową pobiera się w sprawach o prawa
majątkowe w wysokości określonej ułamkiem wartości przedmiotu sporu, w granicach oznaczonych w
ustawie.

                           Tytuł VII. Postępowanie — wszczęcie i przebieg

Art. 69.
Postępowanie wszczyna się przez wniesienie pozwu; pozew powinien zawierać dokładnie określone żądanie,
przytoczenie okoliczności faktycznych oraz dowody na ich poparcie.

Art. 70.
Sąd doręcza pozwanemu odpis pozwu i wzywa go do wniesienia odpowiedzi na pozew w wyznaczonym
terminie.

Art. 71.

Strony obowiązane są przytaczać wszystkie twierdzenia i dowody bez zwłoki; spóźnione twierdzenia i
dowody sąd pomija, chyba że strona uprawdopodobni, że nie zgłosiła ich bez swojej winy (koncentracja
materiału dowodowego).

Art. 72.
Pisma i orzeczenia doręcza się za pokwitowaniem; dopuszcza się doręczenia elektroniczne na zasadach
określonych w ustawie.

Art. 73.
Sąd może skierować strony do mediacji na każdym etapie postępowania; mediacja jest dobrowolna.

Art. 74.
1. Ugoda zawarta przed mediatorem, po zatwierdzeniu przez sąd, ma moc ugody sądowej.
2. Ugoda sądowa kończy postępowanie i podlega wykonaniu jak orzeczenie sądu.

Art. 75.
Sąd może zawiesić postępowanie, jeżeli jego dalszy bieg zależy od wyniku innego postępowania albo z
powodu niemożności prowadzenia sprawy; zawieszone postępowanie podejmuje się po ustaniu przyczyny.

Art. 76.
Rozprawa obejmuje przedstawienie stanowisk stron, przeprowadzenie dowodów oraz roztrząsanie ich
wyników; przewodniczący kieruje rozprawą i udziela głosu stronom.

Art. 77.
Pismo procesowe powinno zawierać oznaczenie sądu, stron, rodzaj pisma, osnowę wniosku lub
oświadczenia, dowody oraz podpis; do pisma dołącza się jego odpisy dla pozostałych stron.

Art. 78.
Jeżeli pismo nie może otrzymać prawidłowego biegu wskutek braków formalnych, przewodniczący wzywa
do ich usunięcia w terminie tygodnia pod rygorem zwrotu pisma.

Art. 79.
W razie niemożności doręczenia pisma adresatowi pismo składa się w placówce pocztowej albo urzędzie
gminy, a zawiadomienie o tym pozostawia w sposób określony w ustawie (doręczenie zastępcze).

Art. 80.
Jeżeli strona nie dokonała czynności procesowej w terminie bez swojej winy, sąd na jej wniosek przywraca
termin; wniosek składa się w terminie tygodnia od ustania przyczyny uchybienia.

Art. 81.
Sąd może rozpoznać sprawę na posiedzeniu niejawnym, jeżeli ustawa tak stanowi albo gdy przeprowadzenie
rozprawy nie jest konieczne.

Art. 82.
1. Powód może cofnąć pozew; cofnięcie pozwu ze zrzeczeniem się roszczenia nie wymaga zgody
pozwanego.
2. W razie skutecznego cofnięcia pozwu sąd umarza postępowanie.

Art. 83.
Sąd umarza postępowanie także wtedy, gdy wydanie wyroku stało się z innych przyczyn zbędne lub
niedopuszczalne.

Art. 84.
Terminy do dokonania czynności procesowej są ustawowe albo wyznaczone przez sąd (sądowe); bieg
terminu wyznaczonego przez sąd rozpoczyna się od jego ogłoszenia lub doręczenia.

Art. 85.
Z przebiegu posiedzenia jawnego sporządza się protokół, który może być utrwalany także za pomocą
urządzenia rejestrującego dźwięk albo obraz i dźwięk.

Art. 86.
Przed wytoczeniem powództwa strona może wystąpić z zawezwaniem przeciwnika do próby ugodowej
przed sądem rejonowym.

Art. 87.
Sąd może przeprowadzić posiedzenie zdalne przy użyciu urządzeń technicznych umożliwiających jego
przeprowadzenie na odległość z jednoczesnym przekazem obrazu i dźwięku.

Art. 88.
Doręczeń można dokonywać za pośrednictwem systemu teleinformatycznego, jeżeli strona wniosła pismo tą
drogą albo wyraziła na to zgodę.

Art. 89.
W czasie trwania procesu nie można wszcząć między tymi samymi stronami nowego postępowania o to
samo roszczenie (zawisłość sporu).

Art. 90.
Zmiana powództwa jest niedopuszczalna, jeżeli pociągałaby za sobą niewłaściwość rzeczową sądu, chyba że
sprawę należałoby przekazać sądowi wyższego rzędu.

Art. 91.
Dla strony, której miejsce pobytu nie jest znane, sąd może ustanowić kuratora, jeżeli podejmowane
czynności są dla niej niekorzystne albo wymagają jej udziału.

                                         Tytuł VIII. Dowody

Art. 92.
Przedmiotem dowodu są fakty mające dla rozstrzygnięcia sprawy istotne znaczenie; nie wymagają dowodu
fakty przyznane oraz powszechnie znane.

Art. 93.
Ciężar udowodnienia faktu spoczywa na osobie, która z faktu tego wywodzi skutki prawne.

Art. 94.
Sąd dopuszcza dowody na wniosek stron, a w wyjątkowych wypadkach może dopuścić dowód niewskazany
przez stronę.

Art. 95.
Dokument urzędowy stanowi dowód tego, co zostało w nim urzędowo stwierdzone; dokument prywatny
stanowi dowód, że osoba, która go podpisała, złożyła zawarte w nim oświadczenie.

Art. 96.

Świadek składa zeznania po pouczeniu o obowiązku mówienia prawdy i odpowiedzialności karnej za
fałszywe zeznania; osoba najbliższa strony może odmówić zeznań.

Art. 97.
Jeżeli rozstrzygnięcie sprawy wymaga wiadomości specjalnych, sąd dopuszcza dowód z opinii biegłego.

Art. 98.
Sąd może zarządzić oględziny przedmiotu, miejsca lub osoby.

Art. 99.
Jeżeli po wyczerpaniu innych środków dowodowych lub w ich braku pozostały niewyjaśnione fakty istotne
dla sprawy, sąd może dopuścić dowód z przesłuchania stron.

Art. 100.
Sąd ocenia wiarygodność i moc dowodów według własnego przekonania, na podstawie wszechstronnego
rozważenia zebranego materiału.

Art. 101.
Przed wszczęciem postępowania lub w jego toku można żądać zabezpieczenia dowodu, jeżeli zachodzi
obawa, że jego przeprowadzenie stanie się niewykonalne lub utrudnione.

Art. 102.
Dokumentem jest także zapis w postaci elektronicznej umożliwiający ustalenie jego wystawcy oraz
zapoznanie się z jego treścią.

Art. 103.
Świadka wezwanego, który bez usprawiedliwienia nie stawił się albo bezpodstawnie odmawia zeznań, sąd
może ukarać grzywną, a w razie ponownego niestawiennictwa — zarządzić przymusowe doprowadzenie.

Art. 104.
Sąd może zażądać opinii odpowiedniego instytutu naukowego lub naukowo-badawczego zamiast opinii
biegłego.

Art. 105.
Domniemania ustanowione przez prawo (domniemania prawne) wiążą sąd; mogą być obalone, ilekroć
ustawa tego nie wyłącza.

Art. 106.
Sąd może uznać za ustalone fakty mające istotne znaczenie, jeżeli wniosek taki można wyprowadzić z
innych ustalonych faktów (domniemanie faktyczne).

Art. 107.
Sąd może pominąć środek dowodowy zmierzający jedynie do przewlekania postępowania albo dotyczący
faktów bezspornych lub nieistotnych.

Art. 108.
Strona, która zaprzecza prawdziwości dokumentu prywatnego albo twierdzi, że zawarte w nim oświadczenie
nie pochodzi od osoby, która go podpisała, powinna okoliczności te udowodnić.

Art. 109.
Świadek może odmówić odpowiedzi na pytanie, jeżeli zeznanie mogłoby narazić jego lub osobę najbliższą
na odpowiedzialność karną albo naruszyć istotną tajemnicę zawodową.

Art. 110.
Sąd, zarządzając dowód z przesłuchania stron, może odebrać od nich przyrzeczenie zeznania prawdy.

Art. 111.
Dowodem mogą być również zapisy obrazu lub dźwięku oraz inne środki utrwalające albo przekazujące
informacje, uzyskane zgodnie z prawem.

Art. 112.
Strona może w wyznaczonym terminie zgłosić zarzuty do opinii biegłego; sąd może zażądać opinii
uzupełniającej albo dopuścić dowód z opinii innego biegłego.

                                         Tytuł IX. Orzeczenia

Art. 113.
Sąd rozstrzyga sprawę co do istoty wyrokiem; w innych kwestiach sąd orzeka postanowieniem.

Art. 114.
Wyrok zapada po niejawnej naradzie; sąd jest związany żądaniem i nie może orzekać co do przedmiotu
nieobjętego żądaniem ani ponad żądanie.

Art. 115.
1. Wyrok ogłasza się publicznie.
2. Uzasadnienie wyroku sporządza się na wniosek strony złożony w terminie 7 dni od ogłoszenia; termin do
wniesienia apelacji biegnie od doręczenia wyroku z uzasadnieniem.

Art. 116.
Jeżeli pozwany nie stawił się na rozprawę ani nie zajął stanowiska, sąd może wydać wyrok zaoczny;
pozwanemu przysługuje sprzeciw.

Art. 117.
Orzeczenie staje się prawomocne, jeżeli nie przysługuje od niego środek odwoławczy lub inny środek
zaskarżenia.

Art. 118.
Wyrok prawomocny korzysta z powagi rzeczy osądzonej; nie można ponownie żądać rozstrzygnięcia sprawy
prawomocnie osądzonej między tymi samymi stronami.

Art. 119.
Sąd może nadać wyrokowi rygor natychmiastowej wykonalności, w szczególności gdy zasądza świadczenie
z tytułu uznanego roszczenia albo należność z tytułu czynszu najmu.

Art. 120.
Jeżeli nadaje się do rozstrzygnięcia tylko część żądania, sąd może wydać wyrok częściowy.

Art. 121.
Sąd może wydać wyrok wstępny, uznając roszczenie za usprawiedliwione co do zasady, a o wysokości orzec
po dalszym postępowaniu.

Art. 122.
Sąd z urzędu lub na wniosek sprostuje w wyroku niedokładności, błędy pisarskie albo rachunkowe.

Art. 123.

Strona może w terminie dwóch tygodni od ogłoszenia wyroku żądać jego uzupełnienia, jeżeli sąd nie orzekł
o całości żądania.

Art. 124.
W razie wątpliwości co do treści wyroku sąd może na wniosek strony rozstrzygnąć je w drodze wykładni
wyroku.

Art. 125.
Sprzeciw od wyroku zaocznego pozwany wnosi w terminie dwóch tygodni od doręczenia mu wyroku; sąd
rozpoznaje wówczas sprawę ponownie.

Art. 126.
Sąd z urzędu nadaje wyrokowi rygor natychmiastowej wykonalności w części zasądzającej świadczenie z
tytułu wynagrodzenia za pracę oraz roszczeń alimentacyjnych.

Art. 127.
Ocena prawna wyrażona w orzeczeniu sądu drugiej instancji lub Sądu Najwyższego wiąże sąd, któremu
sprawę przekazano do ponownego rozpoznania.

                                      Tytuł X. Środki zaskarżenia

Art. 128.
Od wyroku sądu pierwszej instancji przysługuje apelacja do sądu drugiej instancji.

Art. 129.
Sąd drugiej instancji rozpoznaje sprawę w granicach apelacji; nie może uchylić lub zmienić wyroku na
niekorzyść strony wnoszącej apelację, jeżeli druga strona apelacji nie wniosła.

Art. 130.
Na postanowienia sądu pierwszej instancji kończące postępowanie oraz wskazane w ustawie przysługuje
zażalenie.

Art. 131.
1. Od prawomocnego wyroku sądu drugiej instancji przysługuje skarga kasacyjna do Sądu Najwyższego z
powodu naruszenia prawa.
2. Skarga kasacyjna jest niedopuszczalna w sprawach o prawa majątkowe, w których wartość przedmiotu
zaskarżenia nie przekracza progu określonego w ustawie.

Art. 132.
Skargę kasacyjną sporządza i podpisuje adwokat lub radca prawny (przymus zastępstwa przed Sądem
Najwyższym).

Art. 133.
Można żądać wznowienia prawomocnie zakończonego postępowania, jeżeli ujawnią się okoliczności lub
dowody, które mogłyby mieć wpływ na wynik sprawy, a strona nie mogła z nich skorzystać w poprzednim
postępowaniu, albo gdy orzeczenie oparto na przestępstwie.

Art. 134.
Apelację wnosi się w terminie dwóch tygodni od doręczenia wyroku z uzasadnieniem; apelacja powinna
wskazywać zaskarżony wyrok, zarzuty oraz wniosek o jego zmianę lub uchylenie.

Art. 135.

Zażalenie wnosi się w terminie tygodnia od doręczenia postanowienia.

Art. 136.
1. Sąd Najwyższy przyjmuje skargę kasacyjną do rozpoznania, jeżeli w sprawie występuje istotne
zagadnienie prawne, potrzeba wykładni przepisów budzących wątpliwości albo skarga jest oczywiście
uzasadniona.
2. Odmowa przyjęcia skargi kasacyjnej do rozpoznania nie wymaga szczegółowego uzasadnienia.

Art. 137.
Skargę o wznowienie postępowania wnosi się w terminie trzech miesięcy od dnia, w którym strona
dowiedziała się o podstawie wznowienia.

Art. 138.
Na orzeczenia i zarządzenia referendarza sądowego przysługuje skarga do sądu, który wydaje orzeczenie w
danej sprawie jako sąd pierwszej instancji.

Art. 139.
Sąd drugiej instancji rozpoznaje sprawę na nowo w granicach apelacji; może utrzymać wyrok w mocy,
zmienić go albo uchylić i przekazać sprawę do ponownego rozpoznania w razie nierozpoznania istoty
sprawy.

Art. 140.
Uwzględniając skargę kasacyjną, Sąd Najwyższy uchyla zaskarżony wyrok i przekazuje sprawę do
ponownego rozpoznania albo, jeżeli podstawa naruszenia prawa materialnego jest oczywiście uzasadniona,
orzeka co do istoty sprawy.

Art. 141.
Od prawomocnego wyroku, który przez swą niezgodność z prawem wyrządził stronie szkodę, przysługuje
skarga o stwierdzenie niezgodności z prawem prawomocnego orzeczenia, stanowiąca podstawę roszczenia
odszkodowawczego wobec Skarbu Państwa.

Tytuł XI. Postępowania odrębne — sprawy gospodarcze, nakazowe, upominawcze, uproszczone i
                                      elektroniczne

Art. 142.
Sprawy ze stosunków między przedsiębiorcami w zakresie prowadzonej przez nich działalności
gospodarczej rozpoznaje się w postępowaniu odrębnym w sprawach gospodarczych, z zaostrzonymi
wymaganiami co do terminowego zgłaszania twierdzeń i dowodów.

Art. 143.
1. Sąd wydaje nakaz zapłaty w postępowaniu nakazowym, jeżeli powód dochodzi roszczenia pieniężnego
udowodnionego dokumentem urzędowym, zaakceptowanym przez dłużnika rachunkiem albo wezwaniem do
zapłaty i pisemnym uznaniem długu.
2. Nakaz zapłaty stanowi tytuł zabezpieczenia wykonalny bez nadawania klauzuli wykonalności.

Art. 144.
W postępowaniu upominawczym sąd wydaje nakaz zapłaty, jeżeli roszczenie pieniężne nie jest oczywiście
bezzasadne; od nakazu pozwany może wnieść sprzeciw, który powoduje jego utratę mocy i rozpoznanie
sprawy na zasadach ogólnych.

Art. 145.

W sprawach o świadczenia nieprzekraczające progu określonego w ustawie prowadzi się postępowanie
uproszczone, w którym pismo wnosi się na urzędowym formularzu, a postępowanie dowodowe jest
ograniczone.

Art. 146.
Roszczenia pieniężne mogą być dochodzone w elektronicznym postępowaniu upominawczym,
prowadzonym za pośrednictwem systemu teleinformatycznego, we współpracy z ministrem właściwym do
spraw cyfryzacji.

            Tytuł XII. Postępowanie odrębne w sprawach o najem i opróżnienie lokalu

Art. 147.
Sprawy o roszczenia z umowy najmu lokalu, w szczególności o zapłatę czynszu oraz o opróżnienie lokalu,
rozpoznaje się według przepisów niniejszego tytułu, a w zakresie nieuregulowanym — według przepisów o
procesie.

Art. 148.
Zaległego czynszu oraz innych opłat z umowy najmu wynajmujący może dochodzić w postępowaniu
nakazowym lub upominawczym, na podstawie umowy najmu oraz wezwania do zapłaty.

Art. 149.
1. Powództwo o opróżnienie lokalu wynajmujący może wytoczyć, jeżeli najemca dopuszcza się zwłoki z
zapłatą czynszu za co najmniej dwa pełne okresy płatności albo używa lokalu w sposób sprzeczny z umową
lub jego przeznaczeniem.
2. Warunkiem wytoczenia powództwa z powodu zaległości jest uprzednie pisemne wypowiedzenie najmu z
wyznaczeniem najemcy dodatkowego, co najmniej miesięcznego terminu do zapłaty zaległości.

Art. 150.
1. W wyroku nakazującym opróżnienie lokalu mieszkalnego sąd orzeka o uprawnieniu osoby do lokalu
socjalnego albo o jego braku.
2. Sąd nie może orzec o braku uprawnienia do lokalu socjalnego wobec kobiety ciężarnej, małoletniego,
osoby niepełnosprawnej, obłożnie chorej ani osoby w podeszłym wieku pozostającej w niedostatku, chyba że
osoby te mają zapewniony inny lokal.

Art. 151.
Nie orzeka się opróżnienia lokalu mieszkalnego bez wskazania lokalu, do którego ma nastąpić
przekwaterowanie; komornik wstrzymuje wykonanie opróżnienia do czasu zapewnienia lokalu socjalnego,
zamiennego albo tymczasowego pomieszczenia.

Art. 152.
1. Opróżnienia lokalu mieszkalnego nie wykonuje się w okresie od 1 listopada do 31 marca wobec osoby,
która nie ma zapewnionego innego lokalu.
2. Ograniczenia, o którym mowa w ust. 1, nie stosuje się, jeżeli przyczyną opróżnienia jest stosowanie
przemocy wobec domowników.

Art. 153.
Przepisów o ochronie najemcy nie stosuje się do lokali użytkowych; opróżnienie lokalu użytkowego
następuje bez orzekania o lokalu socjalnym.

Art. 154.

Za okres zajmowania lokalu bez tytułu prawnego osoba zajmująca obowiązana jest do zapłaty
odszkodowania odpowiadającego czynszowi, jaki wynajmujący mógłby otrzymać z tytułu najmu lokalu.

Art. 155.
Obowiązek zapewnienia lokalu socjalnego osobie uprawnionej wyrokiem ciąży na gminie właściwej ze
względu na położenie lokalu podlegającego opróżnieniu.

Art. 156.
Wypowiedzenie umowy najmu lokalu mieszkalnego wymaga formy pisemnej i wskazania przyczyny;
terminy wypowiedzenia określa ustawa.

Art. 157.
Po zakończeniu najmu wynajmujący rozlicza z najemcą wpłaconą kaucję, potrącając należności wynikające
z umowy.

              Tytuł XIII. Postępowanie odrębne w sprawach z zakresu prawa pracy

Art. 158.
Sprawy o roszczenia ze stosunku pracy rozpoznaje się w postępowaniu odrębnym, z uwzględnieniem
ochrony pracownika jako strony słabszej.

Art. 159.
W sprawach z zakresu prawa pracy pracownik może dochodzić roszczeń bez ponoszenia opłat sądowych, w
granicach określonych w ustawie.

Art. 160.
Zawezwanie do próby ugodowej oraz mediacja są w sprawach pracowniczych szczególnie zalecane; sąd
dąży do ugodowego rozstrzygnięcia sporu.

Art. 161.
W sprawach o uznanie wypowiedzenia za bezskuteczne lub o przywrócenie do pracy sąd rozpoznaje sprawę
w pierwszej kolejności.

Art. 162.
Sprawy o roszczenia konsumentów przeciwko przedsiębiorcom rozpoznaje się z uwzględnieniem przepisów
o ochronie konsumenta; sąd bada z urzędu, czy postanowienie umowne nie jest niedozwolone.

                              Tytuł XIV. Dalsze postępowania odrębne

Art. 163.
Grupa co najmniej dziesięciu osób dochodzących roszczeń jednego rodzaju, opartych na takiej samej
podstawie faktycznej, może dochodzić ich w postępowaniu grupowym prowadzonym przez reprezentanta
grupy.

Art. 164.
W postępowaniu o uznanie postanowień wzorca umowy za niedozwolone sąd bada, czy postanowienie
stosowane przez przedsiębiorcę wobec konsumentów kształtuje ich prawa w sposób sprzeczny z dobrymi
obyczajami, rażąco naruszając ich interesy.

Art. 165.
1. Sprawy o naruszenie posiadania rozpoznaje się w postępowaniu odrębnym.

2. W sprawach tych sąd bada jedynie ostatni stan posiadania oraz fakt jego naruszenia, nie rozpoznając
samego prawa do rzeczy.

Art. 166.
Sprawy o roszczenia wynikające z czynności bankowych oraz z obrotu instrumentami finansowymi
rozpoznaje się z uwzględnieniem przepisów szczególnych.

Art. 167.
Sprawy o ochronę praw autorskich, praw pokrewnych oraz praw własności przemysłowej rozpoznaje się w
postępowaniu odrębnym w sprawach własności intelektualnej, w którym sąd może zarządzić zabezpieczenie
środków dowodowych oraz wyjawienie informacji o naruszeniu.

                 KSIĘGA II — POSTĘPOWANIE NIEPROCESOWE

Art. 168.
W postępowaniu nieprocesowym rozpoznaje się sprawy wskazane w ustawie; postępowanie wszczyna się na
wniosek, a w przypadkach określonych w ustawie — z urzędu.

Art. 169.
Uczestnikiem postępowania jest wnioskodawca oraz każdy, czyich praw dotyczy wynik postępowania.

Art. 170.
W sprawach nieprocesowych sąd orzeka postanowieniem co do istoty sprawy.

Art. 171.
Sąd stwierdza nabycie spadku na wniosek osoby mającej w tym interes, oznaczając spadkobierców oraz
przypadające im udziały.

Art. 172.
Sąd orzeka o ubezwłasnowolnieniu całkowitym albo częściowym po zbadaniu stanu osoby, której wniosek
dotyczy, i po jej wysłuchaniu.

Art. 173.
Sąd orzeka o zniesieniu współwłasności, dokonując podziału rzeczy wspólnej, przyznając ją jednemu z
uczestników ze spłatą albo zarządzając jej sprzedaż.

Art. 174.
Sąd rozpoznaje sprawy o złożenie przedmiotu świadczenia do depozytu sądowego oraz o zwrot depozytu.

Art. 175.
Sąd orzeka o uznaniu za zmarłego oraz o stwierdzeniu zgonu na zasadach określonych w ustawie.

Art. 176.
Sprawy z zakresu prowadzenia ksiąg wieczystych rozpoznaje sąd wieczystoksięgowy; wpisu dokonuje się na
wniosek, na podstawie dokumentów uzasadniających wpis.

Art. 177.
Sąd stwierdza nabycie własności przez zasiedzenie, oznaczając osobę, która nabyła własność, oraz
nieruchomość lub rzecz.

Art. 178.

Od postanowień co do istoty sprawy wydanych w postępowaniu nieprocesowym przysługuje apelacja.

Art. 179.
W sprawach, które mogą być wszczęte z urzędu, sąd wszczyna postępowanie, gdy poweźmie wiadomość o
okolicznościach uzasadniających jego wszczęcie.

Art. 180.
Sąd może zarządzić sporządzenie spisu inwentarza majątku spadkowego oraz ustanowić zarząd majątku,
jeżeli wymaga tego ochrona praw uczestników.

Art. 181.
Jeżeli krąg uczestników nie jest znany, sąd może zarządzić ogłoszenie wzywające zainteresowanych do
udziału w sprawie.

Art. 182.
Sąd rozpoznaje sprawy o rozgraniczenie nieruchomości oraz o ustanowienie służebności drogi koniecznej.

Art. 183.
Sąd rozstrzyga w postępowaniu nieprocesowym sprawy dotyczące zarządu rzeczą wspólną oraz sposobu
korzystania z niej przez współwłaścicieli.

Art. 184.
Sąd wydaje zezwolenie na złożenie przedmiotu świadczenia do depozytu sądowego oraz orzeka o jego
wydaniu uprawnionemu.

Art. 185.
Sprawy o wpis do rejestrów przedsiębiorców, stowarzyszeń i fundacji rozpoznaje sąd rejestrowy; wpisu
dokonuje się na wniosek albo z urzędu na podstawie ustawy.

Art. 186.
W postępowaniu nieprocesowym każdy uczestnik ponosi koszty związane ze swoim udziałem w sprawie,
chyba że sąd postanowi inaczej ze względu na sprzeczność interesów.

            CZĘŚĆ DRUGA — POSTĘPOWANIE ZABEZPIECZAJĄCE

Art. 187.
Każda strona lub uczestnik może żądać udzielenia zabezpieczenia, jeżeli uprawdopodobni roszczenie oraz
interes prawny w udzieleniu zabezpieczenia.

Art. 188.
Interes prawny istnieje, gdy brak zabezpieczenia uniemożliwi lub poważnie utrudni wykonanie zapadłego
orzeczenia albo osiągnięcie celu postępowania.

Art. 189.
Zabezpieczenia można żądać przed wszczęciem postępowania oraz w jego toku; udzielając zabezpieczenia
przed wszczęciem sprawy, sąd wyznacza termin do jej wytoczenia.

Art. 190.
Zabezpieczenie roszczeń pieniężnych następuje w szczególności przez zajęcie ruchomości, wynagrodzenia,
rachunku bankowego albo przez obciążenie nieruchomości hipoteką przymusową.

Art. 191.
Zabezpieczenie roszczeń niepieniężnych następuje w sposób odpowiedni do okoliczności, w tym przez
unormowanie praw i obowiązków stron na czas postępowania.

Art. 192.
Sąd uchyli lub zmieni zabezpieczenie, jeżeli odpadnie lub zmieni się przyczyna jego udzielenia.

Art. 193.
Zabezpieczenie upada, jeżeli uprawniony nie wytoczył sprawy w wyznaczonym terminie albo orzeczenie
oddalające roszczenie stało się prawomocne.

Art. 194.
Sposób zabezpieczenia oznacza sąd, biorąc pod uwagę interesy stron w takiej mierze, aby uprawnionemu
zapewnić należytą ochronę prawną, a obowiązanego nie obciążać ponad potrzebę.

Art. 195.
Zabezpieczenie nie może zmierzać do zaspokojenia roszczenia, chyba że ustawa stanowi inaczej.

Art. 196.
Jeżeli zabezpieczenie okazało się nieuzasadnione, obowiązanemu przysługuje przeciwko uprawnionemu
roszczenie o naprawienie szkody wyrządzonej wykonaniem zabezpieczenia.

              CZĘŚĆ TRZECIA — POSTĘPOWANIE EGZEKUCYJNE

                                  Tytuł I. Organy i tytuł wykonawczy

Art. 197.
Organami egzekucyjnymi są komornik sądowy oraz sąd; egzekucję prowadzi się na wniosek wierzyciela.

Art. 198.
Komornik sądowy jest funkcjonariuszem działającym przy sądzie rejonowym; wykonuje orzeczenia i inne
tytuły wykonawcze oraz przeprowadza czynności egzekucyjne w sposób bezstronny.

Art. 199.
Podstawą egzekucji jest tytuł wykonawczy, którym jest tytuł egzekucyjny (w szczególności prawomocne
orzeczenie, ugoda sądowa, akt notarialny, w którym dłużnik poddał się egzekucji) zaopatrzony w klauzulę
wykonalności.

Art. 200.
Klauzulę wykonalności nadaje sąd; od chwili jej nadania wierzyciel może żądać wszczęcia egzekucji.

Art. 201.
Dłużnik może w drodze powództwa żądać pozbawienia tytułu wykonawczego wykonalności, jeżeli
zaprzecza zdarzeniom, na których oparto klauzulę, albo jeżeli zobowiązanie wygasło (powództwo
przeciwegzekucyjne).

Art. 202.
Osoba trzecia może w drodze powództwa żądać zwolnienia zajętego przedmiotu spod egzekucji, jeżeli
skierowanie do niego egzekucji narusza jej prawa.

Art. 203.

Egzekucję wszczyna się na wniosek wierzyciela zawierający tytuł wykonawczy oraz wskazanie świadczenia
i sposobu egzekucji; wierzyciel może zlecić komornikowi poszukiwanie majątku dłużnika.

Art. 204.
Postępowanie egzekucyjne zawiesza się na wniosek wierzyciela oraz w innych przypadkach określonych w
ustawie; zawieszone postępowanie podejmuje się na wniosek.

Art. 205.
Postępowanie egzekucyjne umarza się w całości lub w części, jeżeli egzekucja stała się niedopuszczalna,
wierzyciel ją cofnął albo okazała się bezskuteczna.

Art. 206.
Koszty egzekucji obciążają dłużnika; komornik ustala je w postanowieniu, na które przysługuje skarga do
sądu.

Art. 207.
Jeżeli egzekucja okazała się bezskuteczna, wierzyciel może żądać zobowiązania dłużnika do złożenia
wykazu majątku oraz przyrzeczenia, że wykaz jest prawdziwy i zupełny (wyjawienie majątku).

Art. 208.
Na czynności komornika przysługuje skarga do sądu rejonowego.

Art. 209.
Klauzulę wykonalności można nadać także przeciwko następcy prawnemu dłużnika oraz, w granicach
określonych w ustawie, przeciwko małżonkowi dłużnika co do majątku wspólnego.

Art. 210.
Jeżeli tytuł egzekucyjny obejmuje świadczenie zależne od zdarzenia, które wierzyciel powinien udowodnić,
klauzulę wykonalności nadaje się po wykazaniu tego zdarzenia dokumentem.

Art. 211.
Sąd sprawuje nadzór nad zgodnością z prawem czynności komornika i może wydawać mu zarządzenia w
toku egzekucji.

Art. 212.
W razie wytoczenia powództwa przeciwegzekucyjnego sąd może zawiesić postępowanie egzekucyjne albo
ograniczyć zakres egzekucji.

                             Tytuł II. Egzekucja świadczeń pieniężnych

Art. 213.
Egzekucję świadczeń pieniężnych prowadzi się z ruchomości, z wynagrodzenia za pracę, z rachunków
bankowych, z innych wierzytelności i praw majątkowych oraz z nieruchomości.

Art. 214.
Zajęcia ruchomości dokonuje komornik przez wpisanie ich do protokołu zajęcia; zajęte ruchomości
sprzedaje się w drodze licytacji publicznej.

Art. 215.
Egzekucja z wynagrodzenia za pracę oraz ze świadczeń pieniężnych podlega ograniczeniom określonym w
ustawie; wolna od zajęcia jest kwota niezbędna do utrzymania dłużnika i osób pozostających na jego
utrzymaniu.

Art. 216.
Egzekucja z nieruchomości obejmuje jej zajęcie, opis i oszacowanie oraz sprzedaż w drodze licytacji, a
następnie podział sumy uzyskanej z egzekucji między wierzycieli.

Art. 217.
Nie podlegają egzekucji przedmioty urządzenia domowego, narzędzia i przedmioty niezbędne do pracy
zarobkowej oraz inne przedmioty wskazane w ustawie, konieczne dla dłużnika i jego rodziny.

Art. 218.
Egzekucja z wierzytelności następuje przez jej zajęcie oraz zakaz wypłaty przez dłużnika zajętej
wierzytelności do rąk dłużnika egzekwowanego.

Art. 219.
Egzekucja z rachunku bankowego następuje przez zajęcie wierzytelności z rachunku; wolna od zajęcia jest
kwota niezbędna dla utrzymania określona w ustawie.

Art. 220.
W razie zbiegu egzekucji sądowej i administracyjnej do tej samej rzeczy lub prawa dalszą egzekucję
prowadzi organ wskazany według zasad określonych w ustawie.

Art. 221.
Zajęte ruchomości sprzedaje się w drodze licytacji publicznej; nabywca staje się właścicielem z chwilą
uprawomocnienia się przybicia i zapłaty ceny.

Art. 222.
Sumę uzyskaną z egzekucji dzieli się między wierzycieli według sporządzonego przez organ egzekucyjny
planu podziału, z uwzględnieniem kolejności zaspokojenia określonej w ustawie.

Art. 223.
Egzekucja z nieruchomości obejmuje jej zajęcie, opis i oszacowanie, licytację, przybicie oraz przysądzenie
własności na rzecz nabywcy.

Art. 224.
Roszczenia alimentacyjne oraz należności za pracę zaspokaja się z pierwszeństwem przed innymi
należnościami.

Art. 225.
W egzekucji świadczeń alimentacyjnych komornik z urzędu ustala majątek i źródła dochodu dłużnika; przy
tych świadczeniach ograniczenia egzekucji z wynagrodzenia stosuje się w węższym zakresie określonym w
ustawie.

Art. 226.
Egzekucja z innych praw majątkowych, w tym z udziałów, akcji oraz praw własności intelektualnej,
następuje przez ich zajęcie i realizację na zasadach określonych w ustawie.

Art. 227.
Egzekucja ze świadczeń emerytalnych i rentowych podlega ograniczeniom; wolna od zajęcia jest kwota
określona w ustawie.

Art. 228.
Na postanowienie o przybiciu oraz o przysądzeniu własności przysługuje zażalenie; przysądzenie własności
przenosi własność na nabywcę i stanowi tytuł do ujawnienia go w księdze wieczystej.

Art. 229.
Za zgodą stron oraz w przypadkach określonych w ustawie zajęte przedmioty można sprzedać z wolnej ręki
po cenie nie niższej niż oszacowanie.

                            Tytuł III. Egzekucja świadczeń niepieniężnych

Art. 230.
Egzekucja świadczeń niepieniężnych obejmuje wydanie rzeczy ruchomej, wydanie nieruchomości,
opróżnienie lokalu oraz wykonanie czynności, którą może wykonać inna osoba na koszt dłużnika.

Art. 231.
1. Wykonując opróżnienie lokalu mieszkalnego, komornik usuwa z niego dłużnika i jego rzeczy oraz
wprowadza wierzyciela w posiadanie.
2. Komornik wstrzymuje się z wykonaniem opróżnienia lokalu mieszkalnego do czasu zapewnienia osobie
eksmitowanej lokalu socjalnego, zamiennego albo tymczasowego pomieszczenia, z zachowaniem ograniczeń
przewidzianych w Kodeksie.

Art. 232.
Jeżeli dłużnik nie wykonuje czynności, której nie może za niego wykonać inna osoba, sąd może nałożyć na
niego grzywnę w celu przymuszenia albo orzec inne środki określone w ustawie.

Art. 233.
Egzekucja wydania rzeczy ruchomej następuje przez odebranie jej dłużnikowi i wydanie wierzycielowi;
egzekucja wydania nieruchomości — przez wprowadzenie wierzyciela w posiadanie.

Art. 234.
W celu zaspokojenia świadczeń pieniężnych z dochodów nieruchomości sąd może ustanowić zarząd
przymusowy nad nieruchomością.

Art. 235.
Czynność, którą może wykonać inna osoba, może być na wniosek wierzyciela wykonana na koszt dłużnika
(wykonanie zastępcze).

              CZĘŚĆ CZWARTA — SĄD POLUBOWNY (ARBITRAŻ)

Art. 236.
Strony mogą poddać pod rozstrzygnięcie sądu polubownego spory o prawa majątkowe oraz spory o prawa
niemajątkowe mogące być przedmiotem ugody, z wyłączeniem spraw zastrzeżonych dla sądów
państwowych.

Art. 237.
Poddanie sporu pod rozstrzygnięcie sądu polubownego następuje przez umowę stron (zapis na sąd
polubowny), która powinna być sporządzona na piśmie.

Art. 238.
Strony ustalają liczbę arbitrów i sposób ich powołania; arbiter powinien być bezstronny i niezależny.

Art. 239.
Sąd polubowny rozstrzyga spór wyrokiem; wyrok powinien zawierać uzasadnienie i podpisy arbitrów.

Art. 240.
Wyrok sądu polubownego może być uchylony przez sąd państwowy wyłącznie z przyczyn określonych w
ustawie, w szczególności w razie braku ważnego zapisu albo sprzeczności wyroku z podstawowymi
zasadami porządku prawnego.

Art. 241.
Wyrok sądu polubownego oraz ugoda przed nim zawarta, po uznaniu albo stwierdzeniu wykonalności przez
sąd państwowy, mają moc równą wyrokowi sądu państwowego.

Art. 242.
Przed sądem polubownym strony są traktowane równo i każda z nich ma prawo przedstawienia swojego
stanowiska oraz dowodów.

Art. 243.
Sąd polubowny dąży do ugodowego zakończenia sporu; ugodę zawartą przed nim zamieszcza się w wyroku.

Art. 244.
O kosztach postępowania przed sądem polubownym rozstrzyga ten sąd w wyroku.

Art. 245.
Arbiter może być wyłączony, jeżeli zachodzą okoliczności budzące uzasadnione wątpliwości co do jego
bezstronności lub niezależności.

Art. 246.
Postępowanie przed sądem polubownym jest poufne, chyba że strony postanowią inaczej.

Art. 247.
Jeżeli strony nie oznaczyły terminu, sąd polubowny wydaje wyrok bez nieuzasadnionej zwłoki.

                       CZĘŚĆ PIĄTA — PRZEPISY KOŃCOWE

