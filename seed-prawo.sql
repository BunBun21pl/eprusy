Art. 10.
Przestępstwa ściga się z oskarżenia publicznego, z oskarżenia prywatnego albo na wniosek, na zasadach
określonych w ustawie.

                                    Rozdział 2. Przesłanki procesowe

Art. 11.

Nie wszczyna się postępowania, a wszczęte umarza, gdy:
    1) czynu nie popełniono albo brak jest jego ustawowych znamion;
    2) społeczna szkodliwość czynu jest znikoma;
    3) sprawca nie podlega karze;
    4) nastąpiło przedawnienie karalności;
    5) postępowanie co do tego samego czynu tej samej osoby zostało prawomocnie zakończone albo toczy
    się;
    6) oskarżony zmarł;
    7) brak jest wymaganej skargi, wniosku lub zezwolenia na ściganie;
    8) sprawca jest objęty immunitetem.

                              Rozdział 3. Doręczenia, terminy i protokoły

Art. 12.
Pisma doręcza się adresatom za pokwitowaniem; w wypadkach określonych w ustawie dopuszcza się
doręczenie elektroniczne.

Art. 13.
1. Czynność dokonaną po upływie terminu uważa się za bezskuteczną.
2. Jeżeli uchybienie terminowi nastąpiło z przyczyn niezależnych od strony, sąd na jej wniosek przywraca
termin.

Art. 14.
Z każdej czynności procesowej mającej znaczenie dla sprawy sporządza się protokół; przebieg czynności
można nadto utrwalać za pomocą urządzeń rejestrujących obraz lub dźwięk.

Art. 15.
Strony mają prawo przeglądać akta sprawy i sporządzać z nich odpisy, na zasadach określonych w ustawie.

                                               DZIAŁ II
                                                      SĄD

                                     Rozdział 1. Właściwość sądów

Art. 16.
W sprawach karnych orzekają: sąd rejonowy, sąd okręgowy, sąd apelacyjny oraz Sąd Najwyższy.

Art. 17.
1. Sąd rejonowy działa w każdym powiecie.
2. Sąd okręgowy działa w siedzibie każdej rejencji.

Art. 18.
Postępowanie karne odbywa się w trzech instancjach.

Art. 19.
W pierwszej instancji orzeka sąd rejonowy, z wyjątkiem spraw zastrzeżonych dla sądu okręgowego.

Art. 20.
W pierwszej instancji sąd okręgowy orzeka w sprawach:
    1) o zbrodnie;
    2) o występki zagrożone karą pozbawienia wolności powyżej 8 lat;
    3) określonych w Kodeksie karnym ciężkim;
    4) innych wskazanych w ustawie ze względu na ich wagę lub zawiłość.

Art. 21.
W drugiej instancji sąd apelacyjny rozpoznaje apelacje od wyroków sądów rejonowych i okręgowych.

Art. 22.
W trzeciej instancji Sąd Najwyższy rozpoznaje kasacje od prawomocnych wyroków sądów apelacyjnych.

Art. 23.
Sąd Najwyższy orzeka ponadto w sprawach zastrzeżonych Konstytucją i ustawami, w tym o ważności
wyborów oraz referendum, na zasadach określonych w Kodeksie wyborczym.

Art. 24.
Właściwym miejscowo jest sąd, w którego okręgu popełniono przestępstwo; spory o właściwość rozstrzyga
sąd wyższego rzędu.

                             Rozdział 2. Skład sądu i wyłączenie sędziego

Art. 25.
1. Na rozprawie sąd orzeka jednoosobowo.
2. W sprawach o zbrodnie, występowania dużej zawiłości oraz w postępowaniu odwoławczym sąd orzeka w
składzie trzech sędziów, chyba że ustawa stanowi inaczej.
3. W sprawach, gdzie jest możliwość wymierzenia kary dożywotniego pozbawienia wolności sąd orzeka w
składzie pięciu sędziów.

Art. 26.
Sędzia jest z mocy prawa wyłączony od udziału w sprawie, w której jest stroną, osobą najbliższą strony, brał
udział w niższej instancji albo zachodzi inna okoliczność mogąca wywołać wątpliwość co do jego
bezstronności.

                                              DZIAŁ III
                            STRONY, OBROŃCY I PEŁNOMOCNICY

Art. 27.
Stronami postępowania są oskarżyciel oraz oskarżony; w postępowaniu przygotowawczym stronami są
pokrzywdzony i podejrzany.

Art. 28.
Oskarżycielem publicznym jest prokurator, na czele którego pionu stoi Prokurator Generalny (art. 111–112
Konstytucji).

Art. 29.

Pokrzywdzonym jest osoba, której dobro prawne zostało bezpośrednio naruszone lub zagrożone przez
przestępstwo.

Art. 30.
Pokrzywdzony może działać jako oskarżyciel posiłkowy obok oskarżyciela publicznego.

Art. 31.
W sprawach o przestępstwa ścigane z oskarżenia prywatnego pokrzywdzony wnosi i popiera oskarżenie jako
oskarżyciel prywatny.

Art. 32.
1. Podejrzanym jest osoba, wobec której wydano postanowienie o przedstawieniu zarzutów.
2. Oskarżonym jest osoba, przeciwko której wniesiono do sądu akt oskarżenia.

Art. 33.
Oskarżony nie ma obowiązku dowodzenia swojej niewinności ani dostarczania dowodów na swoją
niekorzyść; może odmówić wyjaśnień i odpowiedzi na pytania.

Art. 34.
1. Obrońcą może być wyłącznie adwokat.
2. Oskarżony może mieć jednocześnie nie więcej niż trzech obrońców.

Art. 35.
Oskarżony musi mieć obrońcę, jeżeli nie ukończył 21 lat, jest niepełnosprawny w stopniu utrudniającym
obronę, sprawa dotyczy zbrodni określonej w Kodeksie karnym ciężkim albo jest zagrożona karą
dożywotniego pozbawienia wolności lub karą śmierci.

Art. 36.
Oskarżonemu, który nie jest w stanie ponieść kosztów obrony, wyznacza się obrońcę z urzędu.

Art. 37.
Pokrzywdzony oraz strony inne niż oskarżony mogą ustanowić pełnomocnika.

Art. 38.
Pełnomocnikiem może być adwokat lub radca prawny.

Art. 39.
Pokrzywdzonemu przysługuje prawo do informacji o przebiegu postępowania, udziału w czynnościach
sądowych, składania wniosków dowodowych oraz żądania naprawienia szkody.

Art. 40.
Za pokrzywdzonego małoletniego lub nieporadnego prawa wykonuje jego przedstawiciel ustawowy albo
osoba, pod której stałą pieczą pozostaje.

Art. 41.
1. Pociągnięcie do odpowiedzialności karnej lub pozbawienie wolności osoby objętej immunitetem wymaga
uprzedniej zgody właściwego organu.
2. Zgody na pociągnięcie sędziego do odpowiedzialności karnej udziela właściwy sąd dyscyplinarny (art.
103 Konstytucji), a posła albo senatora — odpowiednio Rada Narodowa albo Senat Narodowy (art. 57
Konstytucji).

                                              DZIAŁ IV
                                              DOWODY

                                      Rozdział 1. Przepisy ogólne

Art. 42.
Przedmiotem dowodu są fakty mające znaczenie dla rozstrzygnięcia sprawy.

Art. 43.
Ciężar udowodnienia winy spoczywa na oskarżycielu.

Art. 44.
Dowody przeprowadza się na wniosek stron albo z urzędu.

                                     Rozdział 2. Środki dowodowe

Art. 45.
Oskarżony ma prawo składać wyjaśnienia; może jednak bez podania powodów odmówić ich złożenia.

Art. 46.
1. Świadek ma obowiązek zeznawać prawdę; przed przesłuchaniem uprzedza się go o odpowiedzialności
karnej za fałszywe zeznania.
2. Osoba najbliższa dla oskarżonego może odmówić zeznań.

Art. 47.
Świadkowi, którego życiu, zdrowiu lub wolności zagraża niebezpieczeństwo, można zapewnić ochronę, w
tym zachowanie w tajemnicy jego danych (świadek anonimowy).

Art. 48.
Pokrzywdzonemu oraz świadkowi, którym w związku z postępowaniem zagraża niebezpieczeństwo, można
zapewnić ochronę osobistą oraz pomoc, w tym zmianę miejsca pobytu, na zasadach określonych w ustawie.

Art. 49.
Jeżeli stwierdzenie okoliczności wymaga wiadomości specjalnych, zasięga się opinii biegłego.

Art. 50.
W celu ujawnienia śladów i dowodów dokonuje się oględzin oraz, w razie potrzeby, eksperymentu
procesowego.

Art. 51.
Dowodami są także dokumenty, opinie, oględziny rzeczy oraz inne dowody rzeczowe.

Art. 52.
Przesłuchanie rozpoczyna się od zapytania o to, co osobie przesłuchiwanej wiadomo w sprawie; następnie
zadaje się pytania. Zabronione jest zadawanie pytań sugerujących odpowiedź oraz stosowanie przymusu.

Art. 53.
W razie sprzeczności w oświadczeniach można przeprowadzić konfrontację przesłuchiwanych osób.

Art. 54.
W celu rozpoznania osoby lub rzeczy można zarządzić okazanie; dokonuje się go w warunkach
wyłączających sugestię.

Art. 55.
W razie podejrzenia przestępnego spowodowania śmierci przeprowadza się oględziny i otwarcie zwłok.

Art. 56.
Kontrola i utrwalanie treści rozmów telefonicznych oraz innych przekazów są dopuszczalne wyłącznie na
podstawie postanowienia sądu, wydanego na wniosek prokuratora, w sprawach o poważne przestępstwa.

Art. 57.
Wobec sprawcy współdziałającego, który ujawnił organom istotne okoliczności przestępstwa oraz osoby w
nim uczestniczące, sąd może zastosować nadzwyczajne złagodzenie kary albo odstąpić od jej wymierzenia
(świadek koronny), na zasadach określonych w ustawie.

                                   Rozdział 3. Zakazy dowodowe

Art. 58.
Nie może stanowić dowodu wyjaśnienie, zeznanie ani oświadczenie uzyskane wbrew zakazom, w
szczególności w warunkach wyłączających swobodę wypowiedzi lub z zastosowaniem przymusu, groźby
albo tortur.

Art. 59.
1. Nie wolno przesłuchiwać obrońcy co do faktów, o których dowiedział się udzielając pomocy prawnej
(tajemnica obrończa).
2. Osoby zobowiązane do zachowania tajemnicy zawodowej lub państwowej mogą być przesłuchane co do
jej treści tylko po zwolnieniu z niej na zasadach określonych w ustawie.

Art. 60.
Nie wolno zastępować wyjaśnień oskarżonego lub zeznań świadka treścią pism, zapisków lub notatek
urzędowych.

                           Rozdział 4. Przeszukanie i zatrzymanie rzeczy

Art. 61.
Przeszukania pomieszczeń i osób dokonuje się na podstawie postanowienia, z poszanowaniem godności
osób oraz nienaruszalności mieszkania (art. 22 Konstytucji).

Art. 62.
Zatrzymanie rzeczy, kontrola i utrwalanie treści korespondencji oraz rozmów następują na zasadach
określonych w ustawie, a w wypadkach w niej wskazanych — za zgodą sądu.

                                             DZIAŁ V
                                      ŚRODKI PRZYMUSU

Art. 63.
1. Osobę podejrzaną można zatrzymać na czas nieprzekraczający 48 godzin.

2. Zatrzymanemu przysługuje prawo do kontaktu z obrońcą oraz do zaskarżenia zatrzymania do sądu; po
upływie terminu zatrzymanego zwalnia się albo przekazuje sądowi z wnioskiem o tymczasowe aresztowanie.

Art. 64.
Tymczasowe aresztowanie stosuje wyłącznie sąd, na wniosek prokuratora.

Art. 65.
Tymczasowe aresztowanie oraz pozostałe środki zapobiegawcze można stosować w celu zabezpieczenia
prawidłowego toku postępowania, gdy zachodzi uzasadniona obawa ucieczki, ukrywania się, matactwa albo
gdy grozi surowa kara; aresztowanie stosuje się jako środek ostateczny.

Art. 66.
Czas trwania tymczasowego aresztowania oraz jego przedłużenie podlegają kontroli sądu; areszt uchyla się
niezwłocznie po ustaniu przesłanek.

Art. 67.
Zamiast tymczasowego aresztowania stosuje się w miarę możliwości środki wolnościowe: poręczenie
majątkowe, poręczenie społeczne, dozór policji, zawieszenie w czynnościach, zakaz opuszczania kraju lub
zakaz zbliżania się do określonych osób.

Art. 68.
W celu zabezpieczenia grożących kar majątkowych i roszczeń o naprawienie szkody można orzec
zabezpieczenie majątkowe na mieniu oskarżonego.

Art. 69.
Wobec oskarżonego ukrywającego się można wydać list gończy; osobie przebywającej za granicą można
wydać list żelazny zapewniający odpowiadanie z wolnej stopy.

Art. 70.
Świadka lub oskarżonego, który bez usprawiedliwienia nie stawia się na wezwanie, można zatrzymać i
przymusowo doprowadzić.

Art. 71.
Na osobę, która bez usprawiedliwienia nie stawia się, samowolnie wydala się albo narusza powagę
czynności sądowych, sąd lub prokurator może nałożyć karę porządkową.

Art. 72.
1. Oskarżonego można poddać badaniom psychologicznym i psychiatrycznym; w razie potrzeby sąd może
orzec jego obserwację w zakładzie leczniczym na czas oznaczony, nie dłuższy niż określony w ustawie.
2. Od oskarżonego oraz, w niezbędnym zakresie, od innych osób można pobrać odciski, wymaz ze śluzówki,
krew lub inne próbki w celu przeprowadzenia badań, w tym badań kodu genetycznego (DNA).

                                             DZIAŁ VI
                            POSTĘPOWANIE PRZYGOTOWAWCZE

Art. 73.
Celem postępowania przygotowawczego jest ustalenie, czy popełniono przestępstwo, wykrycie sprawcy oraz
zebranie i zabezpieczenie dowodów.

Art. 74.
Postępowanie przygotowawcze prowadzi się w formie śledztwa albo dochodzenia.

Art. 75.
Postępowanie przygotowawcze prowadzi lub nadzoruje prokurator; dochodzenie może prowadzić Policja
pod nadzorem prokuratora.

Art. 76.
Postępowanie wszczyna się z urzędu albo wskutek zawiadomienia o popełnieniu przestępstwa.

Art. 77.
Jeżeli dane uzasadniają dostatecznie podejrzenie popełnienia czynu przez określoną osobę, wydaje się
postanowienie o przedstawieniu zarzutów.

Art. 78.
Podejrzanemu przysługuje prawo dostępu do akt, składania wniosków dowodowych oraz korzystania z
pomocy obrońcy.

Art. 79.
Postępowanie umarza się, gdy zachodzi przesłanka procesowa albo brak dostatecznych podstaw do
oskarżenia; można je również zawiesić z powodu długotrwałej przeszkody.

Art. 80.
Zawieszone postępowanie podejmuje się niezwłocznie po ustaniu przeszkody, która była przyczyną
zawieszenia.

Art. 81.
W toku postępowania można, za zgodą pokrzywdzonego i podejrzanego, skierować sprawę do mediacji
prowadzonej przez bezstronnego mediatora.

Art. 82.
Po zamknięciu postępowania prokurator wnosi do właściwego sądu akt oskarżenia albo kieruje inny wniosek
kończący postępowanie.

Art. 83.
1. Śledztwo powinno być ukończone w terminie 3 miesięcy; w sprawach zawiłych właściwy prokurator
może przedłużyć ten okres.
2. Dochodzenie kończy się w terminie 2 miesięcy, z możliwością przedłużenia na zasadach określonych w
ustawie.

Art. 84.
1. W razie powtórnego umorzenia postępowania przygotowawczego albo odmowy jego wszczęcia
pokrzywdzony może samodzielnie wnieść do sądu akt oskarżenia (subsydiarny akt oskarżenia).
2. Subsydiarny akt oskarżenia sporządza i podpisuje adwokat lub radca prawny.

                                             DZIAŁ VII
                 POSTĘPOWANIE PRZED SĄDEM PIERWSZEJ INSTANCJI

Art. 85.

Prezes sądu dokonuje wstępnej kontroli aktu oskarżenia pod względem formalnym i kieruje sprawę na
rozprawę.

Art. 86.
O terminie rozprawy zawiadamia się strony, obrońców, pełnomocników oraz świadków.

Art. 87.
1. Rozprawa jest jawna.
2. Sąd wyłącza jawność w całości lub w części, jeżeli jawność mogłaby naruszyć dobre obyczaje,
bezpieczeństwo państwa, porządek publiczny albo ważny interes prywatny.

Art. 88.
Rozprawę rozpoczyna wywołanie sprawy oraz odczytanie aktu oskarżenia.

Art. 89.
W toku przewodu sądowego przeprowadza się dowody, przesłuchuje oskarżonego, świadków i biegłych oraz
ujawnia dokumenty.

Art. 90.
Po zamknięciu przewodu sądowego przewodniczący udziela głosu stronom; oskarżonemu przysługuje prawo
ostatniego słowa.

Art. 91.
Sąd wyrokuje po niejawnej naradzie; wyrok zapada większością głosów.

Art. 92.
1. Sąd wydaje wyrok skazujący, uniewinniający albo umarzający postępowanie.
2. Wyrok ogłasza się publicznie, a następnie sporządza jego uzasadnienie na zasadach określonych w
ustawie.

Art. 93.
Sąd jest związany granicami czynu zarzucanego w akcie oskarżenia, nie jest jednak związany jego
kwalifikacją prawną.

Art. 94.
Pokrzywdzony może dochodzić w postępowaniu karnym roszczeń majątkowych wynikających bezpośrednio
z przestępstwa; sąd może również z urzędu orzec obowiązek naprawienia szkody.

Art. 95.
Rozprawę można odroczyć albo zarządzić w jej toku przerwę, jeżeli zachodzi ku temu potrzeba; z przebiegu
rozprawy sporządza się protokół.

Art. 96.
Obecność oskarżonego na rozprawie jest obowiązkowa w sprawach o zbrodnie; w pozostałych sprawach,
jeżeli oskarżony prawidłowo zawiadomiony nie stawia się bez usprawiedliwienia, sąd może prowadzić
rozprawę pod jego nieobecność (rozprawa zaoczna).

Art. 97.
Strona może żądać sprostowania protokołu, wskazując dostrzeżone nieścisłości i opuszczenia.

Art. 98.
1. Uzasadnienie wyroku sporządza się na wniosek strony złożony w terminie 7 dni od dnia ogłoszenia
wyroku.
2. Termin do wniesienia apelacji biegnie od dnia doręczenia wyroku wraz z uzasadnieniem.

                                             DZIAŁ VIII
                                 POSTĘPOWANIA SZCZEGÓLNE

Art. 99.
W sprawach o drobne przestępstwa sąd może wydać wyrok nakazowy bez przeprowadzania rozprawy;
wniesienie sprzeciwu powoduje rozpoznanie sprawy na zasadach ogólnych.

Art. 100.
Wobec sprawcy ujętego na gorącym uczynku lub bezpośrednio potem można stosować postępowanie
przyspieszone.

Art. 101.
Oskarżony może, w porozumieniu z oskarżycielem, wnieść o wydanie wyroku skazującego i wymierzenie
uzgodnionej kary bez przeprowadzania postępowania dowodowego (dobrowolne poddanie się karze);
wniosek zatwierdza sąd, jeżeli okoliczności czynu nie budzą wątpliwości.

Art. 102.
W sprawach z oskarżenia prywatnego rozprawę główną poprzedza posiedzenie pojednawcze.

Art. 103.
1. Jeżeli osobę prawomocnie skazano dwoma lub więcej wyrokami, a zachodzą warunki do orzeczenia kary
łącznej, sąd wydaje wyrok łączny.
2. Do wydania wyroku łącznego właściwy jest sąd, który wydał ostatni wyrok skazujący w pierwszej
instancji.

                                              DZIAŁ IX
                                POSTĘPOWANIE ODWOŁAWCZE

Art. 104.
Środkami odwoławczymi są apelacja od wyroków oraz zażalenie na postanowienia.

Art. 105.
1. Od wyroku sądu pierwszej instancji przysługuje apelacja do sądu apelacyjnego.
2. Apelację wnosi się w terminie i z zachowaniem wymogów określonych w ustawie.

Art. 106.
Sąd odwoławczy nie może orzec na niekorzyść oskarżonego, jeżeli środek odwoławczy wniesiono wyłącznie
na jego korzyść (zakaz reformationis in peius).

Art. 107.
Sąd apelacyjny utrzymuje zaskarżony wyrok w mocy, zmienia go albo uchyla i przekazuje sprawę do
ponownego rozpoznania.

Art. 108.
Od prawomocnego wyroku sądu apelacyjnego przysługuje kasacja do Sądu Najwyższego z powodu rażącego
naruszenia prawa mającego wpływ na treść orzeczenia.

Art. 109.
Kasacja przysługuje niezależnie od podstawy określonej w artykule poprzedzającym również wtedy, gdy:
    1) sąd apelacyjny skazał oskarżonego, który został uniewinniony w pierwszej instancji, albo wymierzył
    mu karę surowszą niż orzeczona w pierwszej instancji, w szczególności karę dożywotniego pozbawienia
    wolności;
    2) skazanemu na karę dożywotniego pozbawienia wolności albo karę pozbawienia wolności
    przekraczającą 10 lat przedstawiono istotne i wiarygodne dowody wskazujące na jego niewinność,
    sprzeczne z ustaleniami zaskarżonego wyroku.

Art. 110.
1. W przypadkach, o których mowa w art. poprzedzającym, Sąd Najwyższy rozpoznaje sprawę jako sąd
trzeciej instancji, badając nie tylko zgodność orzeczenia z prawem, lecz także jego zgodność z rzeczywistym
stanem rzeczy.
2. Sąd Najwyższy może w tym celu przeprowadzić lub zlecić przeprowadzenie dowodów wskazujących na
niewinność skazanego.

Art. 111.
Wniesienie kasacji, o której mowa w art. dotyczącym podstaw szczególnych, wstrzymuje wykonanie kary
dożywotniego pozbawienia wolności do czasu jej rozpoznania.

Art. 112.
Na postanowienia dotyczące w szczególności tymczasowego aresztowania oraz umorzenia postępowania
przysługuje zażalenie.

Art. 113.
Prawomocnie zakończone postępowanie wznawia się, jeżeli ujawnią się nowe fakty lub dowody nieznane
wcześniej, wskazujące na niewinność skazanego, albo gdy orzeczenie oparto na przestępstwie.

Art. 114.
Sąd odwoławczy rozpoznaje sprawę w granicach zaskarżenia oraz podniesionych zarzutów, a szerzej —
tylko w wypadkach wskazanych w ustawie.

Art. 115.
Niezależnie od granic zaskarżenia sąd uchyla orzeczenie, jeżeli zachodzi bezwzględna przyczyna
odwoławcza, w szczególności gdy w wydaniu orzeczenia brała udział osoba nieuprawniona, sąd był
nienależycie obsadzony albo oskarżony w wypadku obrony obligatoryjnej nie miał obrońcy.

